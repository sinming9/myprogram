# 2025년 3월 국민연금법 개정(2026년 1월 1일 시행)
#   · 보험료율 : 2026년 9.5% → 매년 0.5%p → 2033년 13%
#   · 소득대체율 : 41.5% → 43% (2026년 1월 이후 가입기간에만 적용)
#   · 2025년 12월 31일까지의 가입기간은 기존 규정을 그대로 씁니다.
#
# 연금액 산식 (공단 간단계산)
#   기본연금액(연) = 상수 × (A + B) × (1 + 0.05n/12)
#     A = 연금 수급 직전 3년간 전체 가입자 평균소득월액 (매년 공표)
#     B = 본인 가입기간 중 기준소득월액 평균
#     n = 20년(240개월)을 초과한 가입월수
#   상수는 가입 시기마다 다릅니다. 아래 표를 보세요.

A값_2026 = 3_193_511          # 2026년 적용 A값
보험료율_2026 = 0.095
소득대체율_2026 = 0.43

보험료율_표 = {2026: 0.095, 2027: 0.10, 2028: 0.105, 2029: 0.11,
            2030: 0.115, 2031: 0.12, 2032: 0.125, 2033: 0.13}


def 보험료율(연도: int) -> float:
    if 연도 < 2026:
        return 0.09
    return 보험료율_표.get(연도, 0.13)


def 상수(연도: int) -> float:
    """가입 연도별 연금액 산정 상수."""
    if 연도 <= 1998:
        return 2.4
    if 연도 <= 2007:
        return 1.8
    if 연도 <= 2025:
        # 2008년 1.5 에서 해마다 0.015 씩 낮아져 2025년 1.245
        return round(1.5 - 0.015 * (연도 - 2008), 4)
    return 1.29             # 2026년~ 개혁 적용


def 소득대체율(연도: int) -> float:
    """그 해 가입기간에 적용되는 소득대체율(%).

    ※ '상수 ÷ 3' 으로 구하면 안 됩니다. 그 관계는 2008년 이후에만 성립합니다.
      1988~1998년은 상수 2.4 인데 소득대체율은 70% 입니다.
    """
    if 연도 <= 1998:
        return 70.0
    if 연도 <= 2007:
        return 60.0
    if 연도 <= 2025:
        return round(50.0 - 0.5 * (연도 - 2008), 2)   # 2025년 41.5%
    return 43.0


def 국민연금_계산(가입시작: int, 가입종료: int, 평균소득월액: float,
              A값: float = A값_2026, 수급개시나이: int = 65,
              현재나이: int = None) -> dict:
    """가입 기간을 시기별로 나눠 상수를 다르게 적용합니다.

    가입시작·가입종료 : 연도 (예: 2005, 2045)
    평균소득월액       : 가입기간 중 평균 (B값). 현재 소득이 아닙니다.
    """
    가입종료 = max(가입종료, 가입시작)
    총개월 = (가입종료 - 가입시작 + 1) * 12
    if 총개월 <= 0:
        return {"오류": "가입기간이 없습니다"}

    # 시기별로 나눠 가중평균 상수를 구합니다
    가중합, 개월합 = 0.0, 0
    구간 = []
    for 연도 in range(가입시작, 가입종료 + 1):
        c = 상수(연도)
        가중합 += c * 12
        개월합 += 12
        if 구간 and abs(구간[-1]["상수"] - c) < 1e-9:
            구간[-1]["끝"] = 연도
            구간[-1]["개월"] += 12
        else:
            구간.append({"시작": 연도, "끝": 연도, "상수": c, "개월": 12})
    평균상수 = 가중합 / 개월합

    초과월 = max(총개월 - 240, 0)
    기본연금액_연 = 평균상수 * (A값 + 평균소득월액) * (1 + 0.05 * 초과월 / 12)
    월연금 = 기본연금액_연 / 12

    # 수급개시 연령에 따른 가감
    #  조기수령(최대 5년) 1년당 6% 감액 / 연기(최대 5년) 1년당 7.2% 증액
    기준나이 = 65
    차이 = 수급개시나이 - 기준나이
    if 차이 < 0:
        지급률 = 1 + 0.06 * 차이          # 조기: 감액
        비고 = f"조기수령 {-차이}년 → {abs(0.06 * 차이) * 100:.0f}% 감액"
    elif 차이 > 0:
        지급률 = 1 + 0.072 * min(차이, 5)
        비고 = f"연기수령 {min(차이, 5)}년 → {0.072 * min(차이, 5) * 100:.1f}% 증액"
    else:
        지급률 = 1.0
        비고 = "정상 수령 (65세)"

    return {
        "총가입월": 총개월,
        "총가입년": 총개월 / 12,
        "초과월": 초과월,
        "평균상수": 평균상수,
        "구간": 구간,
        "A값": A값,
        "B값": 평균소득월액,
        "지급률": 지급률,
        "지급률비고": 비고,
        "월연금_기본": 월연금,
        "월연금": 월연금 * 지급률,
        "연연금": 월연금 * 지급률 * 12,
        "소득대체율": (월연금 * 지급률 / 평균소득월액 * 100) if 평균소득월액 else 0.0,
    }


# ==========================================================================
# 적립식 자산의 미래가치 (퇴직연금 DC · 연금저축)
# ==========================================================================
def 미래가치(현재잔액: float, 연납입액: float, 연수: float,
          수익률: float) -> dict:
    """현재 잔액이 굴러가고, 매년 납입액이 더해집니다.

    연납입액은 연말에 넣는다고 봅니다(보수적).
    """
    r = 수익률 / 100
    n = max(연수, 0)
    원금성장 = 현재잔액 * ((1 + r) ** n)
    if abs(r) < 1e-9:
        납입성장 = 연납입액 * n
    else:
        납입성장 = 연납입액 * (((1 + r) ** n - 1) / r)
    총액 = 원금성장 + 납입성장
    총납입 = 현재잔액 + 연납입액 * n
    return {
        "현재잔액": 현재잔액,
        "연납입액": 연납입액,
        "연수": n,
        "수익률": 수익률,
        "원금성장": 원금성장,
        "납입성장": 납입성장,
        "총액": 총액,
        "총납입": 총납입,
        "운용수익": 총액 - 총납입,
    }


# ==========================================================================
# 목돈 → 월 연금 환산
# ==========================================================================
def 확정기간_월연금(잔액: float, 년수: int, 수익률: float) -> float:
    """정해진 기간 동안 나눠 받기. 받는 동안에도 남은 돈이 굴러갑니다.

    연금현가 공식의 역산입니다.
        월연금 = 잔액 x i / (1 - (1+i)^-N),  i = 월수익률, N = 총 개월수
    """
    N = 년수 * 12
    if N <= 0:
        return 0.0
    i = (수익률 / 100) / 12
    if abs(i) < 1e-12:
        return 잔액 / N
    return 잔액 * i / (1 - (1 + i) ** (-N))


# 통계청 생명표 기준 기대여명(년) 어림값.
#  ※ 종신형은 보험사 연금보험에서만 되고, 실제 지급액은 보험사의 경험생명표·
#    예정이율·사업비에 따라 달라집니다. 아래는 '대략 이 정도' 를 보는 용도입니다.
기대여명 = {
    (55, "남"): 27.5, (55, "여"): 32.8,
    (60, "남"): 23.0, (60, "여"): 28.0,
    (65, "남"): 19.0, (65, "여"): 23.6,
    (70, "남"): 15.2, (70, "여"): 19.3,
}


def 기대여명_찾기(나이: int, 성별: str = "남") -> float:
    후보 = sorted(기대여명, key=lambda k: abs(k[0] - 나이))
    for (a, s) in 후보:
        if s == 성별:
            # 5살 단위 표라 사이는 직선으로 보정
            return max(기대여명[(a, s)] - (나이 - a) * 0.85, 3.0)
    return 20.0


def 종신_월연금(잔액: float, 나이: int, 성별: str = "남",
            수익률: float = 2.5, 사업비율: float = 0.06) -> dict:
    """죽을 때까지 받기. 기대여명 동안 나눠 받는 것으로 어림합니다.

    사업비율 : 보험사 수수료·위험보험료 어림 (기본 6%)
    """
    여명 = 기대여명_찾기(나이, 성별)
    실질잔액 = 잔액 * (1 - 사업비율)
    월액 = 확정기간_월연금(실질잔액, int(round(여명)), 수익률)
    return {
        "기대여명": 여명,
        "차감후잔액": 실질잔액,
        "월연금": 월액,
        "사업비율": 사업비율,
    }


# ==========================================================================
# 물가 보정
# ==========================================================================
def 실질가치(명목금액: float, 연수: float, 물가상승률: float = 2.0) -> float:
    """미래의 명목 금액을 지금 돈 가치로 환산합니다."""
    return 명목금액 / ((1 + 물가상승률 / 100) ** max(연수, 0))


# ==========================================================================
# 세금 (연금 수령 시)
# ==========================================================================
#  연금저축·IRP·퇴직연금을 '연금' 으로 받으면 연금소득세가 붙습니다.
#    70세 미만 5.5% / 70~79세 4.4% / 80세 이상 3.3%
#  연간 연금수령액이 1,500만원을 넘으면 종합과세 또는 16.5% 분리과세 선택.
연금소득세율 = [(70, 0.055), (80, 0.044), (200, 0.033)]
종합과세_기준 = 15_000_000


def 연금소득세율_찾기(나이: int) -> float:
    for 상한, 세율 in 연금소득세율:
        if 나이 < 상한:
            return 세율
    return 0.033


def 세후_월연금(세전월액: float, 나이: int, 퇴직연금인가: bool = False) -> dict:
    """연금소득세를 뺀 실수령액.

    퇴직연금(퇴직금 재원)은 퇴직소득세의 30~40%를 감면받는 구조라
    실효세율이 더 낮습니다. 여기서는 3.3% 로 어림합니다.
    """
    연액 = 세전월액 * 12
    if 퇴직연금인가:
        세율 = 0.033
        비고 = "퇴직연금 재원 — 퇴직소득세 감면 적용 어림 3.3%"
    else:
        세율 = 연금소득세율_찾기(나이)
        비고 = f"연금소득세 {세율 * 100:.1f}% ({나이}세 기준)"
        if 연액 > 종합과세_기준:
            비고 += f" · 연 {종합과세_기준 / 1e4:,.0f}만원 초과분은 종합과세 또는 16.5% 선택"
    return {
        "세전월액": 세전월액,
        "세율": 세율,
        "세금": 세전월액 * 세율,
        "세후월액": 세전월액 * (1 - 세율),
        "비고": 비고,
    }
