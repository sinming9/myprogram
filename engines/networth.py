def 숫자_읽기(값) -> float:
    """한국식 표기의 숫자를 읽습니다. 못 읽으면 0."""
    if 값 is None:
        return 0.0
    if isinstance(값, (int, float)):
        return float(값)
    글자 = str(값).strip()
    if not 글자 or 글자 in ("-", "—", "–", "N/A", "nan"):
        return 0.0
    음수 = 글자.startswith("(") and 글자.endswith(")")
    if 음수:
        글자 = 글자[1:-1]
    for 지움 in ("원", "₩", ",", " ", "\u00a0"):
        글자 = 글자.replace(지움, "")
    글자 = 글자.replace("%", "")
    if 글자.startswith("-"):
        음수 = True
        글자 = 글자[1:]
    try:
        v = float(글자)
    except ValueError:
        return 0.0
    return -v if 음수 else v


def 날짜_읽기(값):
    """2026-07-31 / 2026.07.31 / 2026/7/31 등을 date 로."""
    if isinstance(값, date):
        return 값
    글자 = str(값 or "").strip()
    if not 글자:
        return None
    글자 = 글자.replace(".", "-").replace("/", "-").replace(" ", "")
    글자 = 글자.rstrip("-")
    조각 = [c for c in 글자.split("-") if c]
    if len(조각) < 2:
        return None
    try:
        연 = int(조각[0])
        월 = int(조각[1])
        일 = int(조각[2]) if len(조각) > 2 else 1
        return date(연, 월, 일)
    except (ValueError, TypeError):
        return None


def 붙여넣기_읽기(텍스트: str) -> tuple:
    """엑셀에서 복사한 표를 [{날짜, 순자산, 순납입액, 메모}] 로.

    (기록목록, 경고목록) 을 돌려줍니다.
    첫 줄에 '기준월' '순자산' 같은 머리글이 있으면 그 위치를 찾아 쓰고,
    없으면 첫 열을 날짜, 그 다음 숫자 열을 순자산으로 봅니다.
    """
    경고 = []
    줄들 = [l for l in str(텍스트 or "").splitlines() if l.strip()]
    if not 줄들:
        return [], ["붙여넣은 내용이 없습니다."]

    def 쪼개기(줄):
        칸 = 줄.split("\t")
        if len(칸) == 1:
            칸 = [c for c in 줄.split(",")]
        return [c.strip() for c in 칸]

    표 = [쪼개기(l) for l in 줄들]

    # 머리글 찾기
    머리 = None
    시작 = 0
    for i, 행 in enumerate(표[:5]):
        붙임 = "".join(행)
        if any(k in 붙임 for k in ("순자산", "기준월", "총자산", "날짜")):
            머리 = 행
            시작 = i + 1
            break

    열번호 = {}
    if 머리:
        for j, 이름 in enumerate(머리):
            깨끗 = 이름.replace(" ", "")
            for 별칭, 표준 in _별칭.items():
                if 깨끗 == 별칭 or 깨끗.startswith(별칭):
                    열번호.setdefault(표준, j)
    if "날짜" not in 열번호:
        열번호["날짜"] = 0
        if 머리:
            경고.append("날짜 열을 못 찾아 첫 번째 열을 날짜로 봤습니다.")

    기록 = []
    건너뜀 = 0
    for 행 in 표[시작:]:
        if not 행 or all(not c for c in 행):
            continue
        d = 날짜_읽기(행[열번호["날짜"]] if 열번호["날짜"] < len(행) else "")
        if d is None:
            건너뜀 += 1
            continue

        if "순자산" in 열번호 and 열번호["순자산"] < len(행):
            순 = 숫자_읽기(행[열번호["순자산"]])
        else:
            # 머리글이 없으면 날짜 뒤의 '가장 큰 숫자' 를 순자산으로 봅니다
            숫자들 = [숫자_읽기(c) for c in 행[열번호["날짜"] + 1:]]
            순 = max(숫자들) if 숫자들 else 0.0
            if not 열번호.get("_추정안내"):
                경고.append("순자산 열을 못 찾아 각 줄에서 가장 큰 값을 썼습니다. "
                          "결과를 확인해 주세요.")
                열번호["_추정안내"] = True

        if 순 == 0:
            건너뜀 += 1
            continue

        기록.append({
            "날짜": d.isoformat(),
            "순자산": 순,
            "순납입액": (숫자_읽기(행[열번호["순납입액"]])
                    if "순납입액" in 열번호 and 열번호["순납입액"] < len(행) else 0.0),
            "메모": (str(행[열번호["메모"]]) if "메모" in 열번호
                   and 열번호["메모"] < len(행) else ""),
        })

    if 건너뜀:
        경고.append(f"{건너뜀}줄은 날짜나 금액을 읽지 못해 건너뛰었습니다.")
    if not 기록:
        경고.append("읽어낸 줄이 없습니다. 머리글 행까지 함께 복사했는지 확인해 주세요.")

    기록.sort(key=lambda r: r["날짜"])
    return 기록, 경고
