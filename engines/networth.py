#  엑셀에서 범위를 복사하면 '탭으로 구분된 텍스트' 가 클립보드에 담깁니다.
#  그걸 그대로 받아서 표로 바꿉니다.
#
#  한국식 숫자 표기를 모두 처리합니다.
#     "1,151,059,235원"        →  1151059235
#     "(355,166,297원)"        →  -355166297   (괄호는 음수)
#     "-355,166,297원"         →  -355166297
#     "₩ 144,399"              →  144399
