def 만기_남은일(만기일, 오늘: date = None):
    """만기까지 남은 일수. 만기일이 없으면 None."""
    if not 만기일:
        return None
    try:
        d = 만기일 if isinstance(만기일, date) else date.fromisoformat(str(만기일)[:10])
    except Exception:  # noqa: BLE001
        return None
    return (d - (오늘 or date.today())).days


def 만기_표시(만기일, 오늘: date = None) -> str:
    """D-58 / 오늘 / 지남 형태로."""
    남은 = 만기_남은일(만기일, 오늘)
    if 남은 is None:
        return ""
    if 남은 < 0:
        return f"지남 ({-남은}일)"
    if 남은 == 0:
        return "오늘"
    return f"D-{남은}"


def 만기_급함(만기일, 기준일수: int = 90, 오늘: date = None) -> bool:
    남은 = 만기_남은일(만기일, 오늘)
    return 남은 is not None and 0 <= 남은 <= 기준일수


