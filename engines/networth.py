def 순자산_계산(투자자산: float, 부동산: float, 대출잔액: float,
             기타자산: dict = None, 기타부채: dict = None) -> dict:
    기타자산 = 기타자산 or {}
    기타부채 = 기타부채 or {}
    기타자산합 = sum(float(v or 0) for v in 기타자산.values())
    기타부채합 = sum(float(v or 0) for v in 기타부채.values())

    총자산 = float(투자자산) + float(부동산) + 기타자산합
