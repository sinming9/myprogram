def 지분_비었나(값) -> bool:
    """지분 칸을 '안 적은' 것인지. 0 을 적은 것과 구별해야 합니다.

    ※ 이걸 구별하지 않으면 0 을 적어도 '안 적었다' 로 보고 반반(50%)으로
      바꿔버립니다. "이 대출은 전부 가족 몫" 이라는 뜻으로 0 을 적었는데
      절반이 내 부채로 잡히면 순자산이 그만큼 틀립니다.
      (표에서 지운 칸은 NaN 으로 들어옵니다)
    """
    if 값 is None:
        return True
    if isinstance(값, float) and 값 != 값:        # NaN
        return True
    return str(값).strip() in ("", "-", "—", "–", "None", "nan", "N/A")


def 내지분_비율(소유자, 내지분=None) -> float:
    """개인 기준에 반영할 비율 (0.0 ~ 1.0).

    지분율은 '내가 가진 몫' 입니다. 부부 공동명의 5:5 면 50 을 넣습니다.
      · 0 을 적었으면 0% 로 봅니다 (= 전부 가족 몫)
      · 아예 안 적었으면 반반(50%)으로 봅니다
    """
    s = str(소유자 or "본인").strip()
    if s == "배우자":
        return 0.0
    if s == "공동":
        if 지분_비었나(내지분):
            return 0.5
        v = 숫자_읽기(내지분)
        return min(max(v, 0.0), 100.0) / 100.0
    return 1.0


def 행_정리(행: dict):
    """표 한 줄을 표준 형태로. 금액이 0이면 (아직 안 채운 줄) None.

    부채는 **구분을 '부채' 로 두고 금액은 양수**로 넣습니다.
    빼기는 이 함수 밖(표_집계)에서 처리하므로, 음수를 넣으면 부호가
    두 번 뒤집혀 엉뚱해집니다. 그래서 금액은 절댓값으로 받습니다.
    """
    항목 = str(행.get("항목") or "").strip()
    구분 = str(행.get("구분") or "").strip()
    금액 = 숫자_읽기(행.get("금액"))
    if 금액 == 0:
        return None
    if 구분 not in 대분류_목록:
        구분 = 대분류_찾기(항목)

    소유자 = str(행.get("소유자") or "본인").strip()
    if 소유자 not in 소유자_목록:
        소유자 = "본인"
    비율 = 내지분_비율(소유자, 행.get("내 지분(%)"))
    금액 = abs(금액)

    return {
        "구분": 구분,
        "항목": 항목 or 구분,
        "금액": 금액,
        "소유자": 소유자,
        "내 지분(%)": round(비율 * 100, 1),
        "내비율": 비율,
        "부채": 구분 == "부채",
        "내몫": 금액 * 비율,
        "가족몫": 금액 * (1 - 비율),
        "만기일": 행.get("만기일"),
        "메모": str(행.get("메모") or ""),
    }


def _기준(자산: float, 부채: float) -> dict:
    return {
        "총자산": 자산, "총부채": 부채, "순자산": 자산 - 부채,
        "부채비율": (부채 / 자산 * 100) if 자산 else 0.0,
    }


def 표_집계(행들: list) -> dict:
    """소유자 태그가 붙은 자산·부채 표를 개인 / 가족 / 가구 세 기준으로 집계.

    돌려주는 것
      개인·가족·가구 : {총자산, 총부채, 순자산, 부채비율}
      소유자별       : {본인/배우자/공동: {자산, 부채, 순자산}}  (전액 기준)
      대분류별       : [{구분, 가구, 개인, 가족}] — 대분류_목록 순서
      행들           : 금액이 채워진 줄만 정리한 것
    """
    개인자산 = 개인부채 = 가구자산 = 가구부채 = 0.0
    소유자별 = {s: {"자산": 0.0, "부채": 0.0} for s in 소유자_목록}
    묶음 = {c: {"가구": 0.0, "개인": 0.0} for c in 대분류_목록}
    정리 = []

    for 원행 in (행들 or []):
        r = 행_정리(원행)
        if r is None:
            continue
        정리.append(r)
        칸 = 묶음.setdefault(r["구분"], {"가구": 0.0, "개인": 0.0})
        칸["가구"] += r["금액"]
        칸["개인"] += r["내몫"]
        쪽 = 소유자별.setdefault(r["소유자"], {"자산": 0.0, "부채": 0.0})
        if r["부채"]:
            가구부채 += r["금액"]
            개인부채 += r["내몫"]
            쪽["부채"] += r["금액"]
        else:
            가구자산 += r["금액"]
            개인자산 += r["내몫"]
            쪽["자산"] += r["금액"]

    for 쪽 in 소유자별.values():
        쪽["순자산"] = 쪽["자산"] - 쪽["부채"]

    개인 = _기준(개인자산, 개인부채)
    가구 = _기준(가구자산, 가구부채)
    가족 = _기준(가구자산 - 개인자산, 가구부채 - 개인부채)

    대분류별 = [{"구분": c,
               "가구": 묶음[c]["가구"],
               "개인": 묶음[c]["개인"],
               "가족": 묶음[c]["가구"] - 묶음[c]["개인"]}
              for c in 대분류_목록 if 묶음.get(c, {}).get("가구")]

    return {
        "행들": 정리, "쓴줄수": len(정리),
        "개인": 개인, "가족": 가족, "가구": 가구,
        "소유자별": 소유자별, "대분류별": 대분류별,
    }


def 지분_어긋남(집계: dict, 여유_퍼센트포인트: float = 15.0):
    """부동산과 부채의 '내 몫 비중' 이 크게 어긋나면 알려줍니다.

    집은 내 몫 60% 인데 그 집에 걸린 주택담보대출을 0% 로 두면,
    **대출 없는 집을 60% 가진 셈**이 되어 내 몫이 부풀려집니다.
    반대로 집은 0% 인데 대출만 내 몫으로 두면 내 몫이 실제보다 작게 나옵니다.

    자산과 부채는 같은 지분으로 나눠야 짝이 맞습니다. 명의가 정말 한쪽
    단독이라면 집도 대출도 같은 소유자로 두는 것이 맞습니다.

    (부동산·부채 어느 한쪽이라도 없으면 비교하지 않고 None)
    """
    묶음 = {d["구분"]: d for d in (집계 or {}).get("대분류별") or []}
    집 = 묶음.get("부동산")
    빚 = 묶음.get("부채")
    if not 집 or not 빚 or not 집.get("가구") or not 빚.get("가구"):
        return None

    집비중 = 집["개인"] / 집["가구"] * 100
    빚비중 = 빚["개인"] / 빚["가구"] * 100
    차이 = 집비중 - 빚비중
    if abs(차이) < 여유_퍼센트포인트:
        return None
    return {
        "부동산비중": 집비중,
        "부채비중": 빚비중,
        "차이": 차이,
        # + 면 집을 더 많이 갖고 빚은 덜 진 것으로 잡힘 = 내 몫 부풀려짐
        "방향": "부풀려짐" if 차이 > 0 else "작게 나옴",
    }


