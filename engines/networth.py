# 증감 속도
# ==========================================================================
#  기록 한 줄 = (날짜, 순자산, 그 기간에 새로 넣은 돈)
#
#  "작년보다 20% 늘었다" 는 실력인지 장세인지 알 수 없습니다.
#  월급을 넣어서 늘어난 것과 주가가 올라서 늘어난 것을 나눠 봅니다.
#
#    총증감  = 이번 순자산 − 지난 순자산
#    저축기여 = 그 기간에 새로 넣은 돈 (순납입액)
#    시장기여 = 총증감 − 저축기여
#
#  수익률은 Modified Dietz 방식으로 어림합니다.
#  (기간 중간에 넣었다고 가정 → 분모에 순납입액의 절반을 더함)

def 구간_분석(이전: dict, 현재: dict) -> dict:
    d1 = _날짜(이전["날짜"])
    d2 = _날짜(현재["날짜"])
    일수 = max((d2 - d1).days, 1)
    년 = 일수 / 365.25

    시작 = float(이전["순자산"])
    끝 = float(현재["순자산"])
    납입 = float(현재.get("순납입액") or 0)

    총증감 = 끝 - 시작
    시장기여 = 총증감 - 납입

    분모 = 시작 + 납입 / 2
    수익률 = (시장기여 / 분모 * 100) if 분모 > 0 else 0.0
    연환산수익률 = ((1 + 수익률 / 100) ** (1 / 년) - 1) * 100 if 년 > 0 and 분모 > 0 else 0.0

    성장률 = ((끝 / 시작) - 1) * 100 if 시작 > 0 else 0.0
    cagr = (((끝 / 시작) ** (1 / 년) - 1) * 100) if (시작 > 0 and 끝 > 0 and 년 > 0) else 0.0

    return {
        "시작일": d1, "종료일": d2, "일수": 일수, "년": 년,
        "시작": 시작, "끝": 끝,
        "총증감": 총증감, "저축기여": 납입, "시장기여": 시장기여,
        "성장률": 성장률, "CAGR": cagr,
        "수익률": 수익률, "연환산수익률": 연환산수익률,
        "저축비중": (납입 / 총증감 * 100) if 총증감 else 0.0,
    }


def _날짜(v):
    if isinstance(v, date):
        return v
    return date.fromisoformat(str(v)[:10])


def 추이_분석(기록: list) -> dict:
    """[{날짜, 순자산, 순납입액}] 을 시간순으로 훑어 요약합니다."""
    정렬 = sorted([r for r in 기록 if r.get("날짜") and r.get("순자산") is not None],
                key=lambda r: _날짜(r["날짜"]))
    if len(정렬) < 2:
        return {"구간들": [], "충분": False, "기록수": len(정렬)}

    구간들 = [구간_분석(정렬[i], 정렬[i + 1]) for i in range(len(정렬) - 1)]
    전체 = 구간_분석(정렬[0], {
        "날짜": 정렬[-1]["날짜"], "순자산": 정렬[-1]["순자산"],
        "순납입액": sum(float(r.get("순납입액") or 0) for r in 정렬[1:]),
    })

    cagr = 전체["CAGR"]
    배가 = (math.log(2) / math.log(1 + cagr / 100)) if cagr > 0 else None

    return {
        "구간들": 구간들,
        "전체": 전체,
        "충분": True,
        "기록수": len(정렬),
        "배가기간": 배가,
        "처음": 정렬[0],
        "마지막": 정렬[-1],
    }


def 소득대비_축적(전체구간: dict, 연봉: float) -> dict:
    """연봉 대비 순자산이 얼마나 빨리 쌓이는지.

    ※ 예전에는 '저축률' 을 계산했는데, 그러려면 기간별 순납입액을 알아야
      합니다. 정확히 알기 어려운 값이라 입력에서 빼면서 이 함수도
      **순자산 증가분 기준**으로 바꿨습니다.

      '연간증가/연봉' 은 저축률이 아닙니다. 시장 수익까지 포함된 값이라
      저축률보다 높게 나오는 게 정상입니다. 100%를 넘을 수도 있습니다.
    """
    if not 연봉 or 연봉 <= 0 or not 전체구간:
        return {}
    년 = 전체구간["년"] or 1
    연간증가 = 전체구간["총증감"] / 년
    return {
        "연간증가": 연간증가,
        "연봉대비": 연간증가 / 연봉 * 100,
        "연봉배수": 전체구간["끝"] / 연봉 if 연봉 else 0,
    }


