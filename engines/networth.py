def 백분위(순자산: float) -> dict:
    """순자산 → 상위 몇 %. (추정치)"""
    v = float(순자산)
    if v <= _앵커[0][0]:
        상위 = 99.0
    elif v >= _앵커[-1][0]:
        상위 = _앵커[-1][1]
    else:
        상위 = _앵커[-1][1]
        for i in range(len(_앵커) - 1):
            x1, y1 = _앵커[i]
            x2, y2 = _앵커[i + 1]
            if x1 <= v <= x2:
                # 자산은 로그 스케일이 자연스럽습니다
                l1 = math.log(max(x1, 1_000_000))
                l2 = math.log(max(x2, 1_000_000))
                lv = math.log(max(v, 1_000_000))
                비율 = (lv - l1) / (l2 - l1) if l2 > l1 else 0
                상위 = y1 + (y2 - y1) * 비율
                break
    상위 = min(max(상위, 0.05), 99.5)
    return {
        "순자산": v,
        "상위": 상위,
        "하위": 100 - 상위,
        "평균대비": (v / 가구평균_순자산 * 100) if 가구평균_순자산 else 0,
        "정확도": _정확도(v),
    }


def _정확도(v: float) -> str:
    """공표값 근처인지 알려줍니다. 멀수록 추정 오차가 큽니다."""
    가까운 = min(_앵커, key=lambda a: abs(math.log(max(a[0], 1e6))
                                      - math.log(max(v, 1e6))))
    차이 = abs(가까운[0] - v) / max(가까운[0], 1)
    if 차이 < 0.15:
        return "공표값 근처 — 비교적 정확"
    if 차이 < 0.5:
        return "보간 추정"
    return "보간 추정 (오차 클 수 있음)"


