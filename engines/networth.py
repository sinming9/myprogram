#  [왜 나눠야 하는가]
#
#  가계금융복지조사는 **가구 단위** 통계입니다. 전국 비교는 가구 기준으로
#  해야 맞습니다. 그런데 "내가 실제로 가진 게 얼마인가" 는 가구 합계가
#  아니라 내 몫입니다. 두 값은 다르고, 둘 다 필요합니다.
#
#  예전 방식은 '배우자 자산' 을 숫자 한 칸으로만 받았습니다. 그래서
#    · 배우자 돈이 예금인지 부동산인지 알 수 없었고
#    · 부부 공동명의 집을 어느 쪽에 넣어야 할지 정할 수 없었고
#    · 대분류별로 볼 때 내 것과 가족 것이 뒤섞였습니다.
#
#  그래서 **줄마다 소유자를 붙이는 방식**으로 바꿨습니다.
#
#      소유자 = 본인    → 개인 100% · 가구 100%
#      소유자 = 배우자  → 개인   0% · 가구 100%
#      소유자 = 공동    → 개인 지분% · 가구 100%
#
#  세 가지 값이 나옵니다.
#      가구 = 모든 줄 전액             (전국 비교에 쓰는 값)
#      개인 = 본인 전액 + 공동 지분분   (내 몫)
#      가족 = 가구 − 개인              (배우자 전액 + 공동 나머지)
#
#  '공동' 의 지분은 등기 지분율을 그대로 넣으시면 됩니다. 60:40 처럼
#  반반이 아닌 경우도 정확히 반영됩니다. 안 적으면 반반(50%)으로 봅니다.

