ISA_의무기간_년 = 3
ISA_분리과세율 = 0.099
일반계좌_배당세율 = 0.154


def ISA_현황(가입일: date, 총납입액: float, 올해납입액: float,
           순이익: float, 유형: str = "일반형", 제도: str = "현행",
           오늘: date = None) -> dict:
    """ISA 만기·납입한도·비과세 소진 현황과 절세액을 계산합니다."""
    오늘 = 오늘 or date.today()
    설정 = ISA_제도.get(제도, ISA_제도["현행"])

    만기일 = date(가입일.year + ISA_의무기간_년, 가입일.month,
               min(가입일.day, 28))
    남은일 = (만기일 - 오늘).days
    채움 = 남은일 <= 0

    비과세한도 = (설정["비과세_서민"] if 유형.startswith("서민")
              else 설정["비과세_일반"])
    비과세분 = min(max(순이익, 0.0), 비과세한도)
    초과분 = max(순이익 - 비과세한도, 0.0)
    ISA세금 = 초과분 * ISA_분리과세율
    일반세금 = max(순이익, 0.0) * 일반계좌_배당세율
    절세액 = 일반세금 - ISA세금

    return {
        "가입일": 가입일, "만기일": 만기일,
        "의무기간_충족": 채움,
        "남은일": max(남은일, 0),
        "경과일": (오늘 - 가입일).days,
        "진행률": min((오늘 - 가입일).days / max((만기일 - 가입일).days, 1) * 100, 100),
        "제도": 설정["이름"],
        "유형": 유형,
        "비과세한도": 비과세한도,
        "비과세사용": 비과세분,
        "비과세잔여": max(비과세한도 - 비과세분, 0.0),
        "비과세소진률": (비과세분 / 비과세한도 * 100) if 비과세한도 else 0.0,
        "과세대상": 초과분,
        "ISA세금": ISA세금,
        "일반계좌세금": 일반세금,
        "절세액": 절세액,
        "연납입한도": 설정["연납입한도"],
        "연납입잔여": max(설정["연납입한도"] - 올해납입액, 0.0),
        "총납입한도": 설정["총납입한도"],
        "총납입잔여": max(설정["총납입한도"] - 총납입액, 0.0),
        "총소진률": (총납입액 / 설정["총납입한도"] * 100) if 설정["총납입한도"] else 0.0,
    }
