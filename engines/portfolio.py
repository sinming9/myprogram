def 갱신_필요한가(행: dict, 기준일수: int = 30, 오늘: date = None) -> tuple:
    """직접 입력한 평가액이 오래됐는지. (오래됨?, 경과일) 반환.

    펀드·TDF·정기예금은 자동 조회가 안 되니 직접 넣어야 하는데,
    언제 넣은 값인지 잊어버리기 쉽습니다. 갱신일을 같이 적어두면
    오래된 값으로 자산배분을 보는 일을 막을 수 있습니다.
    """
    if not 행.get("평가액(직접입력)"):
        return False, None
    갱신 = 행.get("갱신일")
    if not 갱신:
        return True, None
    try:
        d = 갱신 if isinstance(갱신, date) else date.fromisoformat(str(갱신)[:10])
    except Exception:  # noqa: BLE001
        return True, None
    경과 = ((오늘 or date.today()) - d).days
    return 경과 > 기준일수, 경과


