def 금액표시(값, 시장: str, 소수=None) -> str:
    """해외주식은 달러, 나머지는 원화로 표시합니다."""
    try:
        v = float(값)
    except (TypeError, ValueError):
        return "-"
    if 시장 == "US":
        자릿수 = 2 if 소수 is None else 소수
        return f"${v:,.{자릿수}f}"
    자릿수 = 0 if 소수 is None else 소수
    return f"{v:,.{자릿수}f}원"


def 종목_계산(행: dict, 시세: dict, 환율: float) -> dict:
    """한 종목의 원화 환산 평가액·손익·배당을 계산합니다.

    ※ 퇴직연금(DC)·IRP 의 TDF·펀드·정기예금처럼 티커가 없는 상품은
      '평가액(직접입력)' 에 현재 평가금액을 넣으면 그 값을 그대로 씁니다.
      이때 수량은 1, 평균단가에 투자원금을 넣으면 손익도 나옵니다.
    """
    수량 = float(행.get("수량") or 0)
    평단 = float(행.get("평균단가") or 0)
    시장 = 행.get("시장") or "KR"
    직접평가 = 행.get("평가액(직접입력)")

    if 시장 == "COIN":
        # ★ 코인은 입력값(평균단가·현재가 수동)을 모두 '원화' 기준으로 봅니다.
        #   업비트에서 받으면 이미 원화, 야후에서 받으면 달러라 환율을 곱해
        #   원화로 맞춘 뒤 씁니다. 그래야 평균단가와 단위가 어긋나지 않습니다.
        #   (예전에는 조회 실패 시 수동 입력한 원화에 환율을 또 곱해
        #    평가액이 1,390배로 부풀었습니다)
        현재가 = None
        if 시세 and 시세.get("현재가"):
            현재가 = float(시세["현재가"]) * (1.0 if 시세.get("원화표시") else 환율)
        if not 현재가:
            현재가 = float(행.get("현재가(수동)") or 0) or 평단
        배수 = 1.0
    else:
        배수 = 환율 if 시장 == "US" else 1.0
        현재가 = 시세.get("현재가") if 시세 else None
        if not 현재가:
            현재가 = float(행.get("현재가(수동)") or 0) or 평단

    # 현지 통화 기준 (해외주식은 달러, 국내·코인은 원화)
    if 직접평가:
        현지평가 = float(직접평가)
    else:
        현지평가 = 수량 * 현재가
    현지원금 = 수량 * 평단

    # 원화 환산 (비중·합계 계산용)
    평가액 = 현지평가 * 배수
    원금 = 현지원금 * 배수
    주당배당 = 행.get("주당배당(수동)")
    if 주당배당 in (None, "", 0):
        주당배당 = (시세 or {}).get("주당배당_1년", 0.0)
    연배당 = 수량 * float(주당배당 or 0) * 배수

    return {
        **행,
        "현재가": 현재가,
        "통화": 통화기호(시장),
        "현지평가액": 현지평가,
        "현지원금": 현지원금,
        "평가액": 평가액,
        "원금": 원금,
        "손익": 평가액 - 원금,
        "수익률": ((평가액 / 원금 - 1) * 100) if 원금 else 0.0,
        "연배당": 연배당,
        "현지연배당": 수량 * float(주당배당 or 0),
        "배당수익률": (연배당 / 평가액 * 100) if 평가액 else 0.0,
        "52주위치": (시세 or {}).get("52주위치"),
        "이평60": (시세 or {}).get("이평60"),
        "배당월별": (시세 or {}).get("배당월별") or {},
        "조회성공": bool(시세),
        "직접입력": bool(직접평가),
        "시세출처": (시세 or {}).get("출처"),
    }


def 집계(종목들: list, 기준: str) -> list:
    """기준(계좌/자산군/시장/종류)별로 평가액·손익·배당을 합칩니다."""
    묶음 = {}
    for s in 종목들:
        키 = s.get(기준) or "미분류"
        칸 = 묶음.setdefault(키, {"이름": 키, "평가액": 0.0, "원금": 0.0,
                               "연배당": 0.0, "종목수": 0})
        칸["평가액"] += s["평가액"]
        칸["원금"] += s["원금"]
        칸["연배당"] += s["연배당"]
        칸["종목수"] += 1

    전체 = sum(v["평가액"] for v in 묶음.values()) or 1.0
    출력 = []
    for v in 묶음.values():
        v["비중"] = v["평가액"] / 전체 * 100
        v["손익"] = v["평가액"] - v["원금"]
        v["수익률"] = ((v["평가액"] / v["원금"] - 1) * 100) if v["원금"] else 0.0
        출력.append(v)
    return sorted(출력, key=lambda x: -x["평가액"])


