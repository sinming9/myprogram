def 자산군_짐작(이름: str, 티커: str = "") -> str:
    """이름과 티커로 자산군을 짐작합니다. 모르면 빈 문자열.

    이름은 부분 일치, 티커는 완전 일치로 봅니다.
    """
    본이름 = str(이름 or "")
    위이름 = 본이름.upper()
    본티커 = str(티커 or "").strip().upper()
    for 자산군, 규칙 in _힌트:
        if 본티커 and 본티커 in 규칙["심볼"]:
            return 자산군
        if any(w in 위이름 or w in 본이름 for w in 규칙["단어"]):
            return 자산군
    return ""


def 자산군_확인필요(종목들: list) -> list:
    """자산군 태그가 이름과 어긋나 보이는 종목.

    [{이름, 현재, 짐작}] 을 돌려줍니다. 자동 수정은 하지 않습니다.
    """
    출력 = []
    본것 = set()
    for s in 종목들:
        이름 = str(s.get("이름") or "")
        현재 = s.get("자산군") or ""
        짐작 = 자산군_짐작(이름, s.get("티커"))
        열쇠 = (이름, 현재)
        if 짐작 and 현재 and 짐작 != 현재 and 열쇠 not in 본것:
            본것.add(열쇠)
            출력.append({"이름": 이름, "현재": 현재, "짐작": 짐작})
    return 출력


