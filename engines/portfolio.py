def 야후티커(티커: str, 시장: str) -> list:
    """조회에 쓸 야후 티커 후보들."""
    t = str(티커).strip().upper()
    if 시장 == "US":
        return [t]
    if t.isdigit() and len(t) == 6:
        return [f"{t}.KS", f"{t}.KQ"]      # 코스피 먼저, 실패하면 코스닥
    return [t]


def _야후_조회(티커: str, 기간="1y", 시간제한=15) -> dict:
    url = (f"https://query1.finance.yahoo.com/v8/finance/chart/"
           f"{urllib.parse.quote(티커)}?range={기간}&interval=1d&events=div")
    요청 = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(요청, timeout=시간제한) as resp:
        js = json.loads(resp.read().decode("utf-8"))
    결과 = (js.get("chart") or {}).get("result")
    if not 결과:
        raise ValueError("응답에 데이터가 없습니다")
    return 결과[0]


def 시세_조회(티커: str, 시장: str) -> dict:
    """현재가·52주 고저·이동평균·최근 1년 배당 합계.

    실패하면 예외를 던집니다. 부르는 쪽에서 감싸주세요.
    """
    오류 = []
    for 후보 in 야후티커(티커, 시장):
        try:
            데이터 = _야후_조회(후보)
        except Exception as e:  # noqa: BLE001
            오류.append(f"{후보}: {e}")
            continue

        종가들 = [v for v in
                (데이터["indicators"]["quote"][0].get("close") or []) if v is not None]
        if not 종가들:
            오류.append(f"{후보}: 종가 없음")
            continue

        메타 = 데이터.get("meta", {})
        현재가 = float(메타.get("regularMarketPrice") or 종가들[-1])
        고 = float(메타.get("fiftyTwoWeekHigh") or max(종가들))
        저 = float(메타.get("fiftyTwoWeekLow") or min(종가들))

        # 최근 1년 배당 — 합계와 '월별' 내역을 함께 만듭니다 (배당 달력용)
        배당 = 0.0
        배당횟수 = 0
        월별 = {}
        한해전 = (datetime.now() - timedelta(days=365)).timestamp()
        for 항목 in ((데이터.get("events") or {}).get("dividends") or {}).values():
            초 = 항목.get("date", 0)
            if 초 >= 한해전:
                금액 = float(항목.get("amount", 0))
                배당 += 금액
                배당횟수 += 1
                달 = datetime.fromtimestamp(초).month
                월별[달] = 월별.get(달, 0.0) + 금액

        def 이평(n):
            구간 = 종가들[-n:]
            return sum(구간) / len(구간) if 구간 else 현재가

        위치 = ((현재가 - 저) / (고 - 저) * 100) if 고 > 저 else 50.0
        return {
            "티커": 후보,
            "현재가": 현재가,
            "통화": 메타.get("currency", "USD" if 시장 == "US" else "KRW"),
            "52주고": 고, "52주저": 저, "52주위치": 위치,
            "이평20": 이평(20), "이평60": 이평(60), "이평120": 이평(120),
            "주당배당_1년": 배당, "배당횟수": 배당횟수, "배당월별": 월별,
        }
    raise RuntimeError(" / ".join(오류))


def 환율_조회(시간제한=15) -> float:
    """USD/KRW. 실패하면 예외."""
    데이터 = _야후_조회("KRW=X", 기간="5d", 시간제한=시간제한)
    메타 = 데이터.get("meta", {})
    값 = 메타.get("regularMarketPrice")
    if 값:
        return float(값)
    종가들 = [v for v in (데이터["indicators"]["quote"][0].get("close") or [])
           if v is not None]
    if not 종가들:
        raise ValueError("환율 종가를 찾지 못했습니다")
    return float(종가들[-1])


