def 종목_계산(행: dict, 시세: dict, 환율: float) -> dict:
    """한 종목의 원화 환산 평가액·손익·배당을 계산합니다."""
    수량 = float(행.get("수량") or 0)
    평단 = float(행.get("평균단가") or 0)
    시장 = 행.get("시장") or "KR"
    배수 = 환율 if 시장 == "US" else 1.0

    현재가 = 시세.get("현재가") if 시세 else None
    if not 현재가:
        현재가 = float(행.get("현재가(수동)") or 0) or 평단

    평가액 = 수량 * 현재가 * 배수
    원금 = 수량 * 평단 * 배수
    주당배당 = 행.get("주당배당(수동)")
    if 주당배당 in (None, "", 0):
        주당배당 = (시세 or {}).get("주당배당_1년", 0.0)
    연배당 = 수량 * float(주당배당 or 0) * 배수

    return {
        **행,
        "현재가": 현재가,
        "평가액": 평가액,
        "원금": 원금,
        "손익": 평가액 - 원금,
        "수익률": ((평가액 / 원금 - 1) * 100) if 원금 else 0.0,
        "연배당": 연배당,
        "배당수익률": (연배당 / 평가액 * 100) if 평가액 else 0.0,
        "52주위치": (시세 or {}).get("52주위치"),
        "이평60": (시세 or {}).get("이평60"),
        "배당월별": (시세 or {}).get("배당월별") or {},
        "조회성공": bool(시세),
    }


def 집계(종목들: list, 기준: str) -> list:
    """기준(계좌/자산군/시장/종류)별로 평가액·손익·배당을 합칩니다."""
    묶음 = {}
    for s in 종목들:
        키 = s.get(기준) or "미분류"
        칸 = 묶음.setdefault(키, {"이름": 키, "평가액": 0.0, "원금": 0.0,
                               "연배당": 0.0, "종목수": 0})
        칸["평가액"] += s["평가액"]
        칸["원금"] += s["원금"]
        칸["연배당"] += s["연배당"]
        칸["종목수"] += 1

    전체 = sum(v["평가액"] for v in 묶음.values()) or 1.0
    출력 = []
    for v in 묶음.values():
        v["비중"] = v["평가액"] / 전체 * 100
        v["손익"] = v["평가액"] - v["원금"]
        v["수익률"] = ((v["평가액"] / v["원금"] - 1) * 100) if v["원금"] else 0.0
        출력.append(v)
    return sorted(출력, key=lambda x: -x["평가액"])


def 요약(종목들: list) -> dict:
    평가액 = sum(s["평가액"] for s in 종목들)
    원금 = sum(s["원금"] for s in 종목들)
    연배당 = sum(s["연배당"] for s in 종목들)
    해외 = sum(s["평가액"] for s in 종목들 if s.get("시장") == "US")
    return {
        "평가액": 평가액,
        "원금": 원금,
        "손익": 평가액 - 원금,
        "수익률": ((평가액 / 원금 - 1) * 100) if 원금 else 0.0,
        "연배당": 연배당,
        "배당수익률": (연배당 / 평가액 * 100) if 평가액 else 0.0,
        "월평균배당": 연배당 / 12,
        "달러비중": (해외 / 평가액 * 100) if 평가액 else 0.0,
        "종목수": len(종목들),
    }


def 집중도(종목들: list, 상위=5) -> dict:
    """상위 N개가 전체의 몇 %인지. 쏠림 확인용."""
    평가액 = sum(s["평가액"] for s in 종목들) or 1.0
    정렬 = sorted(종목들, key=lambda s: -s["평가액"])
    상위합 = sum(s["평가액"] for s in 정렬[:상위])
    최대 = 정렬[0]["평가액"] / 평가액 * 100 if 정렬 else 0.0
    return {
        "상위N": 상위,
        "상위비중": 상위합 / 평가액 * 100,
        "최대종목비중": 최대,
        "최대종목": 정렬[0].get("이름") if 정렬 else "",
    }


