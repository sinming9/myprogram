# 1. 배당 달력
# ==========================================================================
#  최근 1년에 "언제" 배당이 나왔는지를 그대로 다음 1년에 대입합니다.
#  예측이 아니라 "작년에 이 달에 줬다" 는 실적입니다. 회사가 배당 시기나
#  금액을 바꾸면 달라집니다.
#
#  한국 주식은 대개 12월 결산 → 이듬해 4월 지급이라 한 달에 몰립니다.
#  미국은 분기배당이 많아 고르게 퍼집니다. 이 차이가 눈에 보입니다.

def 배당_달력(종목들: list, 환율: float, 등급들=None) -> list:
    """[{월, 금액, 종목들}, ...] 12개.

    등급들 을 주면 그 인출 등급(자유/조건부/잠김)만 셉니다.
    예) 등급들=("자유",) → 지금 바로 쓸 수 있는 배당만
    """
    달력 = [{"월": m, "금액": 0.0, "종목들": []} for m in range(1, 13)]
    for s in 종목들:
        if 등급들 is not None and 인출등급(s.get("계좌")) not in 등급들:
            continue
        배수 = 환율 if s.get("시장") == "US" else 1.0
        수량 = float(s.get("수량") or 0)
        월별 = s.get("배당월별") or {}

        if not 월별:
            # 조회가 안 됐거나 수동 입력이면, 연배당을 어디에 놓을지 알 수 없습니다.
            # 한국은 4월(결산배당 지급), 미국은 분기로 나눠 가정합니다.
            연배당 = float(s.get("연배당") or 0)
            if 연배당 <= 0:
                continue
            if s.get("시장") == "US":
                for m in (3, 6, 9, 12):
                    달력[m - 1]["금액"] += 연배당 / 4
                    달력[m - 1]["종목들"].append(f"{s['이름']}(가정)")
            else:
                달력[3]["금액"] += 연배당
                달력[3]["종목들"].append(f"{s['이름']}(가정)")
            continue

        for 달, 주당 in 월별.items():
            금액 = 수량 * float(주당) * 배수
            달력[달 - 1]["금액"] += 금액
            달력[달 - 1]["종목들"].append(s["이름"])
    return 달력


