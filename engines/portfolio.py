def 배당_인출별(종목들: list) -> dict:
    """인출 등급별로 연배당·평가액을 나눠 셉니다.

    {"자유": {연배당, 월평균, 평가액, 배당수익률, 종목수, 계좌들}, ...}
    """
    칸 = {g: {"연배당": 0.0, "평가액": 0.0, "종목수": 0, "계좌들": []}
         for g in 인출_등급순}
    for s in 종목들 or []:
        g = 인출등급(s.get("계좌"))
        칸[g]["연배당"] += float(s.get("연배당") or 0)
        칸[g]["평가액"] += float(s.get("평가액") or 0)
        칸[g]["종목수"] += 1
        계좌 = str(s.get("계좌") or "").strip()
        if 계좌 and 계좌 not in 칸[g]["계좌들"]:
            칸[g]["계좌들"].append(계좌)
    for v in 칸.values():
        v["월평균"] = v["연배당"] / 12
        v["배당수익률"] = (v["연배당"] / v["평가액"] * 100) if v["평가액"] else 0.0
    return 칸


