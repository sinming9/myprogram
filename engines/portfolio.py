def 종목키(s: dict) -> str:
    """같은 종목인지 판단하는 기준. 티커가 있으면 티커, 없으면 이름."""
    티커 = str(s.get("티커") or "").strip().upper()
    return 티커 or str(s.get("이름") or "").strip()


def 종목_합산(종목들: list) -> list:
    """같은 종목이 여러 계좌에 있으면 하나로 합칩니다.

    쏠림(집중도)은 '어느 계좌에 있느냐' 와 무관하게 그 자산에 얼마나
    몰려 있느냐의 문제라, 계좌를 나눠 세면 위험이 작아 보입니다.
    """
    묶음 = {}
    for s in 종목들:
        키 = 종목키(s)
        칸 = 묶음.setdefault(키, {
            "이름": s.get("이름"), "티커": s.get("티커"),
            "자산군": s.get("자산군"), "평가액": 0.0, "원금": 0.0,
            "연배당": 0.0, "계좌들": [], "계좌별": {},
        })
        칸["평가액"] += s["평가액"]
        칸["원금"] += s["원금"]
        칸["연배당"] += s["연배당"]
        계좌 = s.get("계좌") or "기타"
        if 계좌 not in 칸["계좌들"]:
            칸["계좌들"].append(계좌)
        칸["계좌별"][계좌] = 칸["계좌별"].get(계좌, 0.0) + s["평가액"]
    출력 = []
    for v in 묶음.values():
        v["손익"] = v["평가액"] - v["원금"]
        v["수익률"] = ((v["평가액"] / v["원금"] - 1) * 100) if v["원금"] else 0.0
        v["계좌수"] = len(v["계좌들"])
        출력.append(v)
    return sorted(출력, key=lambda x: -x["평가액"])


def 중복_종목(종목들: list) -> list:
    """두 개 이상의 계좌에 걸쳐 있는 종목."""
    return [x for x in 종목_합산(종목들) if x["계좌수"] >= 2]


def 집중도(종목들: list, 상위=5) -> dict:
    """상위 N개가 전체의 몇 %인지. 쏠림 확인용.

    ※ 같은 종목이 여러 계좌에 있으면 합쳐서 셉니다.
    """
    합산 = 종목_합산(종목들)
    평가액 = sum(s["평가액"] for s in 합산) or 1.0
    상위합 = sum(s["평가액"] for s in 합산[:상위])
    최대 = 합산[0]["평가액"] / 평가액 * 100 if 합산 else 0.0
    return {
        "상위N": 상위,
        "상위비중": 상위합 / 평가액 * 100,
        "최대종목비중": 최대,
        "최대종목": 합산[0].get("이름") if 합산 else "",
        "최대종목_계좌수": 합산[0].get("계좌수", 0) if 합산 else 0,
        "나뉜종목수": sum(1 for x in 합산 if x.get("계좌수", 1) > 1),
    }


