# 2. 목표 배분 대비 괴리 (리밸런싱)
# ==========================================================================

def 리밸런싱(종목들: list, 목표: dict, 기준: str = "자산군") -> list:
    """목표 비중(%)과 현재를 비교해 조정 금액을 계산합니다.

    목표 = {"국내주식": 30, "해외주식": 50, "채권": 20}
    반환 = [{이름, 현재비중, 목표비중, 괴리, 현재금액, 목표금액, 조정금액}, ...]
      조정금액 > 0 이면 더 사야 하고, < 0 이면 덜어내야 합니다.
    """
    현재 = {g["이름"]: g for g in 집계(종목들, 기준)}
    전체 = sum(s["평가액"] for s in 종목들)
    이름들 = sorted(set(현재) | set(목표))

    출력 = []
    for 이름 in 이름들:
        현재금액 = 현재.get(이름, {}).get("평가액", 0.0)
        현재비중 = (현재금액 / 전체 * 100) if 전체 else 0.0
        목표비중 = float(목표.get(이름) or 0)
        목표금액 = 전체 * 목표비중 / 100
        출력.append({
            "이름": 이름,
            "현재비중": 현재비중,
            "목표비중": 목표비중,
            "괴리": 현재비중 - 목표비중,
            "현재금액": 현재금액,
            "목표금액": 목표금액,
            "조정금액": 목표금액 - 현재금액,
        })
    return sorted(출력, key=lambda x: -abs(x["괴리"]))


def 목표_합계(목표: dict) -> float:
    return sum(float(v or 0) for v in 목표.values())


