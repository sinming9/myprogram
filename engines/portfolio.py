def 금액_한글(값) -> str:
    """1억 2,345만원 처럼 읽기 쉬운 형태로. 부호는 붙이지 않습니다."""
    v = abs(_숫자(값))
    if v < 10_000:
        return f"{v:,.0f}원"
    만 = int(round(v / 10_000))
    if 만 < 10_000:
        return f"{만:,}만원"
    억, 나머지만 = divmod(만, 10_000)
    return f"{억:,}억원" if 나머지만 == 0 else f"{억:,}억 {나머지만:,}만원"


def 증감_한글(지금, 이전) -> str:
    """"▲0.42% (+51만원)" 형태. 비교할 값이 없거나 변화가 없으면 빈 문자열.

    ★ 변화가 없을 때 "―0.00% (0원)" 을 돌려주면 화면에 "0원" 만 덩그러니
      붙습니다. 말할 게 없으면 아무 말도 안 하는 편이 낫습니다.
    """
    이전값 = _숫자(이전)
    if 이전값 <= 0:
        return ""
    차이 = _숫자(지금) - 이전값
    if abs(차이) < 1:
        return ""
    비율 = 차이 / 이전값 * 100
    화살 = "▲" if 비율 > 0.005 else ("▼" if 비율 < -0.005 else "―")
    부호 = "+" if 차이 > 0 else ("-" if 차이 < 0 else "")
    return f"{화살}{abs(비율):.2f}% ({부호}{금액_한글(차이)})"


def 시세_모으기(종목들: list) -> tuple:
    """(시세맵, 실패목록). 시세맵 = {(티커, 시장): 시세dict}

    같은 티커를 여러 계좌에서 들고 있어도 한 번만 조회합니다.
    실패한 종목은 시세 없이 계산합니다 — 종목_계산() 이 수동 입력값
    (현재가·평균단가)으로 대신하므로 0원이 되지는 않습니다.
    """
    시세맵, 실패 = {}, []
    for 행 in 종목들 or []:
        티커 = str(행.get("티커") or "").strip()
        시장 = str(행.get("시장") or "KR").strip() or "KR"
        if not 티커 or (티커, 시장) in 시세맵:
            continue
        try:
            시세맵[(티커, 시장)] = 시세_조회(티커, 시장)
        except Exception as e:                               # noqa: BLE001
            실패.append((티커, str(e)[:80]))
    return 시세맵, 실패


def 현황_스냅샷(종목들: list, 환율: float = None, 시세맵: dict = None) -> dict:
    """오늘 시점의 평가액을 한 덩어리로 만듭니다.

    돌려주는 것
      {"날짜", "환율", "총액", "원금",
       "계좌": {계좌이름: 원화금액},
       "계좌시장": {계좌이름: {"US": …, "KR": …, "COIN": …}},
       "자산군": {자산군이름: 원화금액},
       "종목": {열쇠: {"이름", "금액", "수량", "계좌"}}}

    이 모양 그대로 저장해 두었다가 다음 날 "어제 대비" 에 씁니다.

    ★ 종목별로 **수량까지** 남기는 이유 — 평가액만 보면 "돈을 더 넣어서
      늘어난 것" 과 "시장이 올려준 것" 을 구분할 수 없습니다. 수량이
      그대로면 순수 시세 변동, 늘었으면 매수가 섞인 것입니다.
      (기여도() 가 이걸로 갈라 줍니다)
    """
    환율 = _숫자(환율) or 기본환율
    시세맵 = 시세맵 or {}
    계좌합, 계좌시장, 자산군합, 종목별 = {}, {}, {}, {}
    원금합 = 0.0
    for 행 in 종목들 or []:
        티커 = str(행.get("티커") or "").strip()
        시장 = str(행.get("시장") or "KR").strip() or "KR"
        계좌 = str(행.get("계좌") or "기타").strip() or "기타"
        자산군 = str(행.get("자산군") or "기타").strip() or "기타"
        이름 = str(행.get("이름") or 티커 or "이름없음").strip()
        계산 = 종목_계산(행, 시세맵.get((티커, 시장)) or {}, 환율)
        금액 = _숫자(계산.get("평가액"))

        계좌합[계좌] = 계좌합.get(계좌, 0.0) + 금액
        계좌시장.setdefault(계좌, {})
        계좌시장[계좌][시장] = 계좌시장[계좌].get(시장, 0.0) + 금액
        자산군합[자산군] = 자산군합.get(자산군, 0.0) + 금액
        원금합 += _숫자(계산.get("원금"))

        # 같은 종목을 여러 계좌에 나눠 가질 수 있어 계좌까지 열쇠에 넣습니다
        열쇠 = f"{계좌}|{티커 or 이름}"
        칸 = 종목별.setdefault(열쇠, {"이름": 이름, "금액": 0.0,
                                  "수량": 0.0, "계좌": 계좌})
        칸["금액"] += 금액
        칸["수량"] += _숫자(행.get("수량"))
    return {
        "날짜": date.today().isoformat(),
        "환율": 환율,
        "총액": sum(계좌합.values()),
        "원금": 원금합,
        "계좌": 계좌합,
        "계좌시장": 계좌시장,
        "자산군": 자산군합,
        "종목": 종목별,
    }


def 기여도(오늘: dict, 이전: dict, 최대: int = 5) -> dict:
    """어제(또는 지난주) 대비 **무엇 때문에** 늘었는지 종목별로 갈라 줍니다.

    돌려주는 것
      {"목록": [{이름, 차이, 매수분, 시장분}], "매수합", "시장합"}
      목록은 |차이| 가 큰 것부터, 최대 개수까지.

    ★ 매수분과 시장분을 나누는 이유 — 500만원을 새로 넣은 날은 평가액이
      500만원 늘지만 그건 '수익' 이 아닙니다. 수량이 늘어난 만큼은
      그 시점 단가로 쳐서 '내가 넣은 돈' 으로 빼 둡니다. 그래야
      "이번 달 얼마 벌었나" 가 정직한 숫자가 됩니다.
    """
    오늘종목 = (오늘 or {}).get("종목") or {}
    이전종목 = (이전 or {}).get("종목") or {}
    if not 이전종목:
        return {"목록": [], "매수합": 0.0, "시장합": 0.0}

    결과, 매수합, 시장합 = [], 0.0, 0.0
    for 열쇠, 칸 in 오늘종목.items():
        옛 = 이전종목.get(열쇠) or {}
        옛금액 = _숫자(옛.get("금액"))
        옛수량 = _숫자(옛.get("수량"))
        금액 = _숫자(칸.get("금액"))
        수량 = _숫자(칸.get("수량"))
        차이 = 금액 - 옛금액
        if 옛금액 <= 0 and 수량 > 0:
            # 새로 산 종목 — 전부 매수분입니다
            매수분 = 금액
        elif 수량 != 옛수량 and 수량 > 0:
            단가 = 금액 / 수량                    # 오늘 단가로 어림합니다
            매수분 = (수량 - 옛수량) * 단가
        else:
            매수분 = 0.0
        시장분 = 차이 - 매수분
        매수합 += 매수분
        시장합 += 시장분
        if abs(차이) > 0:
            결과.append({"이름": 칸.get("이름") or 열쇠, "차이": 차이,
                       "매수분": 매수분, "시장분": 시장분})

    # 팔아서 사라진 종목도 감소로 잡아 줍니다
    for 열쇠, 옛 in 이전종목.items():
        if 열쇠 in 오늘종목:
            continue
        옛금액 = _숫자(옛.get("금액"))
        if 옛금액 > 0:
            결과.append({"이름": 옛.get("이름") or 열쇠, "차이": -옛금액,
                       "매수분": -옛금액, "시장분": 0.0})
            매수합 -= 옛금액

    # ★ 같은 종목을 여러 계좌에 나눠 갖거나, 이름은 같은데 열쇠가 달라진
    #   경우(티커를 나중에 넣은 경우 등) 한 종목이 "+3,000만 / -3,000만"
    #   두 줄로 쪼개져 보입니다. 이름으로 합쳐서 상쇄시킵니다.
    합침 = {}
    for r in 결과:
        칸 = 합침.setdefault(r["이름"], {"이름": r["이름"], "차이": 0.0,
                                     "매수분": 0.0, "시장분": 0.0})
        칸["차이"] += r["차이"]
        칸["매수분"] += r["매수분"]
        칸["시장분"] += r["시장분"]
    목록 = [r for r in 합침.values() if abs(r["차이"]) >= 1]
    목록.sort(key=lambda r: -abs(r["차이"]))
    return {"목록": 목록[:최대], "매수합": 매수합, "시장합": 시장합}


def 목표기준_추측(목표: dict) -> str:
    """저장된 목표의 이름만 보고 자산군·계좌·시장 중 무엇인지 알아냅니다.

    ★ 화면에서 고른 기준이 저장되지 않던 시절의 자료를 위한 대비책입니다.
      세 목록은 "기타" 하나만 겹치므로, 항목이 둘 이상이면 정확합니다.
    """
    이름들 = set(목표 or {})
    if not 이름들:
        return "자산군"
    점수 = {
        "자산군": len(이름들 & set(자산군목록)),
        "계좌": len(이름들 & set(계좌목록)),
        "시장": len(이름들 & set(시장목록)),
    }
    최고 = max(점수.values())
    if 최고 == 0:
        return "자산군"
    # 동점이면 자산군 → 계좌 → 시장 순 (화면 라디오의 순서와 같습니다)
    for 기준 in ("자산군", "계좌", "시장"):
        if 점수[기준] == 최고:
            return 기준
    return "자산군"


def _계산된_행(종목들: list, 대상계좌=None, 환율: float = None,
           시세맵: dict = None) -> list:
    """대상 계좌만 골라 평가액까지 계산해 돌려줍니다.

    집계()·리밸런싱() 은 '평가액' 이 이미 들어 있는 행을 요구합니다.
    저장해 둔 원본 행에는 없으므로 여기서 한 번 계산해 둡니다.
    """
    환율 = _숫자(환율) or 기본환율
    시세맵 = 시세맵 or {}
    고른것 = [x for x in (종목들 or [])
           if not 대상계좌 or str(x.get("계좌") or "기타") in set(대상계좌)]
    return [종목_계산(행,
                   시세맵.get((str(행.get("티커") or "").strip(),
                             str(행.get("시장") or "KR").strip() or "KR")) or {},
                   환율)
            for 행 in 고른것]


def 엇갈린_해외(종목들: list, 대상계좌=None, 환율: float = None,
           시세맵: dict = None) -> float:
    """**한국에 상장됐지만 자산군은 해외**인 금액(원)을 더합니다.

    ★ 왜 필요한가 — 연금저축·퇴직연금·ISA 는 미국 종목을 직접 못 삽니다
      (해외직접매수_불가). 그래서 국내 상장 해외 ETF 로 삽니다. 이 종목은
      '시장' 은 KR, '자산군' 은 해외주식입니다.

      알림에서 시장별(US/KR/COIN) 금액과 자산군별 비중을 같이 보여 주면,
      이 금액만큼 두 숫자가 안 맞아 보입니다. 틀린 게 아니라 다른 것을
      세는 건데, 말해 주지 않으면 숫자를 의심하게 됩니다. 그래서 액수를
      뽑아 한 줄로 알려 줍니다. 0 이면 알릴 것이 없다는 뜻입니다.
    """
    해외성 = ("해외주식",)
    return sum(_숫자(s.get("평가액"))
               for s in _계산된_행(종목들, 대상계좌, 환율, 시세맵)
               if (s.get("시장") or "KR") == "KR"
               and (s.get("자산군") or "") in 해외성)


def 리밸런싱_신호(종목들: list, 목표: dict, 기준: str = None,
            대상계좌=None, 임계: float = 5.0,
            환율: float = None, 시세맵: dict = None) -> list:
    """목표 비중에서 임계(%p) 넘게 벌어진 것만 골라 돌려줍니다.

    [{이름, 현재금액, 현재비중, 목표비중, 괴리, 조정금액}] — 괴리가 큰 것부터.
    조정금액이 양수면 더 사야 하고, 음수면 덜어내야 목표에 맞습니다.

    대상계좌 를 주면 그 계좌 안에서만 비중을 계산합니다. 화면의
    '리밸런싱 대상 계좌' 와 같은 값을 써야 숫자가 일치합니다.

    ★ 종목들 은 아직 계산 전인 원본 행이어도 됩니다. 집계() 가 평가액을
      요구하므로 여기서 종목_계산 을 먼저 돌립니다. 시세맵을 넘기면
      조회를 새로 하지 않습니다.
    """
    if not 목표:
        return []
    기준 = 기준 or 목표기준_추측(목표)
    대상 = _계산된_행(종목들, 대상계좌, 환율, 시세맵)
    if not 대상:
        return []
    나온것 = []
    for r in 리밸런싱(대상, 목표, 기준):
        if abs(_숫자(r.get("괴리"))) < 임계:
            continue
        나온것.append({
            "이름": r.get("이름"),
            # ★ 금액을 같이 내보내는 이유 — 알림에 비중(%)만 있으면 위쪽
            #   계좌 블록의 원 단위와 연결이 안 됩니다. 읽는 사람이 머릿속
            #   에서 환산하게 두지 않으려고 금액도 들고 나갑니다.
            "현재금액": _숫자(r.get("현재금액")),
            "현재비중": _숫자(r.get("현재비중")),
            "목표비중": _숫자(r.get("목표비중")),
            "괴리": _숫자(r.get("괴리")),
            "조정금액": _숫자(r.get("조정금액")),   # +면 더 사기, -면 덜어내기
        })
    나온것.sort(key=lambda r: -abs(r["괴리"]))
    return 나온것


def _계좌_정렬(이름들) -> list:
    """보고_계좌순서 를 먼저, 거기 없는 계좌는 뒤에 이름순으로."""
    있는것 = [c for c in 보고_계좌순서 if c in 이름들]
    나머지 = sorted(c for c in 이름들 if c not in 보고_계좌순서)
    return 있는것 + 나머지


def _안전(글) -> str:
    return (str(글 or "").replace("&", "&amp;")
            .replace("<", "&lt;").replace(">", "&gt;"))


def _날짜_짧게(날짜) -> str:
    """"2026-09-01" → "9/1". 앞의 0 을 떼어 읽기 좋게 합니다."""
    조각 = str(날짜 or "").split("-")
    if len(조각) != 3:
        return str(날짜 or "")
    try:
        return f"{int(조각[1])}/{int(조각[2])}"
    except ValueError:
        return str(날짜)


def 텔레그램_자산요약(오늘: dict, 어제: dict = None, 월초: dict = None,
                시장표시_계좌=("일반",)) -> str:
    """자산 현황을 텔레그램용 글로 만듭니다 (HTML 모드).

    어제·월초 는 예전에 저장해 둔 스냅샷입니다. 없으면 그 줄을 뺍니다
    (처음 돌리는 날에는 비교할 대상이 아직 없습니다).

    시장표시_계좌 에 든 계좌는 US·KR·COIN 으로 쪼개 한 줄 더 보여줍니다.
    """
    어제 = 어제 or {}
    월초 = 월초 or {}
    어제계좌 = 어제.get("계좌") or {}
    월초계좌 = 월초.get("계좌") or {}

    줄 = [f"📊 <b>자산 현황</b> ({오늘.get('날짜', '')})", ""]

    def 비교줄들(지금액, 계좌이름=None):
        나온것 = []
        이전 = (어제계좌.get(계좌이름) if 계좌이름 else 어제.get("총액"))
        글 = 증감_한글(지금액, 이전)
        if 글:
            나온것.append(f"　어제 대비 {글}")
        기준 = (월초계좌.get(계좌이름) if 계좌이름 else 월초.get("총액"))
        글2 = 증감_한글(지금액, 기준)
        if 글2:
            나온것.append(f"　{_날짜_짧게(월초.get('날짜'))} 대비 {글2}")
        return 나온것

    총액 = _숫자(오늘.get("총액"))
    줄.append(f"💰 <b>전체 {금액_한글(총액)}</b>")
    줄.extend(비교줄들(총액))

    계좌합 = 오늘.get("계좌") or {}
    계좌시장 = 오늘.get("계좌시장") or {}
    for 계좌 in _계좌_정렬(계좌합):
        금액 = _숫자(계좌합.get(계좌))
        if 금액 <= 0:
            continue
        줄.append("")
        줄.append(f"🏦 <b>{_안전(계좌)}</b> {금액_한글(금액)}")
        if 계좌 in (시장표시_계좌 or ()):
            쪼갬 = 계좌시장.get(계좌) or {}
            조각 = [f"{시장} {금액_한글(쪼갬[시장])}"
                  for 시장 in ("US", "KR", "COIN") if _숫자(쪼갬.get(시장)) > 0]
            if 조각:
                줄.append("　" + " / ".join(조각))
        줄.extend(비교줄들(금액, 계좌))

    if not 어제계좌 and not 월초계좌:
        줄.append("")
        줄.append("<i>오늘이 첫 기록이라 비교할 값이 아직 없습니다. "
                 "내일부터 어제 대비가 나옵니다.</i>")
    return "\n".join(줄)
