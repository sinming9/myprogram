#  순자산·연금 페이지는 네트워크를 쓰지 않습니다 (첫 화면이 느려지니까).
#  그래서 저장된 값만으로 평가액을 어림해야 합니다.

#  시세를 못 받을 때 달러 환산에 쓰는 값. 정확한 값이 필요하면 환율을
#  넘겨주세요 (💱 환전 페이지를 한 번 열면 세션 캐시에 최신 환율이 있습니다).
기본환율 = 1390.0


def _숫자(v) -> float:
    try:
        return float(v or 0)
    except (TypeError, ValueError):
        return 0.0


def 오프라인_평가액(행: dict, 환율: float = None) -> float:
    """시세 조회 없이 어림한 **원화** 평가액.

    평가액(직접입력) → 수량 × 현재가(수동) → 수량 × 평균단가 순으로 씁니다.

    ※ 평균단가까지 내려가면 '산 값' 이라 실제 시세와 다릅니다. 그래도 0 으로
      두는 것보다 훨씬 낫습니다. 예전에는 현재가(수동)가 없으면 아예 0으로
      셌는데, 그러면 시세 조회로 쓰시는 분은 순자산에 투자자산이 0원으로
      나왔습니다.

    ※ 시장이 US 면 입력값이 모두 **달러**라서 환율을 곱합니다
      (종목_계산 과 같은 규칙). 코인·국내는 입력값이 원화라 그대로 씁니다.
      이걸 빼먹으면 해외주식이 1/1,390 로 줄어듭니다.
    """
    환율 = 기본환율 if 환율 is None else float(환율)
    배수 = 환율 if (행.get("시장") or "KR") == "US" else 1.0

    직접 = _숫자(행.get("평가액(직접입력)"))
    if 직접 > 0:
        return 직접 * 배수

    수량 = _숫자(행.get("수량"))
    for 열 in ("현재가(수동)", "평균단가"):
        단가 = _숫자(행.get(열))
        if 단가 > 0:
            return 수량 * 단가 * 배수
    return 0.0


def 오프라인_계좌별(종목들: list, 환율: float = None) -> dict:
    """{계좌 이름: 원화 평가액} — 시세 조회 없이 어림한 값."""
    묶음 = {}
    for 행 in 종목들 or []:
        계좌 = str(행.get("계좌") or "기타").strip() or "기타"
        묶음[계좌] = 묶음.get(계좌, 0.0) + 오프라인_평가액(행, 환율)
    return 묶음


def 한국_종목코드인가(티커: str) -> bool:
    """한국 종목코드는 6자리입니다.

    ※ 예전에는 숫자 6자리만 있었지만, 번호가 부족해지면서 신규 ETF·ETN 에는
      '0117V0' 처럼 영문이 섞인 코드가 부여됩니다. 숫자만 검사하면
      이런 종목을 한국 종목으로 인식하지 못해 조회에 실패합니다.
    """
    t = str(티커).strip().upper()
    return len(t) == 6 and t.isalnum() and not t.isalpha()


def 야후티커(티커: str, 시장: str) -> list:
    """조회에 쓸 야후 티커 후보들."""
    t = str(티커).strip().upper()
    if 시장 == "COIN":
        return [t if t.endswith("-USD") else f"{t}-USD"]
    if 시장 == "US":
        return [t]
    if 한국_종목코드인가(t):
        return [f"{t}.KS", f"{t}.KQ"]      # 코스피 먼저, 실패하면 코스닥
    return [t]


def _fdr_시세(티커: str, 시장: str) -> dict:
    """FinanceDataReader 로 조회. 야후에 없는 신규 상장 ETF 대비용입니다.

    야후는 국내 신규 상장 종목 수록이 늦습니다. FDR 은 KRX 에서 직접
    받아오므로 상장 직후 종목도 대개 잡힙니다. 다만 배당 정보는 없습니다.
    """
    import FinanceDataReader as fdr
    끝 = datetime.now()
    시작 = 끝 - timedelta(days=400)
    df = fdr.DataReader(str(티커).strip().upper(),
                        시작.strftime("%Y-%m-%d"), 끝.strftime("%Y-%m-%d"))
    if df is None or df.empty or "Close" not in df:
        raise ValueError("FinanceDataReader 응답이 비어 있습니다")
    종가들 = [float(v) for v in df["Close"].tolist() if v == v and v]
    if not 종가들:
        raise ValueError("유효한 종가가 없습니다")

    현재가 = 종가들[-1]
    고, 저 = max(종가들), min(종가들)

    def 이평(n):
        구간 = 종가들[-n:]
        return sum(구간) / len(구간) if 구간 else 현재가

    return {
        "티커": 티커,
        "현재가": 현재가,
        "통화": "USD" if 시장 == "US" else "KRW",
        "52주고": 고, "52주저": 저,
        "52주위치": ((현재가 - 저) / (고 - 저) * 100) if 고 > 저 else 50.0,
        "이평20": 이평(20), "이평60": 이평(60), "이평120": 이평(120),
        "주당배당_1년": 0.0, "배당횟수": 0, "배당월별": {},
        "출처": "FinanceDataReader",
        "원화표시": 시장 != "US",
    }


def _야후_조회(티커: str, 기간="1y", 시간제한=15) -> dict:
    url = (f"https://query1.finance.yahoo.com/v8/finance/chart/"
           f"{urllib.parse.quote(티커)}?range={기간}&interval=1d&events=div")
    요청 = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(요청, timeout=시간제한) as resp:
        js = json.loads(resp.read().decode("utf-8"))
    결과 = (js.get("chart") or {}).get("result")
    if not 결과:
        raise ValueError("응답에 데이터가 없습니다")
    return 결과[0]


def 업비트_시세(심볼: str, 시간제한=10) -> dict:
    """업비트 원화 마켓 현재가. 인증이 필요 없는 공개 API 입니다.

    국내 거래소에 보유 중이라면 이 값이 '실제로 팔 수 있는 가격' 입니다.
    해외 시세와는 김치 프리미엄만큼 차이가 납니다.
    """
    심볼 = str(심볼).strip().upper().replace("KRW-", "")
    url = f"https://api.upbit.com/v1/ticker?markets=KRW-{urllib.parse.quote(심볼)}"
    요청 = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0",
                                              "Accept": "application/json"})
    with urllib.request.urlopen(요청, timeout=시간제한) as resp:
        js = json.loads(resp.read().decode("utf-8"))
    if not js:
        raise ValueError(f"KRW-{심볼}: 업비트에 없는 종목입니다")
    d = js[0]
    현재가 = float(d["trade_price"])
    고 = float(d.get("highest_52_week_price") or 현재가)
    저 = float(d.get("lowest_52_week_price") or 현재가)
    return {
        "티커": f"KRW-{심볼}",
        "현재가": 현재가,
        "통화": "KRW",
        "52주고": 고, "52주저": 저,
        "52주위치": ((현재가 - 저) / (고 - 저) * 100) if 고 > 저 else 50.0,
        "이평20": None, "이평60": None, "이평120": None,
        "주당배당_1년": 0.0, "배당횟수": 0, "배당월별": {},
        "출처": "업비트(원화)",
        "원화표시": True,
    }


