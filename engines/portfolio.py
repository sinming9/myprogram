# ISA 납입 이력
# ==========================================================================
#  '올해 납입액' 을 숫자 한 칸으로 받으면, 해가 바뀌어도 그 값이 그대로
#  남아서 연 한도 여력이 계속 틀립니다. 1월에 손으로 0 으로 되돌리고
#  그만큼을 총납입액에 옮겨야 하는데, 잊기 쉽고 잊으면 1년 내내 틀립니다.
#
#  그래서 납입한 날짜와 금액을 줄로 남기면
#      총납입액  = 이력 전체 합계
#      올해납입액 = 올해 날짜의 합계
#  가 자동으로 나옵니다. 해가 바뀌면 저절로 0 부터 다시 셉니다.

ISA_이력열 = ["날짜", "금액", "메모"]


def ISA_이력_집계(이력: list, 연납입한도: float = None,
              오늘: date = None) -> dict:
    """납입 이력에서 총·올해 납입액과 연도별 내역을 만듭니다.

    돌려주는 것
      줄수·총납입·올해납입·올해
      연도별 : [{연도, 납입, 한도, 잔여, 소진률, 초과}]  (연도 오름차순)
      경고   : 연 한도를 넘긴 해, 음수를 넣은 줄 등
    """
    오늘 = 오늘 or date.today()
    한도 = float(연납입한도 or ISA_제도["현행"]["연납입한도"])
    연별 = {}
    총납입 = 0.0
    줄수 = 0
    경고 = []
    음수 = 0

    for 행 in 이력 or []:
        날짜 = 행.get("날짜")
        if not isinstance(날짜, date):
            try:
                날짜 = date.fromisoformat(str(날짜 or "")[:10])
            except (ValueError, TypeError):
                continue
        try:
            금액 = float(행.get("금액") or 0)
        except (TypeError, ValueError):
            continue
        if 금액 < 0:
            음수 += 1
            continue
        if 금액 == 0:
            continue
        줄수 += 1
        총납입 += 금액
        연별[날짜.year] = 연별.get(날짜.year, 0.0) + 금액

    if 음수:
        경고.append(f"금액이 음수인 {음수}줄은 셈에서 뺐습니다. 중도 인출은 "
                  "납입 한도가 복구되지 않으므로 이력에 넣지 마세요.")

    연도별 = []
    for 연도 in sorted(연별):
        납입 = 연별[연도]
        연도별.append({
            "연도": 연도, "납입": 납입, "한도": 한도,
            "잔여": max(한도 - 납입, 0.0),
            "소진률": (납입 / 한도 * 100) if 한도 else 0.0,
            "초과": 납입 > 한도,
        })
        if 납입 > 한도:
            경고.append(f"{연도}년 납입액이 연 한도를 "
                      f"{(납입 - 한도) / 1e4:,.0f}만원 넘습니다. "
                      "제도상 넘길 수 없으니 날짜나 금액을 확인해 주세요.")

    return {
        "줄수": 줄수,
        "총납입": 총납입,
        "올해납입": 연별.get(오늘.year, 0.0),
        "올해": 오늘.year,
        "연도별": 연도별,
        "경고": 경고,
    }


def ISA_현황(가입일: date, 총납입액: float, 올해납입액: float,
           순이익: float, 유형: str = "일반형", 제도: str = "현행",
           오늘: date = None) -> dict:
    """ISA 만기·납입한도·비과세 소진 현황과 절세액을 계산합니다."""
    오늘 = 오늘 or date.today()
    설정 = ISA_제도.get(제도, ISA_제도["현행"])

    만기일 = _몇년뒤(가입일, ISA_의무기간_년)
    남은일 = (만기일 - 오늘).days
    채움 = 남은일 <= 0

    비과세한도 = (설정["비과세_서민"] if 유형.startswith("서민")
              else 설정["비과세_일반"])
    비과세분 = min(max(순이익, 0.0), 비과세한도)
    초과분 = max(순이익 - 비과세한도, 0.0)
    ISA세금 = 초과분 * ISA_분리과세율
    일반세금 = max(순이익, 0.0) * 일반계좌_배당세율
    절세액 = 일반세금 - ISA세금

    return {
        "가입일": 가입일, "만기일": 만기일,
        "의무기간_충족": 채움,
        "남은일": max(남은일, 0),
        "경과일": (오늘 - 가입일).days,
        "진행률": min((오늘 - 가입일).days / max((만기일 - 가입일).days, 1) * 100, 100),
        "제도": 설정["이름"],
        "유형": 유형,
        "비과세한도": 비과세한도,
        "비과세사용": 비과세분,
        "비과세잔여": max(비과세한도 - 비과세분, 0.0),
        "비과세소진률": (비과세분 / 비과세한도 * 100) if 비과세한도 else 0.0,
        "과세대상": 초과분,
        "ISA세금": ISA세금,
        "일반계좌세금": 일반세금,
        "절세액": 절세액,
        "연납입한도": 설정["연납입한도"],
        "연납입잔여": max(설정["연납입한도"] - 올해납입액, 0.0),
        "총납입한도": 설정["총납입한도"],
        "총납입잔여": max(설정["총납입한도"] - 총납입액, 0.0),
        "총소진률": (총납입액 / 설정["총납입한도"] * 100) if 설정["총납입한도"] else 0.0,
    }


def 계좌_제약_점검(종목들: list) -> list:
    """제도상 그 계좌에 담을 수 없는 조합을 찾아냅니다."""
