def 자산_한줄(오늘, 어제) -> str:
    총액 = PF._숫자((오늘 or {}).get("총액"))
    글 = f"자산  {PF.금액_한글(총액)}"
    증감 = PF.증감_한글(총액, (어제 or {}).get("총액"))
    return 글 + (f"  어제 {증감}" if 증감 else "")


def 환율_한줄(통화) -> str:
    """"달러 1,346원  1년 중 12% · 싼 편" """
    위치 = 통화.get("위치")
    꼬리 = ""
    if 위치 is not None:
        꼬리 = f"  1년 중 {위치:.0f}% · {FX.구간_이름(위치)}"
    return f"{통화['짧은이름']} {통화['표시가']}{꼬리}"


def 자산_자세히(자산, 모드: str = "평일") -> list:
    """★ 기준 비교 줄을 모드에 따라 골라 냅니다.

    예전에는 어제·이번 주·월초·올해를 매일 다 내보냈습니다. 다섯 줄이
    전부 `이름 + 화살표 + % + (금액)` 으로 모양이 같아서 한 덩어리로
    보이고, 그래서 그 안에서 **매일 진짜 새로운 줄인 '어제' 까지 같이
    묻혔습니다.**

    줄마다 새로워지는 주기가 다릅니다.
      어제      매일          → 평일에도
      이번 주   주가 끝날 때  → 토요일(주간)에만
      지난달    달이 끝날 때  → 1일(월간)에만
      올해      사실상 연말   → 1일(월간)에만
      원금 대비 넣고 뺄 때    → 늘 (내 위치를 잡아 주는 한 줄)

    결산 때만 나오는 줄은 그날 눈에 띕니다. 정보량은 같은데 실제로
    읽히는 양이 늘어납니다.
    """
    오늘 = (자산 or {}).get("오늘") or {}
    어제 = (자산 or {}).get("어제") or {}
    총액 = PF._숫자(오늘.get("총액"))
    원금 = PF._숫자(오늘.get("원금"))

    줄 = [f"💰 <b>{PF.금액_한글(총액)}</b>"]

    # ★ 기록이 며칠 없으면 어제·이번 주·이달이 전부 같은 날을 가리켜서
    #   똑같은 줄이 여러 번 나옵니다. 이미 쓴 기준일은 건너뜁니다.
    쓴날짜 = set()

    def 견주기(이름, 기준):
        날 = str((기준 or {}).get("날짜") or "")
        if not 날 or 날 in 쓴날짜:
            return
        증감 = PF.증감_한글(총액, (기준 or {}).get("총액"))
        if not 증감:
            return
        쓴날짜.add(날)
        줄.append(f"　{이름}  {증감}")

    견주기("어제", 어제)
    if 모드 in ("주간", "월간"):
        견주기("이번 주", (자산 or {}).get("주초"))
    if 모드 == "월간":
        지난달 = (자산 or {}).get("지난달") or (자산 or {}).get("월초") or {}
        견주기(f"{_짧은날(지난달.get('날짜'))} 대비", 지난달)
        견주기("올해", (자산 or {}).get("연초"))
    if 원금 > 0:
        수익 = 총액 - 원금
        부호 = "+" if 수익 >= 0 else "-"
        줄.append(f"　원금 {PF.금액_한글(원금)} → "
                 f"{부호}{abs(수익 / 원금 * 100):.1f}% "
                 f"({부호}{PF.금액_한글(수익)})")

    기여 = (자산 or {}).get("기여") or {}
    목록 = 기여.get("목록") or []
    if 목록:
        줄.append("")
        줄.append("　오늘 움직인 것")
        for r in 목록:
            부호 = "+" if r["차이"] >= 0 else "-"
            줄.append(f"　　{_안전(r['이름'])[:12]}  "
                     f"{부호}{PF.금액_한글(r['차이'])}")
        매수 = PF._숫자(기여.get("매수합"))
        시장 = PF._숫자(기여.get("시장합"))
        if abs(매수) >= 10_000:      # 매수·매도가 있었던 날만 갈라 보여줍니다
            줄.append(f"　　└ 내가 넣은 돈 {'+' if 매수 >= 0 else '-'}"
                     f"{PF.금액_한글(매수)} · "
                     f"시장이 준 것 {'+' if 시장 >= 0 else '-'}"
                     f"{PF.금액_한글(시장)}")
    return 줄


def 계좌_블록(오늘, 어제) -> list:
    """계좌별 금액과 어제 대비. 시장이 섞인 계좌는 US/KR/COIN 으로 쪼갭니다.

    ★ 쪼갠 줄에도 증감을 붙이는 이유 — "일반 1억, 그중 US 6천" 까지만
      보면 총액이 왜 움직였는지 알 수 없습니다. 오른 게 미국인지 코인인지
      갈라 줘야 "환율 때문인가, 비트코인 때문인가" 를 그 자리에서 압니다.

    ★ 한 시장뿐인 계좌(연금저축이 전부 KR 인 경우)는 쪼개지 않습니다.
      "KR 3,000만원" 한 줄은 바로 위 계좌 줄과 같은 말이라 소음입니다.
    """
    계좌합 = (오늘 or {}).get("계좌") or {}
    어제계좌 = (어제 or {}).get("계좌") or {}
    계좌시장 = (오늘 or {}).get("계좌시장") or {}
    어제시장 = (어제 or {}).get("계좌시장") or {}
    if not 계좌합:
        return []
    줄 = ["", "　계좌"]
    for 계좌 in PF._계좌_정렬(계좌합):
        금액 = PF._숫자(계좌합.get(계좌))
        if 금액 <= 0:
            continue
        증감 = PF.증감_한글(금액, 어제계좌.get(계좌))
        짧은증감 = 증감.split(" (")[-1].rstrip(")") if 증감 else ""
        줄.append(f"　　{_안전(계좌)}  {PF.금액_한글(금액)}"
                 + (f"  {짧은증감}" if 짧은증감 else ""))

        쪼갬 = 계좌시장.get(계좌) or {}
        옛쪼갬 = (어제시장.get(계좌) or {}) if isinstance(어제시장, dict) else {}
        있는시장 = [m for m in ("US", "KR", "COIN")
                 if PF._숫자(쪼갬.get(m)) > 0]
        if len(있는시장) < 2:
            continue
        for m in 있는시장:
            칸 = PF._숫자(쪼갬.get(m))
            조각증감 = PF.증감_한글(칸, 옛쪼갬.get(m))
            줄.append(f"　　　{m.ljust(4)} {PF.금액_한글(칸)}"
                     + (f"  {조각증감}" if 조각증감 else ""))
    return 줄


def 환율_자세히(환율들) -> list:
    줄 = ["💱 <b>환율</b>"]
    for i, 통화 in enumerate(환율들 or []):
        위치 = 통화.get("위치")
        머리 = f"　{통화['짧은이름']} {통화['표시가']}"
        하루 = 통화.get("하루변화")
        if 하루:
            머리 += f"  어제 {하루}"
        줄.append(머리)
        if 위치 is not None:
            줄.append(f"　　{FX.범위_막대(위치)}  {위치:.0f}% · "
                     f"{FX.구간_이름(위치)}")
        if i == 0 and 통화.get("체감"):
            줄.append(f"　　100만원 → {통화['체감']}")
    return 줄


def 신호_블록(신호들, 범위설명="", 엇갈린해외: float = 0) -> list:
    """★ 범위를 제목에 붙이고, 비중 옆에 금액을 같이 둡니다.

    예전에는 비중(%)만 있고 범위는 맨 아래 작은 글씨였습니다. 그러면
    위쪽 계좌 블록은 원, 여기는 % 라서 두 블록이 머릿속에서 안 이어지고,
    "이게 전 계좌 얘기인가 일반만인가" 를 다 읽은 뒤에야 알게 됩니다.

    엇갈린해외 — 국내 상장 해외 ETF 금액. 위 계좌 블록에서는 KR 로
    세지만 여기서는 해외주식으로 셉니다. 그 액수만큼 두 숫자가 안 맞아
    보이므로, 있을 때만 이유를 한 줄 답니다.
    """
    if not 신호들:
        return []
    머리 = "🔔 <b>행동 신호</b>"
    if 범위설명:
        머리 += f" <i>({_안전(범위설명)})</i>"
    줄 = ["", 머리]
    for s in 신호들:
        금액글 = PF.금액_한글(PF._숫자(s.get("현재금액")))
        줄.append(f"　{_안전(s['이름'])}  {금액글} · {s['현재비중']:.0f}%"
                 f"  (목표 {s['목표비중']:.0f}% · "
                 f"{'+' if s['괴리'] > 0 else ''}{s['괴리']:.0f}%p)")
        금액 = PF._숫자(s.get("조정금액"))
        if abs(금액) >= 10_000:
            말 = "더 사면" if 금액 > 0 else "줄이면"
            줄.append(f"　　→ {PF.금액_한글(abs(금액))}어치 {말} 목표에 맞습니다")
    if 엇갈린해외 >= 10_000:
        줄.append(f"　※ 국내 상장 해외 ETF {PF.금액_한글(엇갈린해외)}은 "
                 f"위 계좌에선 KR, 여기선 해외주식으로 셉니다")
    return 줄


