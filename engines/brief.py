def _안전(글) -> str:
    return (str(글 or "").replace("&", "&amp;")
            .replace("<", "&lt;").replace(">", "&gt;"))


def _종목이름(글) -> str:
    """긴 이름은 자르고 '…' 을 붙입니다.

    ★ 예전에는 14글자에서 말없이 잘라 'TIGER 미국 나스닥 100' 이
      'TIGER 미국 나스닥 1' 로 나갔습니다 — 다른 종목처럼 읽힙니다.
    """
    글 = str(글 or "")
    return _안전(글 if len(글) <= 종목이름_길이 else 글[:종목이름_길이 - 1].rstrip() + "…")


def 만원(값) -> str:
    """만원 단위로 반올림한 금액. 1만원 미만은 '0'. 부호는 붙이지 않습니다."""
    v = abs(PF._숫자(값))
    if v < 5_000:
        return "0"
    return PF.금액_한글(round(v, -4))


def 증감(값) -> str:
    """+123만원 / -45만원 / 0"""
    v = PF._숫자(값)
    글 = 만원(v)
    if 글 == "0":
        return "0"
    return ("+" if v > 0 else "-") + 글


def _날짜머리(오늘날짜: str) -> str:
    try:
        d = date.fromisoformat(오늘날짜)
    except (TypeError, ValueError):
        d = date.today()
    return f"{d.month}/{d.day} ({요일이름[d.weekday()]})"


def 오늘_모드(오늘날짜: str) -> str:
    """"주간"(일요일) / "짧은"(월요일) / "평일"(화~토)."""
    try:
        d = date.fromisoformat(오늘날짜)
    except (TypeError, ValueError):
        d = date.today()
    return {6: "주간", 0: "짧은"}.get(d.weekday(), "평일")


def 결산일인가(오늘날짜: str) -> bool:
    """매달 1일 — 그날의 판에 '지난달 결산' 을 덧붙입니다."""
    try:
        return date.fromisoformat(오늘날짜).day == 1
    except (TypeError, ValueError):
        return False


def _짧은날(값) -> str:
    조각 = str(값 or "").split("-")
    if len(조각) != 3:
        return str(값 or "")
    try:
        return f"{int(조각[1])}/{int(조각[2])}"
    except ValueError:
        return str(값)


def _간격(오늘, 어제) -> int:
    try:
        return max(1, (date.fromisoformat(str(오늘.get("날짜")))
                       - date.fromisoformat(str(어제.get("날짜")))).days)
    except (TypeError, ValueError, AttributeError):
        return 1


def _어제라벨(오늘, 어제) -> str:
    """직전 기록이 어제가 아니면(예약이 빠진 날) 그 날짜로 부릅니다."""
    return "어제" if _간격(오늘, 어제) == 1 else f"{_짧은날(어제.get('날짜'))}"


def _계좌(이름) -> str:
    # 사용자가 지은 계좌 이름에 < & 가 있으면 텔레그램이 글을 거부하므로 이스케이프
    return _안전(계좌_짧게.get(str(이름), str(이름)))


def _수익률(스냅) -> tuple:
    """(수익률 %, 수익액). 원금을 모르면 (None, None)."""
    원금 = PF._숫자((스냅 or {}).get("원금"))
    기준 = PF._숫자((스냅 or {}).get("원금있는총액", (스냅 or {}).get("총액")))
    if 원금 <= 0:
        return None, None
    return (기준 - 원금) / 원금 * 100, 기준 - 원금


def _구간말(위치) -> str:
    if 위치 is None:
        return ""
    if 위치 <= 환율_싼구간:
        return "싼 편"
    if 위치 >= 환율_비싼구간:
        return "비싼 편"
    return ""


