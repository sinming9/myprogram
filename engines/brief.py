def _붙이기(줄, *조각들):
    for 조각 in 조각들:
        if 조각:
            줄 += [""] + 조각
    return 줄


def 평일판(자료: dict, 오늘날짜: str) -> str:
    """화~토 아침 — 전날 장 요약."""
    오늘 = 자료.get("오늘") or {}
    어제 = 자료.get("어제") or {}
    줄 = [f"☀️ <b>{_날짜머리(오늘날짜)}</b> · 전날 장"]
    _붙이기(줄, 원금점검_줄(자료), 특이사항_줄(자료))
    줄 += [""] + 총자산_줄(오늘)
    줄 += 변화_줄(오늘, 어제, 자료.get("움직임_하루"), _어제라벨(오늘, 어제))
    줄 += 큰변동_줄(자료)
    _붙이기(줄,
          종목_줄(자료.get("움직임_하루"), "많이 움직인 종목"),
          계좌변동_줄(오늘, 어제),
          환율_줄(자료.get("환율"), 자료.get("외화")),
          여행_줄(자료.get("여행"), 전체=False),
          비중_줄(자료.get("리밸런싱")))
    return "\n".join(줄)


def 주간판(자료: dict, 오늘날짜: str) -> str:
    """일 아침 — 한 주 결산 + 코인."""
    오늘 = 자료.get("오늘") or {}
    줄 = [f"📅 <b>{_날짜머리(오늘날짜)} 한 주 마무리</b>"]
    _붙이기(줄, 원금점검_줄(자료), 특이사항_줄(자료))
    줄 += [""] + 할일_줄(자료.get("리밸런싱"), 자료.get("환율"), 자료.get("엇갈린해외"),
                      자료.get("엇갈린미국"))
    _붙이기(줄, 신규자금_줄(자료.get("신규자금")))
    줄 += [""] + 총자산_줄(오늘, 누적액=True)
    줄 += 변화_줄(오늘, 자료.get("주초"), 자료.get("움직임_주간"), "이번 주")
    줄 += 일반_시장_줄(오늘, 자료.get("주초"))
    줄 += 주간_큰변동_줄(자료.get("일별변동"))
    _붙이기(줄,
          종목_줄(자료.get("움직임_주간"), "이번 주 많이 움직인 종목"),
          # 코인은 지난 일요일(7일 전) 기록과 비교 — 없으면 이번 주 첫 기록
          # (라벨은 실제로 견준 쪽: '지난주 대비' / '주초 대비')
          코인_줄(오늘, 자료.get("지난주") or 자료.get("주초"),
               "지난주" if 자료.get("지난주") else "주초"),
          환율_줄(자료.get("환율"), 자료.get("외화"), 보유표시=False)
          + 환율_더보기(자료.get("환율")),
          외화_줄(자료.get("외화")),
          여행_줄(자료.get("여행"), 전체=True),
          계좌잔액_줄(오늘))
    return "\n".join(줄)


def 짧은판(자료: dict, 오늘날짜: str) -> str:
    """월 아침 — 코인 변동 · 총자산 · 환율 · 특이사항만.

    토·일은 주식 장이 없어 주식 숫자는 어제(일요일) 결산과 같습니다.
    주말 동안 움직이는 코인과 환율만 짧게 봅니다.
    """
    오늘 = 자료.get("오늘") or {}
    어제 = 자료.get("어제") or {}
    줄 = [f"☀️ <b>{_날짜머리(오늘날짜)}</b> · 주말 사이"]
    _붙이기(줄, 원금점검_줄(자료), 특이사항_줄(자료))
    _붙이기(줄, 코인_줄(오늘, 어제, _어제라벨(오늘, 어제)))
    줄 += [""] + 총자산_줄(오늘)
    _붙이기(줄, 환율_줄(자료.get("환율"), 자료.get("외화")))
    return "\n".join(줄)


def 브리핑_만들기(자료: dict, 오늘날짜: str = None) -> tuple:
    """(본문, 모드). 모드 = "주간"(일) / "짧은"(월) / "평일"(화~토).
    매달 1일이면 그날 판 끝에 '지난달 결산' 을 붙입니다."""
