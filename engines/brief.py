def 특이사항_줄(자료) -> list:
    """자산 급변 · 역대 최고 경신 · 환율 구간 진입. 없으면 빈 목록(섹션 생략).

    ★ 리밸런싱(비중 초과/부족)은 넣지 않습니다 — '할 일' 과 겹칩니다.
    ★ 환율은 '들어온 날' 만 알립니다. 어제도 그 구간이었으면 새 소식이 아닙니다.
    """
    오늘 = 자료.get("오늘") or {}
    어제 = 자료.get("어제") or {}
    총액, 옛 = PF._숫자(오늘.get("총액")), PF._숫자(어제.get("총액"))
    항목 = []
    if 옛 > 0 and 총액 <= 0:
        항목.append("자산이 0원으로 나옵니다 — 시세 조회 문제일 수 있습니다")
    # (예전 '자산 급변' 은 큰변동_줄 의 ⚡ 한 줄로 합쳤습니다 — 2026-11-01)
    최고 = PF._숫자(자료.get("최고"))
    if 총액 > 0 and 최고 > 0 and 총액 > 최고:
        날 = 자료.get("최고날")
        항목.append("자산 역대 최고 경신" + (f" (이전 최고 {_짧은날(날)})" if 날 else ""))
    for 이름 in 환율_보일것:
        t = (자료.get("환율") or {}).get(이름) or {}
        위치, 이전 = t.get("위치"), t.get("이전위치")
        if 위치 is None:
            continue
        쌈, 비쌈 = 위치 <= 환율_싼구간, 위치 >= 환율_비싼구간
        if not (쌈 or 비쌈):
            continue
        if 이전 is not None and ((쌈 and 이전 <= 환율_싼구간)
                                 or (비쌈 and 이전 >= 환율_비싼구간)):
            continue
        if 쌈:
            꼬리 = f"하위 {round(위치)}%" if round(위치) >= 1 else "1년 최저 수준"
            항목.append(f"{이름} 1년 최저 구간 진입 ({꼬리})")
        else:
            꼬리 = (f"상위 {round(100 - 위치)}%" if round(100 - 위치) >= 1
                  else "1년 최고 수준")
            항목.append(f"{이름} 1년 최고 구간 진입 ({꼬리})")
    if not 항목:
        return []
    return ["⚠️ <b>특이사항</b>"] + [f"• {_안전(x)}" for x in 항목]


