"""
==========================================================================
아침 브리핑 — 환율 + 자산을 한 통으로
==========================================================================
[이 모듈이 하는 것]
  매일 아침 보낼 텔레그램 글을 조립합니다. 환율과 자산을 따로 보내면
  둘 다 대충 읽게 되어, 하나로 합쳤습니다.

[설계 원칙 네 가지]

  1) 분량을 상황에 따라 바꿉니다
     조용한 날에 자세히 보내면 사흘이면 안 읽게 됩니다. 평소에는 네댓
     줄로 "이상 없음" 만 알리고, 볼 것이 생겼을 때만 펼칩니다.

  2) '상태' 가 아니라 '전이' 를 알립니다
     달러가 싼 구간에 20일 머무는 동안 20일 내내 "달러 쌉니다" 라고
     하면 그것도 소음입니다. 들어온 날만 알리고, 머무는 동안은 주간
     결산에서 "며칠째" 로만 언급합니다.

  3) 숫자가 아니라 판단을 먼저 줍니다
     맨 윗줄에 "이상 없음" 또는 "볼 것 N가지" 를 놓아, 3초만 봐도
     오늘 더 읽을지 말지 정할 수 있게 합니다.

  4) 오른 이유를 같이 말합니다
     "+218만원" 보다 "비트코인이 180만원 올렸다" 가 정보입니다.
     내가 넣은 돈과 시장이 준 돈도 갈라서 보여줍니다.

[이 파일은 streamlit 을 쓰지 않습니다]
  GitHub Actions 의 scripts/morning_brief.py 가 그대로 씁니다.
==========================================================================
"""

모듈버전 = "2026-09-20"

from datetime import date, datetime

from engines import fx as FX
from engines import portfolio as PF

요일이름 = ["월", "화", "수", "목", "금", "토", "일"]

# 자세히 펼치는 기준 — 여기 숫자만 고치면 민감도가 바뀝니다
기본_임계 = {
    "자산_하루_변동": 2.0,      # % — 이만큼 움직이면 자세히
    "환율_싼구간": 15.0,        # 1년 범위 하위 N% 이하면 신호
    "환율_비싼구간": 85.0,      # 상위 N% 이상이면 신호
    "리밸런싱_괴리": 5.0,       # %p — 목표에서 이만큼 벌어지면 신호
}


def _안전(글) -> str:
    return (str(글 or "").replace("&", "&amp;")
            .replace("<", "&lt;").replace(">", "&gt;"))


def _날짜머리(오늘날짜: str) -> str:
    try:
        d = date.fromisoformat(오늘날짜)
    except (TypeError, ValueError):
        d = date.today()
    return f"{d.month}/{d.day} ({요일이름[d.weekday()]})"


def 오늘_모드(오늘날짜: str) -> str:
    """"월간" / "주간" / "평일" — 날짜만으로 정해지는 모드."""
    try:
        d = date.fromisoformat(오늘날짜)
    except (TypeError, ValueError):
        d = date.today()
    if d.day == 1:
        return "월간"
    if d.weekday() == 5:              # 토요일 = 한 주 마무리
        return "주간"
    return "평일"


