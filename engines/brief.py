def 총자산_줄(오늘, 누적액=False) -> list:
    총액 = PF._숫자(오늘.get("총액"))
    률, 액 = _수익률(오늘)
    꼬리 = ""
    if 률 is not None:
        꼬리 = f" · 원금 대비 {률:+.1f}%"
        if 누적액:
            꼬리 += f" ({증감(액)})"
    return [f"💰 <b>총자산 {만원(총액)}</b>{꼬리}"]


def 변화_줄(오늘, 기준, 움직임, 이름) -> list:
    """'어제 대비 ▼206만원 (-0.98%)' + '└ 추가 매수 0 · 시장 변동 -206만원'."""
    if not 기준 or PF._숫자(기준.get("총액")) <= 0:
        return [f"　{이름} 비교 기록이 아직 없습니다"]
    옛 = PF._숫자(기준.get("총액"))
    차이 = PF._숫자(오늘.get("총액")) - 옛
    화살 = "▲" if 차이 > 0 else ("▼" if 차이 < 0 else "―")
    매수 = PF._숫자((움직임 or {}).get("매수합"))
    시장 = 차이 - 매수
    머리 = 이름 if 이름 == "이번 주" else f"{이름} 대비"
    return [f"　{머리} {화살}{만원(차이)} ({차이 / 옛 * 100:+.2f}%)",
            f"　└ 추가 매수 {증감(매수)} · 시장 변동 {증감(시장)}"]


def 종목_줄(움직임, 제목) -> list:
    """시장 변동이 ±기준 이상인 종목만, 큰 것부터 최대 N개.

    ★ 매수한 금액은 빼고 '시세로 움직인 금액' 으로 고릅니다. 그러지 않으면
      300만원어치 산 종목이 '+300만원 움직였다' 로 맨 위에 옵니다.
    """
    목록 = [r for r in (움직임 or {}).get("목록") or []
          if abs(PF._숫자(r.get("시장분"))) >= 종목_표시_금액]
    목록.sort(key=lambda r: -abs(r["시장분"]))
    if not 목록:
        return []
    줄 = [f"📊 {제목}"]
    for r in 목록[:종목_최대]:
        줄.append(f"　{_안전(str(r['이름'])[:14])} [{_계좌(r['계좌'])}] "
                 f"{증감(r['시장분'])}")
    return 줄


def 계좌변동_줄(오늘, 기준) -> list:
    """±1% 또는 ±50만원 이상 움직인 계좌. 없으면 '계좌 변동 미미'."""
    지금 = (오늘 or {}).get("계좌") or {}
    옛 = (기준 or {}).get("계좌") or {}
    if not 옛:
        return []
    큰것 = []
    for 계좌 in PF._계좌_정렬(지금):
        a, b = PF._숫자(지금.get(계좌)), PF._숫자(옛.get(계좌))
        if b <= 0:
            continue
        차, 률 = a - b, (a - b) / b * 100
        if abs(률) >= 계좌_표시_비율 or abs(차) >= 계좌_표시_금액:
            큰것.append(f"{_계좌(계좌)} {증감(차)} ({률:+.1f}%)")
    return ["🏦 " + (" · ".join(큰것) if 큰것 else "계좌 변동 미미")]


def 환율_줄(환율, 외화들) -> list:
    """달러 1,355원(싼 편) · 엔 860원(보유 -2.1%) · 싱달 1,061원."""
    조각 = []
    for 이름 in 환율_보일것:
        t = (환율 or {}).get(이름)
        if not t:
            continue
        꼬리 = []
        구간 = _구간말(t.get("위치"))
        if 구간:
            꼬리.append(구간)
        보유 = [x for x in 외화들 or [] if x.get("짧은이름") == 이름]
        if 보유 and 보유[0].get("수익률") is not None:
            꼬리.append(f"보유 {보유[0]['수익률']:+.1f}%")
        조각.append(f"{이름} {t['표시가']}" + (f"({', '.join(꼬리)})" if 꼬리 else ""))
    return ["💱 " + " · ".join(조각)] if 조각 else []


def 비중_줄(리밸런싱) -> list:
    """⚖️ 국내 30%(목표 25) · 해외 59%(목표 50)"""
    이름별 = {r["이름"]: r for r in 리밸런싱 or []}
    조각 = []
    for 자산군, 짧게 in (("국내주식", "국내"), ("해외주식", "해외")):
        r = 이름별.get(자산군)
        if r:
            조각.append(f"{짧게} {r['현재비중']:.0f}%(목표 {r['목표비중']:.0f})")
    if not 조각:
        return []
    return [f"⚖️ 비중({'·'.join(리밸런싱_계좌)}): " + " · ".join(조각)]


def 할일_줄(리밸런싱, 환율) -> list:
    """자산군마다 '→ ○○만원 줄이기/더 사기'. 벗어난 게 없으면 '할 일 없음'."""
    벗어남 = [r for r in 리밸런싱 or [] if abs(r["괴리"]) >= 리밸런싱_괴리]
    줄 = [f"✅ <b>할 일</b> (일반 계좌 · 목표에서 {리밸런싱_괴리:.0f}%p 넘게 벗어난 것)"]
    # 목표 합이 100 이 아니면 '○○만원 사기/줄이기' 금액이 정확하지 않습니다
    목표합 = PF._숫자((리밸런싱 or [{}])[0].get("목표합"))
    if 목표합 and abs(목표합 - 100) > 0.5:
        줄.append(f"　※ 목표 비중 합이 {목표합:.0f}% 입니다 — 앱에서 100% 로 맞추세요")
    if not 벗어남:
        return 줄 + ["　할 일 없음"]
    for r in sorted(벗어남, key=lambda r: -abs(r["괴리"])):
        금액 = PF._숫자(r.get("조정금액"))
        말 = "더 사기" if 금액 > 0 else "줄이기"
        줄.append(f"　{_안전(r['이름'])} {r['현재비중']:.0f}% (목표 {r['목표비중']:.0f})"
                 f" → {만원(금액)} {말}")
    해외 = next((r for r in 리밸런싱 or [] if r["이름"] == "해외주식"), None)
    달러 = (환율 or {}).get("달러") or {}
    if (해외 and 해외["괴리"] <= -리밸런싱_괴리
            and _구간말(달러.get("위치")) == "싼 편"):
        줄.append("　→ <b>해외 매수 적기</b> (달러 싼 구간 + 해외 비중 부족)")
    return 줄


def _수량글(x) -> str:
    q = PF._숫자(x.get("수량"))
    if x.get("짧은이름") == "엔":
        return f"{q / 1e4:,.0f}만엔" if q >= 1e4 else f"{q:,.0f}엔"
    return f"{x.get('코드', '')} {q:,.0f}".strip()


def 외화_줄(외화들) -> list:
    """엔 50만엔 · 421만원 · 매입 860원 대비 -2.1%"""
    if not 외화들:
        return []
    줄 = ["💴 <b>외화 보유</b>"]
    for x in 외화들:
        꼬리 = (f" · 매입 {x['평균표시']} 대비 {x['수익률']:+.1f}%"
              if x.get("수익률") is not None else "")
        줄.append(f"　{x['짧은이름']} {_수량글(x)} · {만원(x['평가액'])}{꼬리}")
    return 줄


def 여행_줄(여행들, 전체=True) -> list:
    """토요일판은 전체, 평일판은 '오늘이 평균보다 쌀 때' 만 한 줄."""
    줄 = []
    for t in 여행들 or []:
        목표, 모음 = PF._숫자(t.get("목표")), PF._숫자(t.get("모음"))
        평균, 오늘 = PF._숫자(t.get("평균")), PF._숫자(t.get("오늘"))
        싸다 = 오늘 > 0 and 평균 > 0 and 오늘 < 평균
        if not 전체:
            if 싸다:
                줄.append(f"✈️ {_안전(t['이름'])} 환전 적기 — 오늘 {t['오늘표시']} "
                         f"< 평균 {t['평균표시']}")
            continue
        진행 = f" ({모음 / 목표 * 100:.0f}%)" if 목표 > 0 else ""
        줄.append(f"　{_안전(t['이름'])} {t['코드']} {모음:,.0f} / {목표:,.0f}{진행}")
        if 평균 > 0 and 오늘 > 0:
            비교 = ("지금보다 싸게 모음" if 평균 < 오늘
                  else "지금이 평균보다 쌈 — 더 바꿔 둘 때" if 싸다 else "평균과 같음")
            줄.append(f"　　평균 {t['평균표시']} · 오늘 {t['오늘표시']} ({비교})")
    if 전체 and 줄:
        줄.insert(0, "✈️ <b>여행 환전</b>")
    return 줄


def 계좌잔액_줄(오늘) -> list:
    """🏦 일반 4,255만 · 연금 4,804만 · DC 9,922만 · ISA 1,882만"""
    계좌들 = (오늘 or {}).get("계좌") or {}
    조각 = [f"{_계좌(c)} {만원(계좌들[c])}" for c in PF._계좌_정렬(계좌들)
          if PF._숫자(계좌들.get(c)) > 0]
    return ["🏦 " + " · ".join(조각)] if 조각 else []


