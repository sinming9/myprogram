def 할일_줄(리밸런싱, 환율, 엇갈린해외: float = 0, 엇갈린미국: dict = None) -> list:
    """자산군마다 '→ ○○만원 줄이기/더 사기'. 벗어난 게 없으면 '할 일 없음'."""
    벗어남 = [r for r in 리밸런싱 or [] if abs(r["괴리"]) >= 리밸런싱_괴리]
    줄 = [f"✅ <b>할 일</b> (일반 계좌 · 목표에서 {리밸런싱_괴리:.0f}%p 넘게 벗어난 것)"]
    # 목표 합이 100 이 아니면 '○○만원 사기/줄이기' 금액이 정확하지 않습니다
    목표합 = PF._숫자((리밸런싱 or [{}])[0].get("목표합"))
    if 목표합 and abs(목표합 - 100) > 0.5:
        줄.append(f"　※ 목표 비중 합이 {목표합:.0f}% 입니다 — 앱에서 100% 로 맞추세요")
    if not 벗어남:
        return 줄 + ["　할 일 없음"]
    for r in sorted(벗어남, key=lambda r: -abs(r["괴리"])):
        금액 = PF._숫자(r.get("조정금액"))
        말 = "더 사기" if 금액 > 0 else "줄이기"
        줄.append(f"　{_안전(r['이름'])} {r['현재비중']:.0f}% (목표 {r['목표비중']:.0f})"
                 f" → {만원(금액)} {말}")
    # ★ 위에 나온 금액끼리는 합이 0 이 아닙니다(예: 국내 -498만, 해외 +249만).
    #   나머지는 5%p 안쪽이라 안 보인 항목들 몫이라, 그 합을 한 줄로 보입니다.
    안쪽 = [r for r in 리밸런싱 or [] if abs(r["괴리"]) < 리밸런싱_괴리
          and 만원(r.get("조정금액")) != "0"]
    if 안쪽:
        합 = sum(PF._숫자(r.get("조정금액")) for r in 안쪽)
        안쪽.sort(key=lambda r: -abs(PF._숫자(r.get("조정금액"))))
        줄.append(f"　그 외 항목 {증감(합)} ({리밸런싱_괴리:.0f}%p 이내: "
                 + ", ".join(f"{_안전(r['이름'])} {증감(r.get('조정금액'))}"
                             for r in 안쪽) + ")")
    해외 = next((r for r in 리밸런싱 or [] if r["이름"] == "해외주식"), None)
    달러 = (환율 or {}).get("달러") or {}
    if (해외 and 해외["괴리"] <= -리밸런싱_괴리
            and _구간말(달러.get("위치")) == "싼 편"):
        줄.append("　→ <b>해외 매수 적기</b> (달러 싼 구간 + 해외 비중 부족)")
    # 계좌 줄(US/KR/COIN)과 숫자가 안 맞아 보이는 이유를 한 줄로 (예전 판에 있던 안내)
    if PF._숫자(엇갈린해외) >= 10_000:
        줄.append(f"　※ 국내 상장 해외 ETF {만원(엇갈린해외)}은 계좌 줄에선 KR, "
                 "여기선 해외주식으로 셉니다")
    # 반대 방향 — 미국 상장이지만 주식이 아닌 것(채권·원자재·리츠 ETF 등)
    미국 = 엇갈린미국 or {}
    if PF._숫자(미국.get("합")) >= 10_000:
        줄.append(f"　※ 미국 상장 {_안전('·'.join(미국.get('자산군') or []))} "
                 f"{만원(미국['합'])}은 계좌 줄에선 US, 여기선 해외주식이 아닙니다")
    return 줄


def 신규자금_줄(배분) -> list:
    """'할 일' 아래 — 새 돈을 넣을 때 팔지 않고 어디에 얼마씩 살지.

    💵 신규자금 500만원 투입 시 (매도 없이 · 부족한 자산군에만)
    　해외주식 321만원 · 채권 75만원 · 원자재 69만원 · 리츠 35만원
    　└ 해외주식: VOO 1주 · QQQM 3주 · SCHD 11주 · DGRW 2주
    　└ 채권 TLT 5주 · 원자재 GLDM 5주 · 리츠 리얼티인컴 4주
    　검산: 매수 합계 478만원 · 남는 돈 22만원 (달러 1,364원 · 주 수는 버림)
    　매수 후 비중: 해외 45% · 국내 33% · …
    계산은 engines.portfolio.신규자금_배분 — 위의 '줄이기/더 사기' 와는 별개입니다.
    """
    if not 배분 or not 배분.get("배정"):
        return []

    def 이름(티커):
        return _안전(신규_종목이름.get(티커, 티커))

    제외글 = (f" · {'·'.join(신규_제외자산군)} 제외" if 신규_제외자산군 else "")
    줄 = [f"💵 <b>신규자금 {만원(배분['신규'])} 투입 시</b> (매도 없이{_안전(제외글)})",
         "　" + " · ".join(f"{_안전(r['이름'])} {만원(r['금액'])}" for r in 배분["배정"])]
    해외 = [m for m in 배분.get("매수") or [] if m["자산군"] == "해외주식"]
    그외 = [m for m in 배분.get("매수") or [] if m["자산군"] != "해외주식"]
    if 해외:
        줄.append("　└ 해외주식: " + " · ".join(f"{이름(m['티커'])} {m['주수']}주" for m in 해외))
    if 그외:
        줄.append("　└ " + " · ".join(f"{_안전(m['자산군'])} {이름(m['티커'])} {m['주수']}주"
                                    for m in 그외))
    if 배분.get("가격없음"):
        줄.append("　※ 시세를 못 받아 주 수를 못 낸 종목: "
                 + ", ".join(이름(t) for t in 배분["가격없음"]))
    줄.append(f"　검산: 매수 합계 {만원(배분['매수합'])} · 남는 돈 {만원(배분['남는돈'])} "
             f"(달러 {PF._숫자(배분.get('환율')):,.0f}원 · 주 수는 버림)")
    줄.append("　매수 후 비중: " + " · ".join(
        f"{_안전(str(r['이름']).replace('주식', ''))} {r['비중']:.0f}%" for r in 배분["매수후"]))
    return 줄


def _수량글(x) -> str:
    q = PF._숫자(x.get("수량"))
    if x.get("짧은이름") == "엔":
        return f"{q / 1e4:,.0f}만엔" if q >= 1e4 else f"{q:,.0f}엔"
    return f"{x.get('코드', '')} {q:,.0f}".strip()


def 외화_줄(외화들) -> list:
    """엔 50만엔 · 421만원 · 매입 860원 대비 -2.1%"""
    if not 외화들:
        return []
    줄 = ["💴 <b>외화 보유</b>"]
    for x in 외화들:
        꼬리 = (f" · 매입 {x['평균표시']} 대비 {x['수익률']:+.1f}%"
              if x.get("수익률") is not None else "")
        줄.append(f"　{x['짧은이름']} {_수량글(x)} · {만원(x['평가액'])}{꼬리}")
    return 줄


def 여행_줄(여행들, 전체=True) -> list:
    """토요일판은 전체, 평일판은 '오늘이 평균보다 쌀 때' 만 한 줄."""
    줄 = []
    for t in 여행들 or []:
        목표, 모음 = PF._숫자(t.get("목표")), PF._숫자(t.get("모음"))
        평균, 오늘 = PF._숫자(t.get("평균")), PF._숫자(t.get("오늘"))
        싸다 = 오늘 > 0 and 평균 > 0 and 오늘 < 평균
        if not 전체:
            if 싸다:
                # ★ '<' 를 그대로 쓰면 텔레그램이 태그로 읽어 메시지 전체를
                #   거부합니다(2026-10-20 실제로 발송 실패). 글로 씁니다.
                줄.append(f"✈️ {_안전(t['이름'])} 환전 적기 — 오늘 {t['오늘표시']}, "
                         f"평균 {t['평균표시']}보다 쌈")
            continue
        진행 = f" ({모음 / 목표 * 100:.0f}%)" if 목표 > 0 else ""
        줄.append(f"　{_안전(t['이름'])} {t['코드']} {모음:,.0f} / {목표:,.0f}{진행}")
        if 평균 > 0 and 오늘 > 0:
            비교 = ("지금보다 싸게 모음" if 평균 < 오늘
                  else "지금이 평균보다 쌈 — 더 바꿔 둘 때" if 싸다 else "평균과 같음")
            줄.append(f"　　평균 {t['평균표시']} · 오늘 {t['오늘표시']} ({비교})")
    if 전체 and 줄:
        줄.insert(0, "✈️ <b>여행 환전</b>")
    return 줄


def 계좌잔액_줄(오늘) -> list:
    """🏦 일반 4,255만 · 연금 4,804만 · DC 9,922만 · ISA 1,882만"""
    계좌들 = (오늘 or {}).get("계좌") or {}
    조각 = [f"{_계좌(c)} {만원(계좌들[c])}" for c in PF._계좌_정렬(계좌들)
          if PF._숫자(계좌들.get(c)) > 0]
    return ["🏦 " + " · ".join(조각)] if 조각 else []


