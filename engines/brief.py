def 평일판(자료: dict, 오늘날짜: str) -> str:
    오늘 = 자료.get("오늘") or {}
    어제 = 자료.get("어제") or {}
    줄 = [f"☀️ <b>{_날짜머리(오늘날짜)}</b>", ""]
    줄 += 총자산_줄(오늘)
    줄 += 변화_줄(오늘, 어제, 자료.get("움직임_하루"), _어제라벨(오늘, 어제))
    for 조각 in (종목_줄(자료.get("움직임_하루"), "많이 움직인 종목"),
                계좌변동_줄(오늘, 어제),
                환율_줄(자료.get("환율"), 자료.get("외화")),
                여행_줄(자료.get("여행"), 전체=False),
                비중_줄(자료.get("리밸런싱"))):
        if 조각:
            줄 += [""] + 조각
    return "\n".join(줄)


def 주간판(자료: dict, 오늘날짜: str) -> str:
    오늘 = 자료.get("오늘") or {}
    줄 = [f"📅 <b>{_날짜머리(오늘날짜)} 한 주 마무리</b>", ""]
    줄 += 할일_줄(자료.get("리밸런싱"), 자료.get("환율"))
    줄 += [""] + 총자산_줄(오늘, 누적액=True)
    줄 += 변화_줄(오늘, 자료.get("주초"), 자료.get("움직임_주간"), "이번 주")
    for 조각 in (종목_줄(자료.get("움직임_주간"), "이번 주 많이 움직인 종목"),
                외화_줄(자료.get("외화")),
                여행_줄(자료.get("여행"), 전체=True),
                계좌잔액_줄(오늘)):
        if 조각:
            줄 += [""] + 조각
    return "\n".join(줄)


def 브리핑_만들기(자료: dict, 오늘날짜: str = None) -> tuple:
    """(본문, 모드). 모드 = "주간"(토요일) / "평일"."""
    오늘날짜 = 오늘날짜 or date.today().isoformat()
    모드 = 오늘_모드(오늘날짜)
    본문 = 주간판(자료, 오늘날짜) if 모드 == "주간" else 평일판(자료, 오늘날짜)
    return 본문, 모드
