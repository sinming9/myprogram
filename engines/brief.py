def 볼것_찾기(자산, 환율들, 임계=None) -> list:
    """오늘 알릴 만한 일들을 문장으로 만들어 돌려줍니다.

    자산 = {"오늘", "어제", "최고", "신호"} (없는 건 생략 가능)
    환율들 = [{"이름", "위치", "이전위치", "구간일수"}, …]

    ★ 환율은 '진입한 날' 에만 넣습니다(이전위치와 견줘 판단).
      계속 머무는 동안은 여기 안 넣고 주간 결산에서만 언급합니다.
    """
    임계 = {**기본_임계, **(임계 or {})}
    볼것 = []

    오늘 = (자산 or {}).get("오늘") or {}
    어제 = (자산 or {}).get("어제") or {}
    총액 = PF._숫자(오늘.get("총액"))
    옛총액 = PF._숫자(어제.get("총액"))
    if 옛총액 > 0 and 총액 > 0:
        변동 = (총액 - 옛총액) / 옛총액 * 100
        if abs(변동) >= 임계["자산_하루_변동"]:
            방향 = "올랐습니다" if 변동 > 0 else "내렸습니다"
            부호 = "+" if 변동 > 0 else "-"
            볼것.append(f"자산이 하루 만에 {abs(변동):.1f}% {방향} "
                      f"({부호}{PF.금액_한글(총액 - 옛총액)})")

    최고 = PF._숫자((자산 or {}).get("최고"))
    최고날 = (자산 or {}).get("최고날")
    if 총액 > 0 and 최고 > 0 and 총액 > 최고:
        꼬리 = f" (이전 최고 {_짧은날(최고날)})" if 최고날 else ""
        볼것.append(f"자산 역대 최고 경신{꼬리}")

    for 통화 in 환율들 or []:
        위치 = 통화.get("위치")
        이전 = 통화.get("이전위치")
        if 위치 is None:
            continue
        쌈 = 위치 <= 임계["환율_싼구간"]
        비쌈 = 위치 >= 임계["환율_비싼구간"]
        if not (쌈 or 비쌈):
            continue
        # 어제 이미 그 구간이었으면 '새 소식' 이 아닙니다
        이전쌈 = 이전 is not None and 이전 <= 임계["환율_싼구간"]
        이전비쌈 = 이전 is not None and 이전 >= 임계["환율_비싼구간"]
        if (쌈 and 이전쌈) or (비쌈 and 이전비쌈):
            continue
        말 = "1년 최저 구간에 들어왔습니다" if 쌈 else "1년 최고 구간에 들어왔습니다"
        볼것.append(f"{통화['이름']}가 {말} (하위 {위치:.0f}%)"
                  if 쌈 else f"{통화['이름']}가 {말} (상위 {100 - 위치:.0f}%)")

    for 신호 in (자산 or {}).get("신호") or []:
        방향 = "많습니다" if 신호["괴리"] > 0 else "적습니다"
        볼것.append(f"{신호['이름']} 비중이 목표보다 "
                  f"{abs(신호['괴리']):.0f}%p {방향}")
    return 볼것


def _짧은날(값) -> str:
    조각 = str(값 or "").split("-")
    if len(조각) != 3:
        return str(값 or "")
    try:
        return f"{int(조각[1])}/{int(조각[2])}"
    except ValueError:
        return str(값)


