def 브리핑_만들기(자산: dict, 환율들: list, 오늘날짜: str = None,
            임계: dict = None, 신호범위: str = "") -> tuple:
    """(본문, 모드). 모드 = "조용"/"이벤트"/"주간"/"월간"

    자산 = {오늘, 어제, 주초, 월초, 지난달, 연초, 최고, 최고날, 기여,
           신호, 엇갈린해외}
    환율들 = [{이름, 짧은이름, 표시가, 위치, 이전위치, 하루변화, 체감,
              구간일수}, …]  — 첫 번째가 가장 중요한 통화(달러)입니다.
    """
    오늘날짜 = 오늘날짜 or date.today().isoformat()
    달력모드 = 오늘_모드(오늘날짜)
    볼것 = 볼것_찾기(자산, 환율들, 임계)
    모드 = 달력모드 if 달력모드 != "평일" else ("이벤트" if 볼것 else "조용")

    오늘 = (자산 or {}).get("오늘") or {}
    어제 = (자산 or {}).get("어제") or {}

    # ---------- 조용한 날: 네댓 줄 ----------
    if 모드 == "조용":
        줄 = [f"☀️ <b>{_날짜머리(오늘날짜)}</b>", "", "✅ 특별한 변화 없습니다", ""]
        줄.append(자산_한줄(오늘, 어제))
        원금 = PF._숫자(오늘.get("원금"))
        총액 = PF._숫자(오늘.get("총액"))
        if 원금 > 0 and 총액 > 0:
            수익률 = (총액 / 원금 - 1) * 100
            줄.append(f"　원금 대비 {'+' if 수익률 >= 0 else ''}{수익률:.1f}%")
        for 통화 in (환율들 or [])[:1]:
            줄.append(환율_한줄(통화))
        나머지 = [f"{t['짧은이름']} {t['표시가']}" for t in (환율들 or [])[1:]]
        if 나머지:
            줄.append("　" + " · ".join(나머지))
        return "\n".join(줄), 모드

    # ---------- 이벤트·주간·월간: 펼쳐서 ----------
    머리 = {"이벤트": f"☀️ <b>{_날짜머리(오늘날짜)}</b>",
          "주간": f"📅 <b>{_날짜머리(오늘날짜)} 한 주 마무리</b>",
          "월간": f"📅 <b>{_날짜머리(오늘날짜)} 지난달 결산</b>"}[모드]
    줄 = [머리, ""]

    if 볼것:
        # ★ 다섯 개를 한꺼번에 나열하면 하나하나의 무게가 사라집니다.
        #   위에서 세 개만 보여주고, 나머지는 개수만 알립니다
        #   (상세 블록을 읽으면 어차피 다 나옵니다).
        줄.append(f"⚠️ <b>볼 것이 {len(볼것)}가지</b>")
        for x in 볼것[:3]:
            줄.append(f"• {_안전(x)}")
        if len(볼것) > 3:
            줄.append(f"• 그 밖에 {len(볼것) - 3}가지 (아래 참고)")
        줄.append("")
    elif 모드 in ("주간", "월간"):
        줄.append("✅ 특별한 변화 없이 지나갔습니다")
        줄.append("")

    # 이벤트 날은 평일과 같은 분량, 주간·월간은 결산 줄까지
    줄.extend(자산_자세히(자산, 달력모드))
    줄.extend(계좌_블록(오늘, 어제))
    줄.append("")
    줄.extend(환율_자세히(환율들))
    줄.extend(신호_블록((자산 or {}).get("신호"), 신호범위,
                    PF._숫자((자산 or {}).get("엇갈린해외"))))

    머문것 = [f"{t['이름']} {t.get('구간일수')}일째"
           for t in (환율들 or [])
           if 모드 in ("주간", "월간") and t.get("구간일수", 0) >= 2]
    if 머문것:
        줄.append("")
        줄.append("　머무는 중: " + " · ".join(머문것))
    return "\n".join(줄), 모드
