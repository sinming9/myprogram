def 총자산_줄(오늘, 누적액=False) -> list:
    총액 = PF._숫자(오늘.get("총액"))
    률, 액 = _수익률(오늘)
    꼬리 = ""
    if 률 is not None:
        꼬리 = f" · 원금 대비 {률:+.1f}%"
        if 누적액:
            꼬리 += f" ({증감(액)})"
    return [f"💰 <b>총자산 {만원(총액)}</b>{꼬리}"]


def 변화_줄(오늘, 기준, 움직임, 이름) -> list:
    """'어제 대비 ▼206만원 (-0.98%)' + '└ 추가 매수 0 · 시장 변동 -206만원'."""
    if not 기준 or PF._숫자(기준.get("총액")) <= 0:
        return [f"　{이름} 비교 기록이 아직 없습니다"]
    옛 = PF._숫자(기준.get("총액"))
    차이 = PF._숫자(오늘.get("총액")) - 옛
    화살 = "▲" if 차이 > 0 else ("▼" if 차이 < 0 else "―")
    매수 = PF._숫자((움직임 or {}).get("매수합"))
    시장 = 차이 - 매수
    머리 = 이름 if 이름 == "이번 주" else f"{이름} 대비"
    return [f"　{머리} {화살}{만원(차이)} ({차이 / 옛 * 100:+.2f}%)",
            f"　└ 추가 매수 {증감(매수)} · 시장 변동 {증감(시장)}"]


def 종목_줄(움직임, 제목) -> list:
    """시장 변동이 ±기준 이상인 종목만, 큰 것부터 최대 N개.

    ★ 매수한 금액은 빼고 '시세로 움직인 금액' 으로 고릅니다. 그러지 않으면
      300만원어치 산 종목이 '+300만원 움직였다' 로 맨 위에 옵니다.
    """
    목록 = [r for r in (움직임 or {}).get("목록") or []
          if abs(PF._숫자(r.get("시장분"))) >= 종목_표시_금액]
    목록.sort(key=lambda r: -abs(r["시장분"]))
    if not 목록:
        return []
    줄 = [f"📊 {제목}"]
    for r in 목록[:종목_최대]:
        줄.append(f"　{_안전(str(r['이름'])[:14])} [{_계좌(r['계좌'])}] "
                 f"{증감(r['시장분'])}")
    return 줄


def 계좌변동_줄(오늘, 기준) -> list:
    """±1% 또는 ±50만원 이상 움직인 계좌. 없으면 '계좌 변동 미미'."""
    지금 = (오늘 or {}).get("계좌") or {}
    옛 = (기준 or {}).get("계좌") or {}
    if not 옛:
        return []
    큰것 = []
    for 계좌 in PF._계좌_정렬(지금):
        a, b = PF._숫자(지금.get(계좌)), PF._숫자(옛.get(계좌))
        if b <= 0:
            continue
        차, 률 = a - b, (a - b) / b * 100
        if abs(률) >= 계좌_표시_비율 or abs(차) >= 계좌_표시_금액:
            큰것.append(f"{_계좌(계좌)} {증감(차)} ({률:+.1f}%)")
    return ["🏦 " + (" · ".join(큰것) if 큰것 else "계좌 변동 미미")]


def 환율_줄(환율, 외화들) -> list:
    """달러 1,355원 ▼12원(싼 편) · 엔 860원 ▼2원(보유 -2.1%) · 싱달 1,061원.

    '▼12원' 은 전날 대비 변화입니다(예전 판의 '어제 ▼12원' 을 한 줄에 맞춰 줄임).
    """
    조각 = []
    for 이름 in 환율_보일것:
        t = (환율 or {}).get(이름)
        if not t:
            continue
        꼬리 = []
        구간 = _구간말(t.get("위치"))
        if 구간:
            꼬리.append(구간)
        보유 = [x for x in 외화들 or [] if x.get("짧은이름") == 이름]
        if 보유 and 보유[0].get("수익률") is not None:
            꼬리.append(f"보유 {보유[0]['수익률']:+.1f}%")
        변화 = f" {t['하루변화']}" if t.get("하루변화") else ""
        조각.append(f"{이름} {t['표시가']}{변화}"
                  + (f"({', '.join(꼬리)})" if 꼬리 else ""))
    return ["💱 " + " · ".join(조각)] if 조각 else []


def 환율_더보기(환율) -> list:
    """주간판에만 — '100만원 → 738달러' 와 '머무는 중: 달러 싼 구간 5일째'."""
    줄 = []
    달러 = (환율 or {}).get("달러") or {}
    if 달러.get("체감"):
        줄.append(f"　100만원 → {달러['체감']}")
    머문것 = [f"{이름} {'싼' if (t.get('위치') or 50) <= 50 else '비싼'} 구간 "
           f"{t.get('구간일수')}일째"
           for 이름 in 환율_보일것 for t in [(환율 or {}).get(이름) or {}]
           if t.get("구간일수", 0) >= 2 and t.get("위치") is not None]
    if 머문것:
        줄.append("　머무는 중: " + " · ".join(머문것))
    return 줄


def 특이사항_줄(자료) -> list:
    """자산 급변 · 역대 최고 경신 · 환율 구간 진입. 없으면 빈 목록(섹션 생략).

    ★ 리밸런싱(비중 초과/부족)은 넣지 않습니다 — '할 일' 과 겹칩니다.
    ★ 환율은 '들어온 날' 만 알립니다. 어제도 그 구간이었으면 새 소식이 아닙니다.
    """
    오늘 = 자료.get("오늘") or {}
    어제 = 자료.get("어제") or {}
    총액, 옛 = PF._숫자(오늘.get("총액")), PF._숫자(어제.get("총액"))
    항목 = []
    if 옛 > 0 and 총액 <= 0:
        항목.append("자산이 0원으로 나옵니다 — 시세 조회 문제일 수 있습니다")
    elif 옛 > 0:
        # ★ 넣은 돈(추가 매수)은 빼고 '시장이 움직인 만큼' 으로 판단합니다.
        #   외화를 처음 등록하거나 큰돈을 넣은 날 '자산 급변' 이 뜨지 않게.
        매수 = PF._숫자((자료.get("움직임_하루") or {}).get("매수합"))
        변동 = (총액 - 옛 - 매수) / 옛 * 100
        if abs(변동) >= 자산_급변:
            간격 = _간격(오늘, 어제)
            언제 = "하루 만에" if 간격 == 1 else f"{간격}일 만에"
            항목.append(f"자산이 {언제} {abs(변동):.1f}% "
                      f"{'올랐습니다' if 변동 > 0 else '내렸습니다'} "
                      f"(시장 변동 {증감(총액 - 옛 - 매수)})")
    최고 = PF._숫자(자료.get("최고"))
    if 총액 > 0 and 최고 > 0 and 총액 > 최고:
        날 = 자료.get("최고날")
        항목.append("자산 역대 최고 경신" + (f" (이전 최고 {_짧은날(날)})" if 날 else ""))
    for 이름 in 환율_보일것:
        t = (자료.get("환율") or {}).get(이름) or {}
        위치, 이전 = t.get("위치"), t.get("이전위치")
        if 위치 is None:
            continue
        쌈, 비쌈 = 위치 <= 환율_싼구간, 위치 >= 환율_비싼구간
        if not (쌈 or 비쌈):
            continue
        if 이전 is not None and ((쌈 and 이전 <= 환율_싼구간)
                                 or (비쌈 and 이전 >= 환율_비싼구간)):
            continue
        if 쌈:
            꼬리 = f"하위 {round(위치)}%" if round(위치) >= 1 else "1년 최저 수준"
            항목.append(f"{이름} 1년 최저 구간 진입 ({꼬리})")
        else:
            꼬리 = (f"상위 {round(100 - 위치)}%" if round(100 - 위치) >= 1
                  else "1년 최고 수준")
            항목.append(f"{이름} 1년 최고 구간 진입 ({꼬리})")
    if not 항목:
        return []
    return ["⚠️ <b>특이사항</b>"] + [f"• {_안전(x)}" for x in 항목]


def 코인_줄(오늘, 기준, 이름="어제") -> list:
    """🪙 코인 491만원 ▼1.05% (-5만원) · 비트코인 -5만원

    주말에도 움직이는 건 코인뿐이라 일요일·월요일 판에 넣습니다.
    """
    def 합(스냅):
        return sum(PF._숫자((시장 or {}).get("COIN"))
                   for 시장 in ((스냅 or {}).get("계좌시장") or {}).values())
    지금, 옛 = 합(오늘), 합(기준)
    if 지금 <= 0 and 옛 <= 0:
        return []
    글 = f"🪙 코인 {만원(지금)}"
    if 옛 > 0:
        차 = 지금 - 옛
        글 += f"  {이름} 대비 {증감(차)} ({차 / 옛 * 100:+.2f}%)"
    # 코인별 — 종목 칸에 시장(COIN) 이 적힌 기록에서만 고를 수 있습니다
    움 = PF.종목_움직임(오늘, 기준)
    코인들 = {k: v for k, v in ((오늘 or {}).get("종목") or {}).items()
            if v.get("시장") == "COIN"}
    이름들 = {v.get("이름") for v in 코인들.values()}
    조각 = [f"{_안전(r['이름'])} {증감(r['시장분'])}" for r in 움["목록"]
          if r["이름"] in 이름들 and abs(r["시장분"]) >= 코인_종목_금액][:3]
    줄 = [글]
    if 조각:
        줄.append("　" + " · ".join(조각))
    return 줄


def 일반_시장_줄(오늘, 기준) -> list:
    """일반 계좌를 US/KR/COIN 으로 쪼갠 금액과 증감 (예전 판의 계좌 블록).

    ★ 총액이 왜 움직였는지(환율 때문인지 코인 때문인지)를 그 자리에서
      보려고 넣었던 줄입니다. 개편으로 빠졌다가 되살렸습니다.
    """
    쪼갬 = ((오늘 or {}).get("계좌시장") or {}).get("일반") or {}
    옛쪼갬 = ((기준 or {}).get("계좌시장") or {}).get("일반") or {}
    있는것 = [m for m in ["US", "KR", "COIN"] + sorted(set(쪼갬) - {"US", "KR", "COIN"})
           if PF._숫자(쪼갬.get(m)) > 0]
    if len(있는것) < 2:
        return []
    조각 = []
    for m in 있는것:
        칸, 옛칸 = PF._숫자(쪼갬.get(m)), PF._숫자(옛쪼갬.get(m))
        차 = 증감(칸 - 옛칸) if 옛칸 > 0 else "0"
        조각.append(f"{_안전(m)} {만원(칸)}" + (f" ({차})" if 차 != "0" else ""))
    return ["　└ 일반: " + " · ".join(조각)]


def 결산_줄(자료) -> list:
    """매달 1일 — '지난달 결산'. 지난달 대비 · 올해(1월 1일엔 작년 한 해) · 원금 대비."""
    오늘 = 자료.get("오늘") or {}
    총액 = PF._숫자(오늘.get("총액"))
    줄 = ["📅 <b>지난달 결산</b>"]
    쓴날 = set()
    for 이름, 기준 in (("지난달", 자료.get("지난달")), ("올해", 자료.get("연초"))):
        날 = str((기준 or {}).get("날짜") or "")
        옛 = PF._숫자((기준 or {}).get("총액"))
        if not 날 or 날 in 쓴날 or 옛 <= 0:
            continue
        쓴날.add(날)
        차 = 총액 - 옛
        줄.append(f"　{_짧은날(날)} 대비 ({이름})  {'▲' if 차 > 0 else '▼'}{만원(차)} "
                 f"({차 / 옛 * 100:+.2f}%)")
    률, 액 = _수익률(오늘)
    if 률 is not None:
        줄.append(f"　원금 대비 {률:+.1f}% ({증감(액)})")
    return 줄 if len(줄) > 1 else []


def 비중_줄(리밸런싱) -> list:
    """⚖️ 국내 30%(목표 25) · 해외 59%(목표 50)"""
    이름별 = {r["이름"]: r for r in 리밸런싱 or []}
    조각 = []
    for 자산군, 짧게 in (("국내주식", "국내"), ("해외주식", "해외")):
        r = 이름별.get(자산군)
        if r:
            조각.append(f"{짧게} {r['현재비중']:.0f}%(목표 {r['목표비중']:.0f})")
    if not 조각:
        return []
    return [f"⚖️ 비중({'·'.join(리밸런싱_계좌)}): " + " · ".join(조각)]


def 할일_줄(리밸런싱, 환율, 엇갈린해외: float = 0) -> list:
    """자산군마다 '→ ○○만원 줄이기/더 사기'. 벗어난 게 없으면 '할 일 없음'."""
    벗어남 = [r for r in 리밸런싱 or [] if abs(r["괴리"]) >= 리밸런싱_괴리]
    줄 = [f"✅ <b>할 일</b> (일반 계좌 · 목표에서 {리밸런싱_괴리:.0f}%p 넘게 벗어난 것)"]
    # 목표 합이 100 이 아니면 '○○만원 사기/줄이기' 금액이 정확하지 않습니다
    목표합 = PF._숫자((리밸런싱 or [{}])[0].get("목표합"))
    if 목표합 and abs(목표합 - 100) > 0.5:
        줄.append(f"　※ 목표 비중 합이 {목표합:.0f}% 입니다 — 앱에서 100% 로 맞추세요")
    if not 벗어남:
        return 줄 + ["　할 일 없음"]
    for r in sorted(벗어남, key=lambda r: -abs(r["괴리"])):
        금액 = PF._숫자(r.get("조정금액"))
        말 = "더 사기" if 금액 > 0 else "줄이기"
        줄.append(f"　{_안전(r['이름'])} {r['현재비중']:.0f}% (목표 {r['목표비중']:.0f})"
                 f" → {만원(금액)} {말}")
    해외 = next((r for r in 리밸런싱 or [] if r["이름"] == "해외주식"), None)
    달러 = (환율 or {}).get("달러") or {}
    if (해외 and 해외["괴리"] <= -리밸런싱_괴리
            and _구간말(달러.get("위치")) == "싼 편"):
        줄.append("　→ <b>해외 매수 적기</b> (달러 싼 구간 + 해외 비중 부족)")
    # 계좌 줄(US/KR/COIN)과 숫자가 안 맞아 보이는 이유를 한 줄로 (예전 판에 있던 안내)
    if PF._숫자(엇갈린해외) >= 10_000:
        줄.append(f"　※ 국내 상장 해외 ETF {만원(엇갈린해외)}은 계좌 줄에선 KR, "
                 "여기선 해외주식으로 셉니다")
    return 줄


def _수량글(x) -> str:
    q = PF._숫자(x.get("수량"))
    if x.get("짧은이름") == "엔":
        return f"{q / 1e4:,.0f}만엔" if q >= 1e4 else f"{q:,.0f}엔"
    return f"{x.get('코드', '')} {q:,.0f}".strip()


def 외화_줄(외화들) -> list:
    """엔 50만엔 · 421만원 · 매입 860원 대비 -2.1%"""
    if not 외화들:
        return []
    줄 = ["💴 <b>외화 보유</b>"]
    for x in 외화들:
        꼬리 = (f" · 매입 {x['평균표시']} 대비 {x['수익률']:+.1f}%"
              if x.get("수익률") is not None else "")
        줄.append(f"　{x['짧은이름']} {_수량글(x)} · {만원(x['평가액'])}{꼬리}")
    return 줄


def 여행_줄(여행들, 전체=True) -> list:
    """토요일판은 전체, 평일판은 '오늘이 평균보다 쌀 때' 만 한 줄."""
    줄 = []
    for t in 여행들 or []:
        목표, 모음 = PF._숫자(t.get("목표")), PF._숫자(t.get("모음"))
        평균, 오늘 = PF._숫자(t.get("평균")), PF._숫자(t.get("오늘"))
        싸다 = 오늘 > 0 and 평균 > 0 and 오늘 < 평균
        if not 전체:
            if 싸다:
                # ★ '<' 를 그대로 쓰면 텔레그램이 태그로 읽어 메시지 전체를
                #   거부합니다(2026-10-20 실제로 발송 실패). 글로 씁니다.
                줄.append(f"✈️ {_안전(t['이름'])} 환전 적기 — 오늘 {t['오늘표시']}, "
                         f"평균 {t['평균표시']}보다 쌈")
            continue
        진행 = f" ({모음 / 목표 * 100:.0f}%)" if 목표 > 0 else ""
        줄.append(f"　{_안전(t['이름'])} {t['코드']} {모음:,.0f} / {목표:,.0f}{진행}")
        if 평균 > 0 and 오늘 > 0:
            비교 = ("지금보다 싸게 모음" if 평균 < 오늘
                  else "지금이 평균보다 쌈 — 더 바꿔 둘 때" if 싸다 else "평균과 같음")
            줄.append(f"　　평균 {t['평균표시']} · 오늘 {t['오늘표시']} ({비교})")
    if 전체 and 줄:
        줄.insert(0, "✈️ <b>여행 환전</b>")
    return 줄


def 계좌잔액_줄(오늘) -> list:
    """🏦 일반 4,255만 · 연금 4,804만 · DC 9,922만 · ISA 1,882만"""
    계좌들 = (오늘 or {}).get("계좌") or {}
    조각 = [f"{_계좌(c)} {만원(계좌들[c])}" for c in PF._계좌_정렬(계좌들)
          if PF._숫자(계좌들.get(c)) > 0]
    return ["🏦 " + " · ".join(조각)] if 조각 else []


