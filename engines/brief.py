    모드 = 오늘_모드(오늘날짜)
    본문 = {"주간": 주간판, "짧은": 짧은판}.get(모드, 평일판)(자료, 오늘날짜)
    if 결산일인가(오늘날짜):
        결산 = 결산_줄(자료)
