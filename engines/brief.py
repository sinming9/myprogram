def 총자산_줄(오늘, 누적액=False) -> list:
    총액 = PF._숫자(오늘.get("총액"))
    률, 액 = _수익률(오늘)
    꼬리 = ""
    if 률 is not None:
        꼬리 = f" · 원금 대비 {률:+.1f}%"
        if 누적액:
            꼬리 += f" ({증감(액)})"
    return [f"💰 <b>총자산 {만원(총액)}</b>{꼬리}"]


def 변화_줄(오늘, 기준, 움직임, 이름) -> list:
    """'어제 대비 ▼206만원 (-0.98%)' + '└ 입출금 0 · 시장 변동 -206만원'.

    입출금: + 는 입금·매수, - 는 출금·매도 (예전 이름 '추가 매수').
    """
    if not 기준 or PF._숫자(기준.get("총액")) <= 0:
        return [f"　{이름} 비교 기록이 아직 없습니다"]
    옛 = PF._숫자(기준.get("총액"))
    차이 = PF._숫자(오늘.get("총액")) - 옛
    화살 = "▲" if 차이 > 0 else ("▼" if 차이 < 0 else "―")
    매수 = PF._숫자((움직임 or {}).get("매수합"))
    시장 = 차이 - 매수
    머리 = 이름 if 이름 == "이번 주" else f"{이름} 대비"
    return [f"　{머리} {화살}{만원(차이)} ({차이 / 옛 * 100:+.2f}%)",
            f"　└ 입출금 {증감(매수)} · 시장 변동 {증감(시장)}"]


def 종목_줄(움직임, 제목) -> list:
    """시장 변동이 ±기준 이상인 종목만, 큰 것부터 최대 N개.

    ★ 매수한 금액은 빼고 '시세로 움직인 금액' 으로 고릅니다. 그러지 않으면
      300만원어치 산 종목이 '+300만원 움직였다' 로 맨 위에 옵니다.
    """
    목록 = [r for r in (움직임 or {}).get("목록") or []
          if abs(PF._숫자(r.get("시장분"))) >= 종목_표시_금액]
    목록.sort(key=lambda r: -abs(r["시장분"]))
    if not 목록:
        return []
    # 라벨에 기준을 적습니다 — 한 종목만 나오는 날 '왜 하나뿐인지' 가 보이게
    줄 = [f"📊 {제목} (금액 기준 · ±{종목_표시_금액 // 10_000}만원 이상)"]
    for r in 목록[:종목_최대]:
        줄.append(f"　{_종목이름(r['이름'])} [{_계좌(r['계좌'])}] "
                 f"{증감(r['시장분'])}")
    return 줄


계좌_늘보일것 = ["일반", "연금저축", "퇴직연금(DC)", "ISA"]   # 변동이 작아도 늘 보이는 계좌


def 계좌변동_줄(오늘, 기준) -> list:
    """🏦 일반 +12만원 (+0.3%) · 연금 -5만원 (-0.1%) · DC 0 (+0.0%) · ISA ...

    ★ 예전에는 ±1% 또는 ±50만원 이상 움직인 계좌만 보여서 연금처럼 조용한
      계좌가 빠졌습니다. 이제 일반·연금·DC·ISA 는 늘 보이고, 그 밖의 계좌
      (외화 등)도 금액이 있으면 뒤에 붙입니다. 그래서 줄의 합이 총자산
      변화와 맞습니다.
    """
    지금 = (오늘 or {}).get("계좌") or {}
    옛 = (기준 or {}).get("계좌") or {}
    if not 옛:
        return []
    이름들 = PF._계좌_정렬(set(지금) | set(옛) | set(계좌_늘보일것))
    조각 = []
    for 계좌 in 이름들:
        a, b = PF._숫자(지금.get(계좌)), PF._숫자(옛.get(계좌))
        if a <= 0 and b <= 0:
            continue                       # 없는 계좌는 늘보일것이어도 생략
        차 = a - b
        if 계좌 not in 계좌_늘보일것 and b > 0 and 증감(차) == "0":
            continue                       # 그 밖의 계좌(외화 등)는 움직였을 때만
        률 = f" ({차 / b * 100:+.1f}%)" if b > 0 else " (새로)"
        조각.append(f"{_계좌(계좌)} {증감(차)}{률}")
    return ["🏦 " + " · ".join(조각)] if 조각 else []


def 환율_줄(환율, 외화들, 보유표시=True) -> list:
    """달러 1,355원 ▼12원(싼 편) · 엔 860원 ▼2원(보유 -2.1%) · 싱달 1,061원.

    '▼12원' 은 전날 대비 변화입니다(예전 판의 '어제 ▼12원' 을 한 줄에 맞춰 줄임).
    보유표시=False — 주간판은 '외화 보유' 섹션에 같은 수익률이 있어 뺍니다.
    """
    if not 보유표시:
        외화들 = []
    조각 = []
    for 이름 in 환율_보일것:
        t = (환율 or {}).get(이름)
        if not t:
            continue
        꼬리 = []
        구간 = _구간말(t.get("위치"))
        if 구간:
            꼬리.append(구간)
        보유 = [x for x in 외화들 or [] if x.get("짧은이름") == 이름]
        if 보유 and 보유[0].get("수익률") is not None:
            꼬리.append(f"보유 {보유[0]['수익률']:+.1f}%")
        변화 = f" {t['하루변화']}" if t.get("하루변화") else ""
        조각.append(f"{이름} {t['표시가']}{변화}"
                  + (f"({', '.join(꼬리)})" if 꼬리 else ""))
    return ["💱 " + " · ".join(조각)] if 조각 else []


def 환율_더보기(환율) -> list:
    """주간판에만 — '100만원 → 738달러' 와 '머무는 중: 달러 싼 구간 5일째'."""
    줄 = []
    달러 = (환율 or {}).get("달러") or {}
    if 달러.get("체감"):
        줄.append(f"　100만원 → {달러['체감']}")
