"""
==========================================================================
아침 브리핑 — 평일판 / 토요일판(주간 요약)
==========================================================================
[이 모듈이 하는 것]
  러너(scripts/morning_brief.py)가 모아 준 숫자로 텔레그램 글을 조립만
  합니다. 시세·환율을 받거나 기록을 저장하는 일은 하지 않습니다.

[두 가지 판]
  평일판 (토요일 외 매일) — 어제와 비교한 '오늘 뭐가 달라졌나'
  토요일판              — 한 주 마무리: 할 일(리밸런싱) → 자산 → 주간 변화
                          → 외화 · 여행 환전 → 계좌별 잔액

[공통 규칙]
  · 금액은 만원 단위로 반올림 (1만원 미만은 0)
  · 환율은 달러 · 엔 · 싱가포르 달러만
  · 매수가 없는 날도 '추가 매수 0' 을 씁니다
  · 종목 옆에 계좌를 짧게 [일반/연금/DC/ISA]

[이 파일은 streamlit 을 쓰지 않습니다]
==========================================================================
"""

모듈버전 = "2026-10-17"

from datetime import date

from engines import portfolio as PF

# ==========================================================================
# ▼▼▼ 기준값 — 여기 숫자만 고치면 됩니다 ▼▼▼
# ==========================================================================
종목_표시_금액 = 200_000          # 많이 움직인 종목: ±20만원 이상만
종목_최대 = 5                     # 많이 움직인 종목: 최대 몇 개
계좌_표시_비율 = 1.0              # 큰 변동 계좌: ±1% 이상이거나
계좌_표시_금액 = 500_000          #               ±50만원 이상
리밸런싱_괴리 = 5.0               # 목표에서 이만큼(%p) 벗어나면 '할 일'
리밸런싱_계좌 = ["일반"]          # 리밸런싱·비중은 이 계좌들만
기본_목표비중 = {"국내주식": 25, "해외주식": 50}   # 앱에 저장된 목표가 없을 때
환율_보일것 = ["달러", "엔", "싱달"]                # 이 순서로 한 줄
환율_싼구간 = 15.0                # 1년 범위 하위 N% 이하 = 싼 편
환율_비싼구간 = 85.0              # 상위 N% 이상 = 비싼 편
# 싱가포르 여행 목표액 등 '값' 은 코드가 아니라 앱(자산배분 → 외화·여행)에서
# 넣습니다. 여기는 '보여 주는 기준' 만 둡니다.
# ==========================================================================

요일이름 = ["월", "화", "수", "목", "금", "토", "일"]

계좌_짧게 = {"일반": "일반", "연금저축": "연금", "퇴직연금(DC)": "DC", "IRP": "IRP",
          "ISA": "ISA", "거래소·지갑": "거래소", "외화": "외화", "기타": "기타"}

# 예전 이름 — 러너의 숫자 점검·리밸런싱이 아직 이 이름으로 읽습니다
기본_임계 = {"리밸런싱_괴리": 리밸런싱_괴리,
          "환율_싼구간": 환율_싼구간, "환율_비싼구간": 환율_비싼구간}


