def 배당_진단(종목들: list) -> dict:
    전체 = sum(s["평가액"] for s in 종목들) or 1.0
    배당 = sum(s.get("연배당", 0) for s in 종목들)
    배당종목 = [s for s in 종목들 if s.get("연배당", 0) > 0]
    배당자산 = sum(s["평가액"] for s in 배당종목)
    return {
        "연배당": 배당,
        "배당수익률": 배당 / 전체 * 100,
        "배당종목수": len(배당종목),
        "배당자산비중": 배당자산 / 전체 * 100,
        "월평균": 배당 / 12,
    }
