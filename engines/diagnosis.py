# 2. 연령대별 주식 비중 기준
# ==========================================================================
#  두 가지를 나란히 보여줍니다. 근거의 성격이 다릅니다.
#
#   (가) 100/110/120 − 나이  : 오래된 경험칙. 계산이 단순하고 널리 알려짐.
#                             다만 근거는 '경험' 이지 실증이 아닙니다.
#   (나) TDF 글라이드패스     : 실제 운용되는 상품의 나이별 주식비중.
#                             운용사마다 다르므로 아래는 '대표적인 형태' 입니다.
#                             실제 수치는 가입하신 TDF 설명서를 보세요.

공식_기준 = (100, 110, 120)


def 공식_주식비중(나이: int, 기준: int = 110) -> float:
    return max(0.0, min(100.0, float(기준 - 나이)))


# 은퇴까지 남은 햇수 → 대표적 TDF 주식 비중(%)
#  국내외 TDF 들이 대체로 이런 모양을 보입니다. 정확한 값은 상품마다 다릅니다.
_글라이드 = [(40, 85), (30, 80), (20, 70), (15, 62), (10, 52),
           (5, 45), (0, 38), (-5, 33), (-10, 30), (-99, 28)]


def TDF_주식비중(나이: int, 은퇴나이: int = 65) -> float:
    """대표적인 TDF 글라이드패스에서의 주식 비중(%)."""
    남은 = 은퇴나이 - 나이
    앞, 뒤 = None, None
    for 햇수, 비중 in _글라이드:
        if 남은 >= 햇수:
            뒤 = (햇수, 비중)
            break
        앞 = (햇수, 비중)
    if 뒤 is None:
        return float(_글라이드[-1][1])
    if 앞 is None:
        return float(뒤[1])
    # 두 점 사이를 직선으로 이어 부드럽게
    (h1, w1), (h2, w2) = 앞, 뒤
    if h1 == h2:
        return float(w2)
    비율 = (남은 - h2) / (h1 - h2)
    return float(w2 + (w1 - w2) * 비율)


def 연령_진단(나이: int, 현재_주식비중: float, 은퇴나이: int = 65) -> dict:
    """내 주식 비중을 두 기준과 비교합니다."""
    공식 = {k: 공식_주식비중(나이, k) for k in 공식_기준}
    tdf = TDF_주식비중(나이, 은퇴나이)
    기준값 = list(공식.values()) + [tdf]
    낮음, 높음 = min(기준값), max(기준값)

    if 현재_주식비중 < 낮음:
        위치 = "기준선보다 낮음"
    elif 현재_주식비중 > 높음:
        위치 = "기준선보다 높음"
    else:
        위치 = "기준선 범위 안"

    return {
        "나이": 나이, "은퇴나이": 은퇴나이,
        "은퇴까지": 은퇴나이 - 나이,
        "공식": 공식,
        "TDF": tdf,
        "기준범위": (낮음, 높음),
        "현재": 현재_주식비중,
        "위치": 위치,
        "TDF대비": 현재_주식비중 - tdf,
    }


def 위험자산_비중계산(종목들: list) -> dict:
    """주식성 자산과 안전자산을 나눕니다 (연령 기준과 비교하기 위해).

    주식성 : 국내주식, 해외주식, 리츠
    안전   : 채권, 현금성
    별도   : 원자재, 암호화폐 — 주식도 채권도 아니라 따로 셉니다.
             연령 기준(주식 vs 채권)에 그대로 넣으면 왜곡됩니다.
    """
    주식군 = ("국내주식", "해외주식", "리츠")
    안전군 = ("채권", "현금성")
    별도군 = ("원자재", "암호화폐")

    전체 = sum(s["평가액"] for s in 종목들) or 1.0
    주식 = sum(s["평가액"] for s in 종목들 if s.get("자산군") in 주식군)
    안전 = sum(s["평가액"] for s in 종목들 if s.get("자산군") in 안전군)
    별도 = sum(s["평가액"] for s in 종목들 if s.get("자산군") in 별도군)
    기타 = 전체 - 주식 - 안전 - 별도

    주식안전 = 주식 + 안전
    return {
        "전체": 전체,
        "주식성": 주식, "안전": 안전, "별도": 별도, "기타": 기타,
        "주식비중": 주식 / 전체 * 100,
        "안전비중": 안전 / 전체 * 100,
        "별도비중": 별도 / 전체 * 100,
        # 연령 기준과 비교할 때는 주식+안전 만으로 다시 계산하는 편이 맞습니다
        "주식비중_주식안전만": (주식 / 주식안전 * 100) if 주식안전 else 0.0,
    }


