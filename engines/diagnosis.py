# 1. 집중도 · 분산 지표
# ==========================================================================
def 허핀달지수(비중목록) -> float:
    """HHI = Σ(비중%)².  한 종목 100% 면 10,000, N개 균등이면 10,000/N."""
    return sum(float(w) ** 2 for w in 비중목록)


def 유효_종목수(비중목록) -> float:
    """10,000 / HHI.  '실질적으로 몇 종목에 나눠 담은 셈인가'.

    ※ 이게 가장 직관적인 분산 지표입니다.
      20종목을 들고 있어도 한 종목이 80% 면 유효 종목수는 1.5 에 불과합니다.
      "몇 개 들고 있나" 가 아니라 "얼마나 고르게 나눴나" 를 봅니다.
    """
    h = 허핀달지수(비중목록)
    return (10_000.0 / h) if h > 0 else 0.0


def 분산_진단(종목들: list, 합산=None) -> dict:
    """집중도·분산 지표를 한 번에 계산합니다.

    종목들 : portfolio.종목_계산 결과 목록
    합산   : portfolio.종목_합산 결과 (같은 종목을 계좌 합산한 것).
             주면 그걸 기준으로, 없으면 종목들 그대로 씁니다.
    """
    대상 = 합산 if 합산 is not None else 종목들
    전체 = sum(s["평가액"] for s in 대상) or 1.0
    비중 = sorted((s["평가액"] / 전체 * 100 for s in 대상), reverse=True)

    hhi = 허핀달지수(비중)
    유효 = 유효_종목수(비중)

    def 상위(n):
        return sum(비중[:n])

    자산군 = {}
    지역 = {"국내": 0.0, "해외": 0.0, "기타": 0.0}
    for s in 종목들:
        자산군[s.get("자산군") or "기타"] = (
            자산군.get(s.get("자산군") or "기타", 0.0) + s["평가액"])
        군 = s.get("자산군") or ""
        if 군 == "국내주식":
            지역["국내"] += s["평가액"]
        elif 군 == "해외주식":
            지역["해외"] += s["평가액"]
        else:
            지역["기타"] += s["평가액"]

    return {
        "종목수": len(대상),
        "HHI": hhi,
        "유효종목수": 유효,
        "최대비중": 비중[0] if 비중 else 0.0,
        "상위3": 상위(3),
        "상위5": 상위(5),
        "상위10": 상위(10),
        "자산군수": len([v for v in 자산군.values() if v > 0]),
        "자산군별": {k: v / 전체 * 100 for k, v in 자산군.items() if v > 0},
        "지역별": {k: v / 전체 * 100 for k, v in 지역.items() if v > 0},
        "전체": 전체,
    }


# 널리 쓰이는 기준선.
#  ※ 법칙이 아니라 '흔히 쓰는 경험칙' 입니다.
#    개별종목 위험이 대부분 사라지는 종목 수를 20~30개로 보는 연구가
#    여럿 있지만(Evans & Archer 1968, Statman 1987 등), 몇 개가 '정답' 인지는
#    연구마다 다릅니다. 아래 숫자는 그 범위를 참고한 기준선입니다.
기준선 = {
    "유효종목수": [(3, "매우 집중"), (7, "집중"), (15, "보통"), (25, "분산"),
              (float("inf"), "매우 분산")],
    "최대비중": [(10, "무난"), (20, "다소 큼"), (30, "큼"), (float("inf"), "매우 큼")],
    "상위5": [(40, "무난"), (60, "다소 큼"), (80, "큼"), (float("inf"), "매우 큼")],
}


def 등급(값, 항목: str) -> str:
    for 경계, 이름 in 기준선.get(항목, []):
        if 값 <= 경계:
            return 이름
    return ""


