"""
==========================================================================
적립식 투자 시뮬레이션 · 자산 추세 연장
==========================================================================
[이 파일이 하는 것과 하지 않는 것]

  합니다   — "연 몇 % 로 굴러간다고 **가정하면**" 얼마가 되는지 계산
  안 합니다 — "앞으로 몇 % 가 될 것이다" 라는 예측

  둘은 완전히 다릅니다. 앞의 것은 산수이고, 뒤의 것은 점입니다.
  그래서 수익률은 반드시 사용자가 넣는 **가정**으로만 받고,
  결과도 하나의 숫자가 아니라 **비관·기준·낙관 세 갈래**로 돌려줍니다.

[적립 주기를 월로 바꾸는 방법]

  미국 주식 소수점 모으기처럼 매일 사는 경우, 한 달에 몇 번 사는지가
  '거래일이냐 달력일이냐' 에 따라 다릅니다.

    매일(거래일) : 월 21회   — 미국 증시 연 252거래일 ÷ 12
    매일(달력일) : 월 30.44회 — 365.25 ÷ 12
    매주         : 월 4.345회 — 365.25 ÷ 7 ÷ 12
    매월         : 월 1회
    매년         : 월 1/12회

  이 배수는 어림입니다. 공휴일·휴장이 달마다 달라서 실제와 몇 회씩
  차이가 납니다. 긴 기간을 볼 때는 큰 문제가 아니지만, 한두 달을
  정확히 맞추려는 용도로는 쓰지 마세요.

[복리 방식]

  월 단위로 굴립니다. 납입은 **그 달 말**에 넣는다고 봅니다(보수적).
      잔액 = 잔액 × (1 + 월수익률) + 월납입액
  월수익률은 연수익률을 12로 나누지 않고 (1+연)^(1/12)−1 로 구합니다.
  단순히 12로 나누면 복리가 과대평가됩니다.
==========================================================================
"""

from datetime import date

모듈버전 = "2026-09-05"

# 적립 주기 → 한 달에 몇 번인지
주기_배수 = {
    "매일(거래일)": 252 / 12,      # 21.0
    "매일(달력일)": 365.25 / 12,   # 30.4375
    "매주": 365.25 / 7 / 12,       # 4.3452
    "격주": 365.25 / 14 / 12,
    "매월": 1.0,
    "분기": 1 / 3,
    "매년": 1 / 12,
}
주기_목록 = list(주기_배수)
통화_목록 = ["KRW", "USD"]

# 화면에서 고르는 기본 시나리오 (연 수익률 %)
#  ※ 특정 상품의 기대수익률이 아닙니다. 이야기를 나누기 위한 눈금일 뿐입니다.
기본_시나리오 = {"비관": 2.0, "기준": 6.0, "낙관": 10.0}


def _숫자(v, 기본=0.0) -> float:
    try:
        if v is None or v != v:      # None / NaN
            return 기본
        return float(v)
    except (TypeError, ValueError):
        return 기본


def 월납입_환산(주기: str, 금액, 통화: str = "KRW", 환율: float = 1390.0) -> float:
    """한 번에 넣는 금액을 '한 달에 넣는 원화' 로 바꿉니다.

    ※ 환율은 지금 값을 그대로 미래에 쓰는 것입니다. 앞으로의 환율은
      알 수 없으니, 해외 적립분은 이 가정에 그대로 좌우됩니다.
    """
    배수 = 주기_배수.get(str(주기 or "매월"), 1.0)
    금액 = _숫자(금액)
    원화 = 금액 * (_숫자(환율, 1390.0) if str(통화).upper() == "USD" else 1.0)
    return 원화 * 배수


def 계획_집계(계획들: list, 환율: float = 1390.0) -> dict:
    """적립 계획 표를 읽어 월 납입 합계를 냅니다.

    계획 한 줄 = {이름, 주기, 금액, 통화, 사용}
    """
    줄들, 합계 = [], 0.0
    for 행 in 계획들 or []:
        if 행.get("사용") is False:
            continue
        금액 = _숫자(행.get("금액"))
        if 금액 <= 0:
            continue
        주기 = str(행.get("주기") or "매월")
        통화 = str(행.get("통화") or "KRW").upper()
        월액 = 월납입_환산(주기, 금액, 통화, 환율)
        합계 += 월액
        줄들.append({
            "이름": str(행.get("이름") or "이름 없음"),
            "주기": 주기, "금액": 금액, "통화": 통화,
            "월환산": 월액,
            "연환산": 월액 * 12,
            "횟수": 주기_배수.get(주기, 1.0),
        })
    for r in 줄들:
        r["비중"] = (r["월환산"] / 합계 * 100) if 합계 else 0.0
    return {"줄들": 줄들, "월납입": 합계, "연납입": 합계 * 12, "줄수": len(줄들)}


def 월수익률(연수익률: float) -> float:
    """연 수익률을 월 복리율로. 12로 나누면 복리가 과대평가됩니다."""
    r = _숫자(연수익률) / 100.0
    if r <= -1:
        return -1.0
    return (1 + r) ** (1 / 12) - 1


def 적립_시뮬(현재잔액: float, 월납입: float, 개월수: int,
           연수익률: float, 시작일: date = None) -> list:
    """월별 잔액 흐름. [{개월, 날짜, 잔액, 누적납입, 운용수익}]

    0개월(지금)부터 개월수까지, 개월수+1개 줄을 돌려줍니다.
    """
    시작일 = 시작일 or date.today()
    m = 월수익률(연수익률)
    잔액 = _숫자(현재잔액)
    누적납입 = _숫자(현재잔액)
    월납입 = _숫자(월납입)
    개월수 = max(int(개월수 or 0), 0)

    흐름 = [{"개월": 0, "날짜": 시작일, "잔액": 잔액,
           "누적납입": 누적납입, "운용수익": 0.0}]
    for i in range(1, 개월수 + 1):
        잔액 = 잔액 * (1 + m) + 월납입
        누적납입 += 월납입
        # 날짜는 화면 표시용입니다. 월 단위라 일자는 시작일을 따릅니다.
        해 = 시작일.year + (시작일.month - 1 + i) // 12
        달 = (시작일.month - 1 + i) % 12 + 1
        try:
            그날 = date(해, 달, 시작일.day)
        except ValueError:                       # 31일이 없는 달
            import calendar
            그날 = date(해, 달, calendar.monthrange(해, 달)[1])
        흐름.append({"개월": i, "날짜": 그날, "잔액": 잔액,
                   "누적납입": 누적납입, "운용수익": 잔액 - 누적납입})
    return 흐름


def 시나리오_묶음(현재잔액: float, 월납입: float, 개월수: int,
              수익률들: dict = None, 시작일: date = None) -> dict:
    """비관·기준·낙관을 한 번에. {이름: {흐름, 총액, 총납입, 운용수익, ...}}"""
    수익률들 = 수익률들 or 기본_시나리오
    결과 = {}
    for 이름, 율 in 수익률들.items():
        흐름 = 적립_시뮬(현재잔액, 월납입, 개월수, 율, 시작일)
        끝 = 흐름[-1]
        결과[이름] = {
            "수익률": _숫자(율),
            "흐름": 흐름,
            "총액": 끝["잔액"],
            "총납입": 끝["누적납입"],
            "운용수익": 끝["운용수익"],
            "납입비중": (끝["누적납입"] / 끝["잔액"] * 100) if 끝["잔액"] else 0.0,
            "배수": (끝["잔액"] / 끝["누적납입"]) if 끝["누적납입"] else 0.0,
        }
    return 결과


def 목표_도달(현재잔액: float, 월납입: float, 목표액: float,
           연수익률: float, 최대개월: int = 720) -> dict:
    """목표 금액에 언제 닿는지. 못 닿으면 도달=False."""
    목표액 = _숫자(목표액)
    잔액 = _숫자(현재잔액)
    if 목표액 <= 잔액:
        return {"도달": True, "개월": 0, "년": 0.0, "잔액": 잔액}
    m = 월수익률(연수익률)
    월납입 = _숫자(월납입)
    if 월납입 <= 0 and m <= 0:
        return {"도달": False, "개월": None, "년": None, "잔액": 잔액}
    for i in range(1, int(최대개월) + 1):
        잔액 = 잔액 * (1 + m) + 월납입
        if 잔액 >= 목표액:
            return {"도달": True, "개월": i, "년": i / 12, "잔액": 잔액}
    return {"도달": False, "개월": None, "년": None, "잔액": 잔액}


def 실질가치(명목: float, 개월수: int, 물가: float = 2.0) -> float:
    """물가를 빼고 '지금 돈' 으로 환산합니다."""
    년 = max(int(개월수 or 0), 0) / 12
    return _숫자(명목) / ((1 + _숫자(물가) / 100) ** 년)


