# 내가 실제로 걸어온 속도
# ==========================================================================
#  가정이 말이 되는지 보려면, 지난 기록과 나란히 놓아야 합니다.
#  순자산 페이지의 기록([{날짜, 순자산}])을 그대로 받습니다.

def 과거_속도(기록: list, 최근개월: int = 12) -> dict:
    """기록에서 월평균 증가액과 연평균 증가율을 뽑습니다.

    ※ 이 증가액에는 **새로 넣은 돈과 시장 수익이 섞여 있습니다.**
      "월평균 300만원 늘었다" 를 "월 300만원씩 저축했다" 로 읽으면 안 됩니다.
    """
    from datetime import date as _d

    def 날짜로(v):
        if isinstance(v, _d):
            return v
        try:
            return _d.fromisoformat(str(v)[:10])
        except (ValueError, TypeError):
            return None

    점들 = []
    for r in 기록 or []:
        d = 날짜로(r.get("날짜"))
        v = r.get("순자산")
        if d is None or v is None:
            continue
        try:
            점들.append((d, float(v)))
        except (TypeError, ValueError):
            continue
    점들.sort(key=lambda x: x[0])

    if len(점들) < 2:
        return {"충분": False, "기록수": len(점들)}

    처음, 마지막 = 점들[0], 점들[-1]
    개월 = max((마지막[0] - 처음[0]).days / 30.44, 0.1)
    전체증감 = 마지막[1] - 처음[1]

    최근점들 = [p for p in 점들
             if (마지막[0] - p[0]).days <= 최근개월 * 31]
    최근월평균 = None
    if len(최근점들) >= 2:
        ㄱ, ㄴ = 최근점들[0], 최근점들[-1]
        ㄷ = max((ㄴ[0] - ㄱ[0]).days / 30.44, 0.1)
        최근월평균 = (ㄴ[1] - ㄱ[1]) / ㄷ

    년 = 개월 / 12
    cagr = (((마지막[1] / 처음[1]) ** (1 / 년) - 1) * 100
            if 처음[1] > 0 and 마지막[1] > 0 and 년 > 0 else None)

    return {
        "충분": True,
        "기록수": len(점들),
        "처음": 처음, "마지막": 마지막,
        "개월": 개월, "년": 년,
        "전체증감": 전체증감,
        "월평균증감": 전체증감 / 개월,
        "최근월평균": 최근월평균,
        "최근개월": 최근개월,
        "CAGR": cagr,
    }


def 추세_연장(과거: dict, 개월수: int, 시작일: date = None) -> list:
    """과거 월평균 증가액이 그대로 이어진다고 놓고 선을 긋습니다.

    ★ 이것은 **예측이 아닙니다.** '지난 속도가 그대로 반복된다면' 이라는
      가정 하나만으로 그은 선입니다. 그 가정이 맞을 근거는 없습니다.
      시장이 좋았던 구간이 들어 있으면 그 운까지 미래로 복사됩니다.
      화면에서는 반드시 점선과 '참고' 표시로 구분해 주세요.
    """
    if not (과거 or {}).get("충분"):
        return []
    시작일 = 시작일 or date.today()
    잔액 = 과거["마지막"][1]
    월증가 = (과거["최근월평균"] if 과거.get("최근월평균") is not None
            else 과거["월평균증감"])
    흐름 = [{"개월": 0, "날짜": 시작일, "잔액": 잔액}]
    for i in range(1, max(int(개월수 or 0), 0) + 1):
        잔액 += 월증가
        해 = 시작일.year + (시작일.month - 1 + i) // 12
        달 = (시작일.month - 1 + i) % 12 + 1
        try:
            그날 = date(해, 달, 시작일.day)
        except ValueError:
            import calendar
            그날 = date(해, 달, calendar.monthrange(해, 달)[1])
        흐름.append({"개월": i, "날짜": 그날, "잔액": 잔액})
    return 흐름


