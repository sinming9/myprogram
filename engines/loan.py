이자정산방식_목록 = ("원금분만", "전체잔액 일수정산")


def add_months(d: date, months: int) -> date:
    total = d.month - 1 + months
    year = d.year + total // 12
    month = total % 12 + 1
    day = min(d.day, calendar.monthrange(year, month)[1])
    return date(year, month, day)


def 영업일인가(d: date) -> bool:
    if d.weekday() >= 5:
        return False
    if (d.month, d.day) in 고정일_공휴일:
        return False
    if d in 음력_대체공휴일:
        return False
    return True


def 다음영업일(d: date) -> date:
    while not 영업일인가(d):
        d += timedelta(days=1)
    return d


def 금리_조회(회차, 스케줄):
    적용가능 = [s for s in 스케줄 if s["start_month"] <= 회차]
    return 적용가능[-1]["rate"]


def 이자계산(잔액, 연이율, 시작일, 종료일):
    """일수 기준 이자. 경과일이 0 이하면 0원."""
    경과일 = (종료일 - 시작일).days
    if 경과일 <= 0:
        return 0.0
    return 잔액 * (연이율 / 100) * 경과일 / 365


def 원리금균등_월상환금(잔액, 월이율, 남은개월):
    if 남은개월 <= 0:
        return 잔액
    if 월이율 == 0:
        return 잔액 / 남은개월
    return 잔액 * 월이율 / (1 - (1 + 월이율) ** (-남은개월))


def 상환금_고정시_남은개월(잔액, 월이율, 월상환금):
    if 잔액 <= 0:
        return 0
    if 월상환금 <= 0:
        return float("inf")
    if 월이율 == 0:
        return 잔액 / 월상환금
    비율 = 잔액 * 월이율 / 월상환금
    if 비율 >= 1:
        return float("inf")
    return -math.log(1 - 비율) / math.log(1 + 월이율)


def 중도상환수수료_계산(중도상환원금, 대출시작일, 상환일, 수수료율, 면제기간_개월):
    """국내 은행 일반적인 슬라이딩 방식 중도상환수수료.

    수수료 = 중도상환원금 x 수수료율(%) x 잔여면제기간일수 / 전체면제기간일수
    면제기간(보통 36개월)이 지났으면 0원.
    """
    if not 수수료율 or 수수료율 <= 0 or not 면제기간_개월 or 면제기간_개월 <= 0:
        return 0.0
    면제만료일 = add_months(대출시작일, int(면제기간_개월))
    전체일수 = (면제만료일 - 대출시작일).days
    잔여일수 = (면제만료일 - 상환일).days
    if 전체일수 <= 0 or 잔여일수 <= 0:
        return 0.0
    잔여일수 = min(잔여일수, 전체일수)
    return 중도상환원금 * (수수료율 / 100) * 잔여일수 / 전체일수


def _빈행():
    return {"구분": "", "회차": "-", "날짜": None, "적용금리": 0.0,
            "이자": 0, "원금": 0, "중도상환액": 0, "수수료": 0,
            "납입액": 0, "잔액": 0}


def 스케줄_생성(원금, 대출시작일, 첫납입일, 상환개월수, 금리스케줄, 중도상환목록,
             상환방식="원리금균등", 영업일_적용=True,
             이자정산방식="원금분만", 수수료율=0.0, 면제기간_개월=36):
    """전체 상환 스케줄을 계산. (결과리스트, 경고메시지리스트) 를 반환.

    중도상환목록의 각 항목:
        {"date": date, "amount": int, "method": "기간단축형"|"상환액감소형",
         "interest": int|None,   # 실제 명세서 이자를 알면 직접 입력 (없으면 None)
         "fee": int|None}        # 실제 수수료를 알면 직접 입력 (없으면 자동계산)
    """
    경고 = []
    금리스케줄 = sorted(금리스케줄, key=lambda x: x["start_month"])
    중도정렬 = sorted(중도상환목록, key=lambda x: x["date"])

    if 이자정산방식 not in 이자정산방식_목록:
        이자정산방식 = "원금분만"
    if not 금리스케줄 or 금리스케줄[0]["start_month"] != 1:
        raise ValueError("금리스케줄의 첫 항목은 1회차부터 시작해야 합니다.")
    if 첫납입일 <= 대출시작일:
        raise ValueError("첫납입일은 대출시작일보다 뒤여야 합니다.")
    for p in 중도정렬:
        if p["date"] < 대출시작일:
            raise ValueError(f"{p['date']} 중도상환 날짜가 대출시작일보다 앞설 수 없습니다.")
        if p["method"] not in ("기간단축형", "상환액감소형"):
            raise ValueError(f"{p['date']} 중도상환의 method 값이 올바르지 않습니다.")

    일수정산 = (이자정산방식 == "전체잔액 일수정산")

    잔액 = float(원금)
    목표종료회차 = 상환개월수
    현재금리 = 금리_조회(1, 금리스케줄)
    월이율 = 현재금리 / 100 / 12
    고정원금상환액 = None
    월상환금 = None

    if 상환방식 == "원리금균등":
        월상환금 = 원리금균등_월상환금(잔액, 월이율, 목표종료회차)
    else:
        고정원금상환액 = 잔액 / 목표종료회차

    결과 = []
    중도_idx = 0

    def _수수료(항목, 상환금):
        수동 = 항목.get("fee")
        if 수동 is not None:
            return float(수동)
        return 중도상환수수료_계산(상환금, 대출시작일, 항목["date"], 수수료율, 면제기간_개월)

    def _중도상환_적용(항목, 경과이자, 수수료, 라벨="중도상환"):
        """중도상환 1건을 잔액에 반영하고 결과행을 추가. (상환금액) 반환"""
        nonlocal 잔액
        중도금 = min(float(항목["amount"]), 잔액)
        잔액 -= 중도금
        결과.append({
            "구분": 라벨, "회차": "-", "날짜": 항목["date"], "적용금리": 현재금리,
            "이자": round(경과이자), "원금": 0, "중도상환액": round(중도금),
            "수수료": round(수수료),
            "납입액": round(경과이자 + 중도금 + 수수료), "잔액": round(max(잔액, 0)),
        })
        return 중도금

    def _재산정(항목, 현재회차, 이번회차_납입완료):
        """중도상환 후 기간단축형/상환액감소형 재산정.

        이번회차_납입완료=True  → 회차 납입이 끝난 뒤 상환 (남은 회차는 회차+1부터)
        이번회차_납입완료=False → 회차 납입 전에 상환 (남은 회차는 회차부터)
        """
        nonlocal 목표종료회차, 월상환금, 고정원금상환액
        if 잔액 <= 0.5:
            return
        기준회차 = 현재회차 if 이번회차_납입완료 else 현재회차 - 1

        if 항목["method"] == "기간단축형":
            # 월상환금(또는 고정원금상환액)은 그대로 두고 기간만 줄어듦
            if 상환방식 == "원리금균등":
                n = 상환금_고정시_남은개월(잔액, 월이율, 월상환금)
            else:
                n = 잔액 / 고정원금상환액 if 고정원금상환액 else float("inf")
            if n != float("inf"):
                목표종료회차 = 기준회차 + max(1, math.ceil(n))
        else:
            # 기간은 그대로 두고 월 납입액을 줄임
            남은회차 = 목표종료회차 - 기준회차
            if 남은회차 > 0:
                if 상환방식 == "원리금균등":
                    월상환금 = 원리금균등_월상환금(잔액, 월이율, 남은회차)
                else:
                    고정원금상환액 = 잔액 / 남은회차

    # ======================================================================
    # 0단계: 첫납입일 "이전"의 중도상환 처리 (+ 초기이자 구간 계산)
    #        - 예전 버전은 여기서 경과일이 음수가 되어 이자가 음수로 나왔습니다.
    # ======================================================================
    구간시작 = 대출시작일
    초기이자 = 0.0
    while (중도_idx < len(중도정렬) and 중도정렬[중도_idx]["date"] < 첫납입일
           and 잔액 > 0.5):
        항목 = 중도정렬[중도_idx]
        상환일 = 항목["date"]
        예정금 = min(float(항목["amount"]), 잔액)

        수동이자 = 항목.get("interest")
        if 일수정산:
            # 전체 잔액 기준으로 정산하고 정산일을 옮김 → 초기이자는 남은 구간만
            경과이자 = 수동이자 if 수동이자 is not None else 이자계산(잔액, 현재금리, 구간시작, 상환일)
            수수료 = _수수료(항목, 예정금)
            _중도상환_적용(항목, 경과이자, 수수료)
            구간시작 = 상환일
        else:
            # 상환하는 원금분에 대한 경과이자만 별도 정산.
            # 남은 잔액의 이자는 초기이자에서 구간별로 계산되므로 중복 없음.
            경과이자 = 수동이자 if 수동이자 is not None else 이자계산(예정금, 현재금리, 구간시작, 상환일)
            수수료 = _수수료(항목, 예정금)
            초기이자 += 이자계산(잔액 - 예정금, 현재금리, 구간시작, 상환일)
            _중도상환_적용(항목, 경과이자, 수수료)
            구간시작 = 상환일

        _재산정(항목, 1, 이번회차_납입완료=False)
        중도_idx += 1

    초기이자 += 이자계산(잔액, 현재금리, 구간시작, 첫납입일)
    결과.append({
        "구분": "초기이자", "회차": "-", "날짜": 첫납입일, "적용금리": 현재금리,
        "이자": round(초기이자), "원금": 0, "중도상환액": 0, "수수료": 0,
        "납입액": round(초기이자), "잔액": round(잔액),
    })
    결과.sort(key=lambda r: (r["날짜"], 0 if r["구분"] == "중도상환" else 1))

    # ======================================================================
    # 1단계: 정기납입 루프
    # ======================================================================
    회차 = 1
    직전정산일 = 첫납입일        # 실제 정산일 (전체잔액 일수정산 모드에서 사용)
    직전정산일_명목 = 첫납입일   # 약정일 기준 정산일. 은행은 이 날짜부터 일수를 셉니다.
                              #  ※ 실제 명세서로 검증: 영업일로 밀린 날짜가 아니라
                              #    명목 약정일부터 계산해야 은행 이자와 일치합니다.
    안전한도 = 상환개월수 * 3 + 24

    다음정기납입일_명목 = add_months(첫납입일, 1)
    다음정기납입일 = 다음영업일(다음정기납입일_명목) if 영업일_적용 else 다음정기납입일_명목

    while 잔액 > 0.5 and 회차 <= 안전한도:

        # ---- (a) 정기납입일 "이전"에 발생한 중도상환들 ----
        while 중도_idx < len(중도정렬) and 잔액 > 0.5:
            항목 = 중도정렬[중도_idx]
            상환일 = 항목["date"]
            # 명목일 또는 영업일조정일과 같은 날이면 "정기납입일 당일"로 처리 (아래 b단계)
            if 상환일 >= 다음정기납입일 or 상환일 in (다음정기납입일_명목, 다음정기납입일):
                break

            예정금 = min(float(항목["amount"]), 잔액)
            수동이자 = 항목.get("interest")
            if 수동이자 is not None:
                경과이자 = float(수동이자)
            elif 일수정산:
                경과이자 = 이자계산(잔액, 현재금리, 직전정산일, 상환일)
            else:
                경과이자 = 이자계산(예정금, 현재금리, 직전정산일_명목, 상환일)

            수수료 = _수수료(항목, 예정금)
            _중도상환_적용(항목, 경과이자, 수수료)
            if 일수정산:
                직전정산일 = 상환일
            _재산정(항목, 회차, 이번회차_납입완료=False)
            중도_idx += 1

        if 잔액 <= 0.5:
            break

        # ---- (b) 정기납입 ----
        이번금리 = 금리_조회(회차, 금리스케줄)
        if 이번금리 != 현재금리:
            현재금리 = 이번금리
            월이율 = 현재금리 / 100 / 12
            남은회차 = 목표종료회차 - 회차 + 1
            if 상환방식 == "원리금균등" and 남은회차 > 0:
                월상환금 = 원리금균등_월상환금(잔액, 월이율, 남은회차)

        if 일수정산:
            이자 = 이자계산(잔액, 현재금리, 직전정산일, 다음정기납입일)
        else:
            이자 = 잔액 * 월이율

        if 상환방식 == "원리금균등":
            원금상환 = 월상환금 - 이자
            if 원금상환 < 0:      # 이자가 월상환금보다 크면(금리 급등 등) 원금 미상환
                원금상환 = 0.0
        else:
            원금상환 = 고정원금상환액

        if 원금상환 >= 잔액:
            원금상환 = 잔액

        잔액 -= 원금상환
        직전정산일 = 다음정기납입일
        직전정산일_명목 = 다음정기납입일_명목

        # ---- (c) 정기납입일 당일의 중도상환 ----
        #   정기납입 이자는 위에서 이미 정산했습니다.
        #   단, 납입일이 주말 때문에 영업일로 밀렸다면 명목일 ~ 실제상환일 사이의
        #   하루/이틀치 이자는 별도로 붙습니다. (실제 은행 명세서와 일치)
        당일_중도금 = 0.0
        당일_수수료 = 0.0
        당일_추가이자 = 0.0
        while (중도_idx < len(중도정렬) and 잔액 > 0.5
               and 중도정렬[중도_idx]["date"] in (다음정기납입일_명목, 다음정기납입일)):
            항목 = 중도정렬[중도_idx]
            예정금 = min(float(항목["amount"]), 잔액)
            수동이자 = 항목.get("interest")
            if 수동이자 is not None:
                당일_추가이자 += float(수동이자)
            elif not 일수정산:
                당일_추가이자 += 이자계산(예정금, 현재금리, 다음정기납입일_명목, 항목["date"])
            당일_수수료 += _수수료(항목, 예정금)
            당일_중도금 += 예정금
            잔액 -= 예정금
            _재산정(항목, 회차, 이번회차_납입완료=True)
            중도_idx += 1

        총이자행 = 이자 + 당일_추가이자
        결과.append({
            "구분": "정기납입", "회차": 회차, "날짜": 다음정기납입일, "적용금리": 현재금리,
            "이자": round(총이자행), "원금": round(원금상환),
            "중도상환액": round(당일_중도금), "수수료": round(당일_수수료),
            "납입액": round(총이자행 + 원금상환 + 당일_중도금 + 당일_수수료),
            "잔액": round(max(잔액, 0)),
        })

        if 잔액 <= 0.5:
            break

        회차 += 1
        다음정기납입일_명목 = add_months(첫납입일, 회차)
        다음정기납입일 = 다음영업일(다음정기납입일_명목) if 영업일_적용 else 다음정기납입일_명목

    if 잔액 > 0.5:
        경고.append(f"{안전한도}회차까지 계산했지만 잔액이 완전히 상환되지 않았습니다 "
                   f"(남은 잔액: {잔액:,.0f}원). 금리·상환방식·중도상환 입력값을 확인해 주세요.")

    if 중도_idx < len(중도정렬):
        for p in 중도정렬[중도_idx:]:
            경고.append(f"{p['date']} 중도상환이 반영되지 않았습니다 (그 이전에 이미 대출이 상환 완료됨).")

    return 결과, 경고


def 요약(결과):
    """결과 리스트에서 합계 지표를 뽑아냅니다."""
    총이자 = sum(r["이자"] for r in 결과)
    총수수료 = sum(r.get("수수료", 0) for r in 결과)
    총중도상환 = sum(r["중도상환액"] for r in 결과)
    총정기원금 = sum(r["원금"] for r in 결과)
    개월수 = sum(1 for r in 결과 if r["구분"] == "정기납입")
    return {
        "총이자": 총이자,
        "총수수료": 총수수료,
        "총중도상환": 총중도상환,
        "총정기원금": 총정기원금,
        "총원금": 총정기원금 + 총중도상환,
        "총납입액": 총이자 + 총수수료 + 총정기원금 + 총중도상환,
        "상환개월수": 개월수,
        "완납일": 결과[-1]["날짜"] if 결과 else None,
    }
