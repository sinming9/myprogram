"""
==========================================================================
대출 상환 계산 엔진  (v3 - 중도상환 계산 오류 수정판)
==========================================================================

[v3에서 고친 것]

1) 중도상환 경과이자 이중 계상 오류  ★가장 큰 버그
   (이전) 경과이자 = "전체 잔액" x 연이율 x 경과일/365
          → 그런데 바로 다음 정기납입에서 다시 "한 달치 이자 전액"을 받아감.
            같은 기간의 이자를 두 번 받는 셈이라 총이자가 크게 부풀려졌습니다.
   (수정) 이자정산방식을 두 가지로 명확히 분리하고, 어느 쪽을 골라도
          같은 기간 이자가 두 번 계산되지 않게 했습니다.

     - "원금분만" (기본, 국내 은행 일반 관행)
         중도상환 시점: 상환하는 원금에 대한 경과이자만 정산
                        = 중도상환원금 x 연이율 x 경과일/365
         정기납입 시점: 남은 잔액에 대한 한 달치 이자 (기존과 동일)

     - "전체잔액 일수정산"
         중도상환 시점: 전체 잔액의 경과이자를 정산하고 정산일을 그날로 옮김
         정기납입 시점: 직전 정산일부터 실제 경과일수만큼만 이자 부과
                        (그래서 이중 계상이 발생하지 않음)

2) 첫납입일 이전 중도상환 시 이자가 음수로 나오던 오류
   (이전) 기준일이 첫납입일이라 경과일이 음수 → 이자 -1,150,685원 같은 값
   (수정) 첫납입일 이전 중도상환은 대출시작일부터 구간을 나눠 먼저 처리하고,
          초기이자도 구간별 실제 잔액으로 계산합니다. 표의 날짜 순서도 정상.

3) 같은 날 중도상환 2건 이상일 때 두 번째 건의 경과이자가 0으로 나오던 오류
   (수정) 경과이자 기준일은 "직전 이자정산일"로 고정 (중도상환 때문에 밀리지 않음)

4) 중도상환일이 정기납입일(명목일)과 같은 날인데 그 납입일이 주말이라 다음
   영업일로 밀린 경우, 중도상환이 "납입일 이전"으로 잡혀 이자가 따로 붙던 문제
   (수정) 명목일/영업일조정일 어느 쪽과 같아도 "정기납입일 당일"로 인식

5) 원금균등 + 기간단축형에서 목표종료회차가 갱신되지 않던 문제
   (수정) 남은 잔액 / 고정원금상환액 으로 목표종료회차를 다시 계산

6) [기능 추가] 중도상환수수료 계산
   수수료 = 중도상환원금 x 수수료율(%) x 잔여면제기간일수 / 전체면제기간일수
   (국내 은행 일반적인 슬라이딩 방식. 면제기간 경과 후에는 0원)
   총이자와 별도 항목으로 집계됩니다.
==========================================================================
"""

