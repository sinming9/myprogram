def _FRED조회(코드: str, api_key: str, 일수: int = 400, 시간제한: int = 15):
    """FRED 시계열. [(날짜, 값)] 오름차순."""
    시작 = date.today() - timedelta(days=일수)
    url = ("https://api.stlouisfed.org/fred/series/observations"
           f"?series_id={urllib.parse.quote(코드)}&api_key={api_key}"
           f"&file_type=json&observation_start={시작:%Y-%m-%d}")
    with urllib.request.urlopen(url, timeout=시간제한) as resp:
        js = json.loads(resp.read().decode("utf-8"))
    관측 = js.get("observations")
    if not 관측:
        raise ValueError(f"{코드}: 응답에 데이터가 없습니다")
    점들 = [(datetime.strptime(o["date"], "%Y-%m-%d").date(), float(o["value"]))
          for o in 관측 if o.get("value") not in (".", "", None)]
    if not 점들:
        raise ValueError(f"{코드}: 유효한 값이 없습니다")
    return 점들


def 곡선_조회(api_key: str = None, 만기목록=None, 일수: int = 400):
    """(자료, 출처, 기록) 반환.

    자료 = {"2년": [(날짜,값)...], "10년": [...], "30년": [...]}
    키가 없으면 빈 자료와 안내를 돌려줍니다. 예외를 던지지 않습니다.
    """
    만기목록 = 만기목록 or 기본_만기
    기록 = []
    if not api_key:
        기록.append("FRED API 키가 없어 자동 조회를 건너뜁니다.")
        return {}, "직접 입력", 기록

    자료 = {}
    for 이름 in 만기목록:
        코드 = 계열.get(이름)
        if not 코드:
            continue
        try:
            자료[이름] = _FRED조회(코드, api_key, 일수)
            기록.append(f"{이름}({코드}): {len(자료[이름])}개")
        except Exception as e:  # noqa: BLE001
            기록.append(f"{이름}({코드}) 실패: {e}")
    if not 자료:
        return {}, "직접 입력", 기록
    return 자료, "FRED (세인트루이스 연준)", 기록


def 최근값(자료: dict) -> dict:
    """각 만기의 가장 최근 값."""
    출력 = {}
    for 이름, 점들 in (자료 or {}).items():
        if 점들:
            출력[이름] = 점들[-1][1]
    return 출력


def 변화(자료: dict, 이름: str, 일수: int = 30):
    """일수 전 대비 변화(bp). 자료가 모자라면 None."""
    점들 = (자료 or {}).get(이름) or []
    if len(점들) < 2:
        return None
    끝날짜, 끝값 = 점들[-1]
    기준 = 끝날짜 - timedelta(days=일수)
    이전 = [v for d, v in 점들 if d <= 기준]
    if not 이전:
        이전 = [점들[0][1]]
    return (끝값 - 이전[-1]) * 100


