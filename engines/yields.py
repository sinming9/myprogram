def 곡선_모양(자료: dict, 단기="2년", 장기="30년", 일수: int = 30) -> dict:
    """최근 변화로 곡선 모양을 분류합니다."""
    단 = 변화(자료, 단기, 일수)
    장 = 변화(자료, 장기, 일수)
    if 단 is None or 장 is None:
        return {"유형": "판단 보류", "단기변화": 단, "장기변화": 장,
                "스프레드변화": None, **곡선_유형["판단 보류"]}

    스프 = 장 - 단
    if abs(스프) < 10:                      # 10bp 미만이면 판단 보류
        유형 = "판단 보류"
    elif 스프 > 0:
        유형 = "베어 스티프닝" if 장 > 0 else "불 스티프닝"
    else:
        유형 = "베어 플래트닝" if 단 > 0 else "불 플래트닝"

    return {"유형": 유형, "단기변화": 단, "장기변화": 장,
            "스프레드변화": 스프, **곡선_유형[유형]}


def 스프레드(값들: dict) -> dict:
    """장단기 차이(%p). 역전 여부도 함께."""
    출력 = {}
    for 이름, (긴, 짧) in {"10년−2년": ("10년", "2년"),
                        "30년−10년": ("30년", "10년"),
                        "30년−2년": ("30년", "2년")}.items():
        if 긴 in 값들 and 짧 in 값들:
            차 = 값들[긴] - 값들[짧]
            출력[이름] = {"값": 차, "역전": 차 < 0}
    return 출력


def 정책금리_대비(장기금리: float, 정책금리: float) -> dict:
    """장기금리가 정책금리보다 높은지 낮은지.

    장기 < 정책 이면 시장이 '앞으로 정책금리가 내려간다' 고 보는 쪽에 가깝습니다.
    장기 > 정책 이고 격차가 크면 기간 프리미엄이 붙어 있다는 뜻입니다.
    """
    차 = 장기금리 - 정책금리
    if 차 < -0.25:
        상태 = "장기금리가 정책금리보다 낮음 — 인하 기대가 반영된 모습"
    elif 차 > 1.0:
        상태 = "장기금리가 정책금리보다 크게 높음 — 기간 프리미엄이 두꺼움"
    else:
        상태 = "장기금리와 정책금리가 비슷한 수준"
    return {"차이": 차, "상태": 상태}


def 주담대_영향(십년금리: float) -> str:
    """10년물은 미국 주담대 금리에 직접 영향을 줍니다 (통상 1.5~2%p 가산)."""
    낮 = 십년금리 + 1.5
    높 = 십년금리 + 2.0
    return (f"10년물 {십년금리:.2f}% 기준으로 미국 30년 고정 주담대는 "
            f"대략 {낮:.1f}~{높:.1f}% 언저리가 됩니다. "
            "장기금리가 오르면 집을 사려는 사람의 이자 부담이 함께 오릅니다.")
