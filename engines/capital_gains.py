def 누진세액(과세표준: float) -> tuple:
    """(세액, 적용세율, 누진공제) 반환"""
    하한, 세율, 공제 = 기본세율표[0]
    for h, r, d in 기본세율표:
        if 과세표준 >= h:
            하한, 세율, 공제 = h, r, d
        else:
            break
    return max(0.0, 과세표준 * 세율 - 공제), 세율, 공제


# ---------------------------------------------------------------------------
# 장기보유특별공제
# ---------------------------------------------------------------------------
def 장특공_비율(보유연수: float, 거주연수: float, 일세대일주택: bool,
             중과대상: bool) -> tuple:
    """(공제율, 설명) 반환.

    표2 (1세대1주택 + 거주 2년 이상) : 보유 연 4%(최대 40%) + 거주 연 4%(최대 40%)
                                     = 최대 80%
    표1 (그 외)                     : 보유 연 2%, 3년 이상부터 최대 30%
    중과대상 주택                    : 공제 배제 (소득세법 §95②)
    """
    if 중과대상:
        return 0.0, "중과 대상 주택은 장기보유특별공제가 배제됩니다"
    if 보유연수 < 3:
        return 0.0, "보유 3년 미만은 장기보유특별공제 대상이 아닙니다"

    if 일세대일주택 and 거주연수 >= 2:
        보유율 = min(int(보유연수) * 0.04, 0.40)
        거주율 = min(int(거주연수) * 0.04, 0.40)
        전체 = 보유율 + 거주율
        설명 = (f"표2 적용 — 보유 {int(보유연수)}년 {보유율 * 100:.0f}% "
              f"+ 거주 {int(거주연수)}년 {거주율 * 100:.0f}% = {전체 * 100:.0f}%")
        return 전체, 설명

    비율 = min(int(보유연수) * 0.02, 0.30)
    이유 = ("1세대1주택이지만 거주 2년 미만이라 " if 일세대일주택 else "")
    설명 = f"표1 적용 — {이유}보유 {int(보유연수)}년 x 연 2% = {비율 * 100:.0f}%"
    return 비율, 설명


