모듈버전 = "2026-08-05"

# 다주택 중과 한시배제 종료일. 이 날짜 "이후" 양도분에 중과가 되살아납니다.
중과배제_종료일 = date(2026, 5, 9)

# 1세대1주택 비과세에 '거주 2년' 요건이 붙기 시작한 날 (8·2 대책)
#  · 이 날 "이후" 취득 + 취득 당시 조정대상지역  → 보유 2년 + 거주 2년 모두 필요
#  · 2017.8.2 이전 취득분                      → 보유 2년만으로 비과세
#  · 취득 후 조정지역에서 해제되었어도 취득 당시 기준으로 판단합니다
거주요건_시작일 = date(2017, 8, 3)

# 세법 적용 기준
