def 가격별_비교(입력: 양도입력, 가격목록: List[float]) -> List[dict]:
    출력 = []
    for 가격 in 가격목록:
        임시 = 양도입력(**{**입력.__dict__, "양도가액": 가격})
        r = 계산(임시)
        출력.append({
            "양도가액": 가격,
            "양도차익": r.양도차익,
            "총세액": r.총세액,
            "실수령액": r.실수령액,
            "유효세율": r.유효세율,
            "비과세": r.비과세인가,
        })
    return 출력


def 시점별_비교(입력: 양도입력, 날짜목록: List[date]) -> List[dict]:
    """언제 팔면 세금이 얼마인지. 보유·거주 기간이 늘어나는 효과를 봅니다."""
    출력 = []
    for d in 날짜목록:
        추가개월 = 개월차(입력.양도일, d) if d > 입력.양도일 else 0
        임시 = 양도입력(**{**입력.__dict__, "양도일": d,
                      "거주개월": 입력.거주개월 + (추가개월 if 입력.거주개월 else 0)})
        r = 계산(임시)
        출력.append({
            "양도일": d,
            "보유연수": r.보유연수,
            "장특공율": r.장특공율,
            "총세액": r.총세액,
            "실수령액": r.실수령액,
            "중과": r.중과대상,
        })
    return 출력
