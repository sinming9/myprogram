@dataclass
class 양도입력:
    취득일: date
    양도일: date
    취득가액: float
    양도가액: float
    필요경비: float = 0.0            # 취득세, 중개수수료, 자본적지출 등
    거주개월: int = 0                # 실제 거주한 개월 수
    주택수: int = 1                  # 양도 시점 세대 기준 보유 주택 수
    일시적2주택: bool = False        # 이사 등으로 일시 2주택인 경우

    # ★ 조정대상지역은 두 시점을 따로 봅니다 (판단 기준이 다릅니다)
    취득시_조정대상지역: bool = False   # 비과세 '거주 2년' 요건 판단용
    양도시_조정대상지역: bool = False   # 다주택 중과 판단용

    세법기준: str = "양도일 자동"


@dataclass
class 양도결과:
    보유연수: float = 0.0
    보유개월: int = 0
    거주연수: float = 0.0
    양도차익: float = 0.0
    비과세인가: bool = False
    비과세사유: str = ""
    과세대상차익: float = 0.0
    중과대상: bool = False
    중과폭: float = 0.0
    거주요건_필요: bool = False
    거주요건_설명: str = ""
    적용법령: str = ""
    장특공율: float = 0.0
    장특공액: float = 0.0
    장특공설명: str = ""
    양도소득금액: float = 0.0
    과세표준: float = 0.0
    적용세율: float = 0.0
    세율설명: str = ""
    산출세액: float = 0.0
    지방소득세: float = 0.0
    총세액: float = 0.0
    실수령액: float = 0.0
    유효세율: float = 0.0
    경고: List[str] = field(default_factory=list)


def 개월차(시작: date, 끝: date) -> int:
    개월 = (끝.year - 시작.year) * 12 + (끝.month - 시작.month)
    if 끝.day < 시작.day:
        개월 -= 1
    return max(개월, 0)


def 계산(입력: 양도입력) -> 양도결과:
    r = 양도결과()

    if 입력.양도일 <= 입력.취득일:
        r.경고.append("양도일이 취득일보다 앞서거나 같습니다.")
        return r

    r.보유개월 = 개월차(입력.취득일, 입력.양도일)
    r.보유연수 = r.보유개월 / 12
    r.거주연수 = 입력.거주개월 / 12

    # ---- 1. 양도차익 ----
    r.양도차익 = 입력.양도가액 - 입력.취득가액 - 입력.필요경비
    if r.양도차익 <= 0:
        r.비과세인가 = True
        r.비과세사유 = "양도차익이 없습니다 (손실이면 세금 없음)"
        r.실수령액 = 입력.양도가액
        return r

    # ---- 2. 1세대1주택 비과세 판정 ----
    실질1주택 = (입력.주택수 == 1) or 입력.일시적2주택
    보유2년 = r.보유개월 >= 24
    거주2년 = 입력.거주개월 >= 24

    # ★ 거주요건은 '취득 당시' 조정대상지역 + 취득일 기준으로 판단합니다.
    #   양도 당시 해제되었더라도 취득 당시 조정지역이었으면 거주 2년이 필요합니다.
    #   (근거: 2017.8.2 8·2 대책, 소득세법 시행령 §154①)
    r.거주요건_필요 = (입력.취득시_조정대상지역
                  and 입력.취득일 >= 거주요건_시작일)
    if r.거주요건_필요:
        r.거주요건_설명 = (f"취득일 {입력.취득일} 이 {거주요건_시작일} 이후이고 "
                     "취득 당시 조정대상지역 → 보유 2년 + 거주 2년 모두 필요")
    elif 입력.취득시_조정대상지역:
        r.거주요건_설명 = (f"취득 당시 조정대상지역이지만 {거주요건_시작일} 이전 취득분 "
                     "→ 거주요건 없음 (보유 2년만)")
    else:
        r.거주요건_설명 = "취득 당시 조정대상지역이 아님 → 거주요건 없음 (보유 2년만)"

    거주요건 = (거주2년 if r.거주요건_필요 else True)

    if 실질1주택 and 보유2년 and 거주요건:
        if 입력.양도가액 <= 비과세_기준:
            r.비과세인가 = True
            r.비과세사유 = (f"1세대1주택 · 양도가액 {입력.양도가액 / 1e8:.2f}억 ≤ 12억 "
                       f"→ 전액 비과세")
            r.실수령액 = 입력.양도가액
            return r
        # 고가주택: 12억 초과분만 과세
        r.과세대상차익 = r.양도차익 * (입력.양도가액 - 비과세_기준) / 입력.양도가액
        r.비과세사유 = (f"1세대1주택 고가주택 — 12억 초과분만 과세 "
                   f"(양도차익 {r.양도차익 / 1e8:.2f}억 x "
                   f"{(입력.양도가액 - 비과세_기준) / 1e8:.2f}억 / "
                   f"{입력.양도가액 / 1e8:.2f}억)")
        일세대일주택_공제 = True
    else:
        r.과세대상차익 = r.양도차익
        일세대일주택_공제 = False
        if 실질1주택 and not 보유2년:
            r.비과세사유 = "1주택이지만 보유 2년 미만이라 비과세를 받지 못합니다"
        elif 실질1주택 and not 거주요건:
            r.비과세사유 = ("취득 당시 조정대상지역 1주택인데 거주 2년 미만이라 "
                       "비과세를 받지 못합니다")
        else:
            r.비과세사유 = f"{입력.주택수}주택자 — 비과세 대상이 아닙니다"

    # ---- 3. 중과 판정 ----
    기준 = 입력.세법기준 if 입력.세법기준 in 세법기준_목록 else "양도일 자동"
    if 기준 == "현재 법령":
        중과부활 = True
        r.적용법령 = "현재(중과 부활 후) 법령 고정"
    elif 기준 == "중과 배제 가정":
        중과부활 = False
        r.적용법령 = "중과가 다시 유예된다고 가정"
    else:
        중과부활 = 입력.양도일 > 중과배제_종료일
        r.적용법령 = (f"양도일 {입력.양도일} 기준 — "
                  + ("중과 적용 기간" if 중과부활 else
                     f"중과 배제 기간 (~{중과배제_종료일})"))

    if (입력.양도시_조정대상지역 and not 실질1주택 and 중과부활
            and r.보유개월 >= 24):
        if 입력.주택수 >= 3:
            r.중과대상, r.중과폭 = True, 0.30
        elif 입력.주택수 == 2:
            r.중과대상, r.중과폭 = True, 0.20

    if 입력.양도시_조정대상지역 and not 실질1주택 and not 중과부활:
        if 기준 == "중과 배제 가정":
            r.경고.append(
                "중과가 다시 유예된다는 가정입니다. 확정된 것이 아니니 "
                "'양도일 자동' 이나 '현재 법령' 으로도 비교해 보세요.")
        else:
            r.경고.append(
                f"{중과배제_종료일} 까지는 중과 배제 기간이었습니다. "
                "그 이후 양도분은 중과가 다시 적용됩니다.")

    # ---- 4. 장기보유특별공제 ----
    r.장특공율, r.장특공설명 = 장특공_비율(
        r.보유연수, r.거주연수, 일세대일주택_공제, r.중과대상)
    r.장특공액 = r.과세대상차익 * r.장특공율

    # ---- 5. 과세표준 ----
    r.양도소득금액 = max(0.0, r.과세대상차익 - r.장특공액)
    r.과세표준 = max(0.0, r.양도소득금액 - 기본공제)

    # ---- 6. 세율 ----
    if r.보유개월 < 12:
        r.적용세율 = 0.70
        r.산출세액 = r.과세표준 * 0.70
        r.세율설명 = "보유 1년 미만 → 단기 중과세율 70%"
    elif r.보유개월 < 24:
        r.적용세율 = 0.60
        r.산출세액 = r.과세표준 * 0.60
        r.세율설명 = "보유 1~2년 → 단기 중과세율 60%"
    else:
        기본세액, 세율, 공제 = 누진세액(r.과세표준)
        if r.중과대상:
            r.적용세율 = 세율 + r.중과폭
            r.산출세액 = r.과세표준 * r.적용세율 - 공제
            r.세율설명 = (f"기본세율 {세율 * 100:.0f}% + 중과 "
                      f"{r.중과폭 * 100:.0f}%p = {r.적용세율 * 100:.0f}% "
                      f"(조정대상지역 {입력.주택수}주택)")
        else:
            r.적용세율 = 세율
            r.산출세액 = 기본세액
            r.세율설명 = f"기본세율 {세율 * 100:.0f}% (누진공제 {공제:,.0f}원)"

    r.산출세액 = max(0.0, r.산출세액)
    r.지방소득세 = r.산출세액 * 지방소득세율
    r.총세액 = r.산출세액 + r.지방소득세
    r.실수령액 = 입력.양도가액 - r.총세액
    r.유효세율 = (r.총세액 / r.양도차익 * 100) if r.양도차익 else 0.0

    # ---- 참고 경고 ----
    if r.보유개월 < 24:
        r.경고.append("보유 2년 미만은 단기 중과세율(60~70%)이 적용돼 세금이 매우 큽니다.")
    if 일세대일주택_공제 and 입력.거주개월 < 24:
        r.경고.append(
            "1세대1주택이라도 거주 2년 이상이어야 장기보유특별공제 표2(최대 80%)를 "
            "받습니다. 지금은 표1(최대 30%)이 적용됩니다.")
    if 입력.양도일 > date.today() and 기준 == "양도일 자동":
        r.경고.append(
            "미래 시점 계산입니다. 그때의 세법은 지금과 다를 수 있습니다. "
            "'세법 적용 기준' 을 바꿔서 여러 경우를 비교해 보세요.")
    if 입력.필요경비 == 0:
        r.경고.append(
            "필요경비가 0원입니다. 취득세·중개수수료·법무비용·자본적지출(샷시, 확장 등)은 "
            "영수증이 있으면 공제받을 수 있습니다.")
    return r


