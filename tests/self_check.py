def 확인(설명, 조건):
    """조건은 값이어도 되고, 함수(lambda)여도 됩니다.

    ★ 함수로 넘기면 여기 안에서 평가합니다. 조건식이 KeyError 같은 걸
      던져도 파일 전체가 죽지 않고 '실패' 로 기록된 뒤 다음 검사로
      넘어갑니다. 예전에는 조건을 호출 전에 평가해서, 하나가 터지면
      ::error:: 안내 없이 끝나고 뒤 검사가 전부 묻혔습니다.
    """
    try:
        결과 = 조건() if callable(조건) else 조건
    except Exception as e:                                   # noqa: BLE001
        틀린것.append(f"{설명} — 검사 중 예외 {type(e).__name__}: {e}")
        print(f"  예외  {설명}: {type(e).__name__}: {e}")
        return
    if 결과 is True:
        print(f"  ok    {설명}")
    else:
        틀린것.append(설명)
        print(f"  실패  {설명}")


