def 태그_멀쩡(본문):
    """텔레그램 HTML 모드가 받아 주는 모양인지.

    · 쓰는 태그는 b, i 뿐이고 짝이 맞아야 합니다.
    · & 는 전부 &amp; &lt; &gt; 중 하나로 시작해야 합니다(반 토막 금지).
    """
    # ★ '<' 는 반드시 <b> </b> <i> </i> 의 시작이어야 합니다. 예전 검사는
    #   글자로 시작하는 태그만 봐서 '< 평균' 같은 맨 '<' 를 놓쳤고, 그게
    #   2026-10-20 아침 발송을 텔레그램 400 으로 실패시켰습니다.
    for m in re.finditer("<", 본문):
        if not re.match(r"</?[bi]>", 본문[m.start():]):
            return False
    if ">" in re.sub(r"</?[bi]>", "", 본문):
        return False
    for t in ("b", "i"):
        if 본문.count(f"<{t}>") != 본문.count(f"</{t}>"):
            return False
    return all(re.match(r"&(amp|lt|gt);", 본문[m.start():])
               for m in re.finditer("&", 본문))


