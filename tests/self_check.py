def 발송_흐름():
    """기록 먼저 → 전송 → 확실히 실패하면 되돌리기. 가짜 Gist·텔레그램으로."""
    MB = _러너()
    import json as _json

    def 돌리기(전송결과, 쓰기결과, 시세있음=True):
        저장소 = {"기록": {"스냅샷": [], "마지막발송일": "2026-09-18"}}
        보낸 = []
        쓰기순서 = list(쓰기결과)

        def 가짜_읽기(토큰, 아이디):
            return ({MB.자산파일: {"종목": 종목들, "목표": {}},
                     MB.기록파일: _json.loads(_json.dumps(저장소["기록"]))},
                    None)

        def 가짜_쓰기(토큰, 아이디, 이름, 자료, **_):
            좋음 = 쓰기순서.pop(0) if 쓰기순서 else True
            if 좋음:
                저장소["기록"] = _json.loads(_json.dumps(자료, default=str))
            return (True, None) if 좋음 else (False, "Gist 502")

        def 가짜_보내기(토큰, 방, 글, **_):
            보낸.append(글)
            return 전송결과

        # ★ MB.TG·MB.PF·MB.FX 는 다른 절이 쓰는 진짜 모듈과 같은 것입니다.
        #   직접 바꾸면 뒤 절까지 가짜가 새어 나가므로, 러너 모듈 안의
        #   이름만 가짜 모듈로 갈아 끼웁니다.
        import types
        MB.gist_읽기, MB.gist_쓰기 = 가짜_읽기, 가짜_쓰기
        MB.TG = types.SimpleNamespace(보내기=가짜_보내기)
        가짜PF = types.ModuleType("가짜PF")
        가짜PF.__dict__.update(PF.__dict__)
        # 모든 줄이 시세를 받은 것처럼 (못 받으면 '믿을 수 없는 날' 이 되어
        # 기록을 안 남기는데, 그건 아래 따로 검사합니다)
