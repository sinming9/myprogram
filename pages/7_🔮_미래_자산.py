def _설정_정리(불러온: dict) -> dict:
    설정 = {k: (list(v) if isinstance(v, list) else v)
          for k, v in 기본설정.items()}
    설정.update({k: v for k, v in (불러온 or {}).items() if k in 기본설정})
    if not 설정.get("계획"):
        설정["계획"] = FU.기본_계획()
    return 설정


