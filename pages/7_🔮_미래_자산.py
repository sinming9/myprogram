def _표원본_바꾸기(행들):
    # data_editor 는 [원본 + 편집내역] 으로 결과를 만듭니다. 편집 결과를 다시
    # 원본에 넣으면 편집내역이 두 번 적용되어 줄이 사라집니다. 원본은 여기서만
    # 바꾸고, 바꿀 때는 표를 새로 만듭니다(버전 올림).
    st.session_state["미래_표원본"] = [dict(r) for r in (행들 or [])]
    st.session_state["미래_표버전"] += 1


def _설정_적용(데이터):
    새것 = _설정_정리(데이터 or {})
    st.session_state["미래_설정"] = 새것
    _표원본_바꾸기(새것.get("계획"))


