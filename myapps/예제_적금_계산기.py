"""
==========================================================================
예제 - 적금 만기 계산기
==========================================================================
myapps/ 폴더에 넣는 프로그램의 본보기입니다.
이 파일을 복사해서 이름만 바꾸고 내용을 고치면 새 프로그램이 됩니다.

필요한 것은 딱 두 가지입니다.
  1) 제목 / 아이콘 / 설명  (없어도 되지만 있으면 목록이 예쁩니다)
  2) 실행() 함수            (여기 안에 화면을 그립니다)
==========================================================================
"""

import streamlit as st

# 저장·표시 도우미를 쓰고 싶으면 app_kit 에서 가져오면 됩니다.
from app_kit import 불러오기, 원, 저장, 카드_줄

제목 = "적금 만기 계산기"
아이콘 = "🐷"
설명 = "매월 일정액을 넣을 때 만기에 받는 금액과 세후 이자를 계산합니다."

저장키 = "적금계산기"          # data/ 폴더에 저장할 때 쓸 이름
이자소득세율 = 15.4            # 이자소득세 14% + 지방소득세 1.4%


def 만기계산(월납입액, 개월수, 연이율, 세율=이자소득세율):
    """정기적금(단리) 만기 계산.

    이자 = 월납입액 x (연이율/12) x (n x (n+1) / 2)
      → 첫 달 넣은 돈은 n개월, 마지막 달 넣은 돈은 1개월 이자가 붙기 때문입니다.
    """
    원금 = 월납입액 * 개월수
    이자 = 월납입액 * (연이율 / 100 / 12) * (개월수 * (개월수 + 1) / 2)
    세금 = 이자 * 세율 / 100
    return {
        "원금": 원금,
        "이자": 이자,
        "세금": 세금,
        "세후이자": 이자 - 세금,
        "만기금액": 원금 + 이자 - 세금,
        "실효수익률": ((이자 - 세금) / 원금 * 100) if 원금 else 0.0,
    }


def 실행():
    저장값 = 불러오기(저장키, {"월납입액": 500_000, "개월수": 12, "연이율": 3.5})

    c1, c2, c3 = st.columns(3)
    월납입액 = c1.number_input("월 납입액(원)", min_value=0, step=100_000,
                          value=int(저장값.get("월납입액", 500_000)))
    개월수 = c2.number_input("기간(개월)", min_value=1, max_value=120, step=1,
                         value=int(저장값.get("개월수", 12)))
    연이율 = c3.number_input("연이율(%)", min_value=0.0, step=0.05, format="%.2f",
                         value=float(저장값.get("연이율", 3.5)))

    결과 = 만기계산(월납입액, 개월수, 연이율)

    카드_줄([
        ("만기 수령액", 원(결과["만기금액"]), f"{개월수}개월 뒤"),
        ("납입 원금", 원(결과["원금"]), f"월 {월납입액:,}원 x {개월수}회"),
        ("세후 이자", 원(결과["세후이자"]), f"세전 {결과['이자']:,.0f}원"),
        ("이자소득세", 원(결과["세금"]), f"{이자소득세율}%"),
    ], 열수=2)

    st.caption(f"원금 대비 실효 수익률 {결과['실효수익률']:.2f}% "
               f"(단리 기준, 예금자보호·우대금리 조건은 반영하지 않음)")

    if st.button("💾 이 조건 저장", width="stretch"):
        성공, 메시지 = 저장(저장키, {"월납입액": int(월납입액), "개월수": int(개월수),
                             "연이율": float(연이율)})
        (st.success if 성공 else st.error)(메시지)

    with st.expander("📈 기간을 늘리면 어떻게 되나"):
        import pandas as pd
        표 = pd.DataFrame([
            {"기간(개월)": n,
             "납입 원금": 만기계산(월납입액, n, 연이율)["원금"],
             "세후 이자": 만기계산(월납입액, n, 연이율)["세후이자"],
             "만기 수령액": 만기계산(월납입액, n, 연이율)["만기금액"]}
            for n in (6, 12, 24, 36, 60)
        ])
        st.dataframe(
            표.style.format({"납입 원금": "{:,.0f}", "세후 이자": "{:,.0f}",
                            "만기 수령액": "{:,.0f}"}),
            width="stretch", hide_index=True,
        )
